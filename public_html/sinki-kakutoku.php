	<section id="m05">
		<h2 class="midashi03-2">WEBでは不可能な6つの革命的機能</h2>
		<h3 id="m05-1" class="midashi05">1．匿名訪問者を「実名顧客」へ100%転換</h3>
		<p>QRコードからのアクセス者は企業名・担当者名まで100%特定可能。従来DMでは0.8%しか捕捉できなかったアクセス者を全員リスト化</p>

		<h3 id="m05-2" class="midashi05">2．購買意欲を「見える化」し営業効率を最大化</h3>
		<p>「料金表」「競合比較ページ」閲覧者をリアルタイム通知。購買意欲の高い「今すぐ客」に絞った効率的営業が可能</p>

		<h3 id="m05-3" class="midashi05">3．「1クリック申込」でCVRを最大8倍改善</h3>
		<p>入力項目ゼロの1クリック申込フォーム。顧客名が表示され、ボタンを押すだけで完了。CVR4～8倍改善の実績</p>

		<h3 id="m05-4" class="midashi05">4．Cookie規制時代も安心の未来対応技術</h3>
		<p>Cookie不使用の独自特許技術。GDPR・個人情報保護法に完全対応。将来の規制強化にも影響を受けない安定したデータ収集</p>

		<h3 id="m05-5" class="midashi05">5．競合が模倣困難な独自マーケティング資産を構築</h3>
