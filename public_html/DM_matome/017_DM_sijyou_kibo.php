	<section id="m02">
		<h2 class="midashi02">DM市場の現状と変化</h2>
		<p><img src="/images/DM_matome/DM_sijyou_kibo_sub13.jpg" width="1980" height="1320" alt="DM市場の現状と変化" decoding="async" loading="lazy"></p>
		<p>先ほど解説した数値を参考にしながら、DM市場の現状と変化についてより詳しく解説していきます。</p>

		<h3 id="m02-1" class="midashi03">DM市場の現状</h3>
		<p>先ほど示したデータのとおり、郵便物（クロネコDM便や飛脚ゆうメール便などを含む）の総数は近年減少傾向にあります。</p>
		<p>それでは、なぜ郵便物は減少しているのでしょうか。郵便物の減少は、さまざまな書類が電子化したことが考えられます。見積書や請求書、契約書のデータ化、決済のシステム化、カタログのPDF化、電子帳簿保存法などが起因し、紙媒体でのやりとりをする必要がなくなっているのです。</p>
		<p>また、近年では年賀状など、個人間で郵便物をやりとりする習慣も薄れてきており、こういった時代背景から、郵便物の取扱量が減少してきているといえます。</p>

		<h3 id="m02-2" class="midashi03">DM取扱量の変化</h3>
		<p>DMを含む郵便物すべての取扱量は統計データから把握可能ですが、DMのみの取扱量の統計データがないため、DM取扱量の変化を正確に把握することはできません。</p>
		<p>しかしながら、弊社が長年ファイリングしてきた手元にあるDMの量は10年前の約半分程度に減少しています。また、弊社の顧客やコンサルタントに聞いたところでは、９割減～２割減との返答が得られています。</p>
		<p>郵便物の総量と同様に、DMの取扱量も減少しており、DMを発行する際は市場の縮小にも考慮する必要があるといえます。</p>

		<h3 id="m02-3" class="midashi03">どのような業種のDMが減ったのか？</h3>
		<p>では、実際にどのような業種のDMが減少しているのでしょうか。弊社がまとめたところによると、以下の内容のDMで、取扱量が減少しています。</p>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>展示会関連</li>
			<li>セミナー案内</li>
			<li>ホテル・旅館</li>
			<li>コンサート</li>
			<li>飲食店</li>
			<li>旅行関連</li>
		</ul>
		</div>
		<p>新型コロナウイルス感染症の影響を受けた飲食業やイベント業関連のDMが減少していると思われます。この傾向からは回復しつつありますが、やはりコロナ禍の影響は色濃いため、コロナ禍前の水準まで取扱量が増えるには時間がかかると考えてください。</p>

		<h3 id="m02-4" class="midashi03">どのような業種のDMが増えたのか？</h3>
		<p>郵便物やDM全体の取扱量が減少するなかで、DMの取扱量が増えている業種もあります。新型コロナウイルス感染症の影響を受け、需要が高まった業種ではDMの取扱量も増えているのです。</p>
		<p>例えば、以下のような業種でDMの取扱量が増えています。</p>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>食料品</li>
			<li>一般雑貨</li>
			<li>通販関連</li>
			<li>コロナ関連</li>
			<li>融資関連</li>
			<li>M&amp;A</li>
		</ul>
		</div>

		<h3 id="m02-5" class="midashi03">DMで売上が伸びているか？</h3>
		<p>DMからの売上の伸びは二極化が進んでおり、業種や業態、DM作成レベルなどによって売上の増減は大きく左右されています。</p>
		<p>DMから撤退している会社の共通点とDMを10年以上出し続けている会社の特徴を以下にまとめました。自社の特徴と比べてみてください。</p>

		<div class="box box--yellow">
		<p class="midashi05-2">DMから撤退している会社の共通点</p>
		<ul class="list-circle">
			<li>初めてDMに取り組む</li>
			<li>新規顧客獲得のためにDMを発送している</li>
			<li>DMテストを行っていない</li>
			<li>インターネットの費用対効果が落ちていることを理由に、深く考察せずDMを発行している</li>
			<li>メーカーが作ったパンフレットのようなDMを発行している</li>
			<li>社長がDMに関わっていない</li>
			<li>DMの市場調査を行わず、とりあえずDMを発行している</li>
		</ul>
		</div>

		<h3 id="m02-6" class="midashi03">DMを10年以上出し続けている会社の共通点</h3>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>既存顧客を中心にDMを発行している</li>
			<li>DMテストを行っている</li>
			<li>ニュースレターを出している</li>
			<li>売込みの少ないDMを発行している</li>
			<li>DMとインターネットを連携させている</li>
			<li>会社全体でDMの情報が共有されている</li>
			<li>DMやニュースレターの担当者がいる</li>
			<li>部分的に外注を使っている</li>
		</ul>
		</div>
	</section>


	<section id="m03">
		<h2 class="midashi02">今後どうなる？ DM市場の今後の動向</h2>
		<p><img src="/images/DM_matome/DM_sijyou_kibo_sub14.jpg" width="1920" height="1320" alt="DM市場の今後" decoding="async" loading="lazy"></p>
		<p>DM市場は今後どのように変化していくのでしょうか。日本ダイレクトメール協会の「DMメディア実態調査2021」をもとにDMの閲読率の変化を考察していきます。</p>
		<p>同調査によると、DMの閲読率は全体で67.6％、本人宛で79.5％となっています。公的機関からのDMや、クーポンやプレゼント、キャンペーンなどの顧客にメリットのあるDMの閲読率が高いのが特徴です。</p>
		<p><img src="/images/DM_matome/DM_sijyou_kibo_sub10.png" width="1500" height="600" alt="DMの閲読率は全体で67.6％、本人宛で79.5" decoding="async" loading="lazy"></p>

		<p>また、DMの閲読後、商品についてインターネットで調べたり資料請求したりするなど、なんらかの行動に移したのは21％です。20代、30代の若年層に高い行動喚起効果が見られることから、若い世代への効果には今後も期待できます。</p>
		<p>全体をとおして、DMの閲読率、行動喚起率は高く、DMは販促媒体として優れていることがわかります。コロナ禍で対面での販促が制限されるなか、DMの価値も高まっています。QRコードを添付するなどしてインターネット広告と連携する手段もとられており、今後もDMの役割は増えていくと予想されます。</p>
		<p>近年、多くの企業がインターネットでの販促に力を入れたことで、インターネットへの新規参入障壁が高くなっています。競合が増えたことから、今までインターネットでの売上が好調だった企業も売上が減少する傾向が見られ、インターネットでの販促効果の今後は安定的とは言い切れません。また、インターネットへの新規参入も今までよりも難しくなってきています。</p>
		<p>一方、DMは、一度うまくいくDMを作れば、その効果が長続きするのが特徴です。業種や業態にもよりますが、これまでDMで成果を出していた企業は、依然としてDMで成果を上げている傾向が見られます。</p>
		<p>また、近年ではDMで顧客に興味を持ってもらい、自社ホームページへ誘導する方法が効果を上げており、今後もこの形で顧客との接触をはかるケースが増えることが見込まれます。さらに、ニュースレターによって顧客との接触頻度を増やし、関係性を強化するケースも根強い効果を持っています。</p>

		<p><a href="https://www.dm110.jp/DM_matome/Newsletter_kouka/"><img src="/images/DM_matome/btn_Newsletter_kouka.png" width="760" height="126" alt="ニュースレターの効果はこちら" decoding="async" loading="lazy"></a></p>
		<p><a href="https://www.dm110.jp/DM_matome/Newsletter_tukurikata/"><img src="/images/DM_matome/btn_Newsletter_tukurikata.png" width="760" height="126" alt="ニュースレターの作り方はこちら" decoding="async" loading="lazy"></a></p>

		<p>今後も、これらのようなさまざまな手段によって顧客との接触頻度を増やし、顧客との関係性を強めることがますます重要になっていくと考えています。</p>
	</section>


	<section id="m04">
		<h2 class="midashi02">取り入れるべき「DM差別化」の戦略</h2>
		<p><img src="/images/DM_matome/DM_sijyou_kibo_sub15.jpg" width="1920" height="1322" alt="" decoding="async" loading="lazy"></p>
		<p>変化していく市場のなかで成果を出すには、DMを差別化する戦略が欠かせません。差別化の戦略をパターン別に解説します。</p>

		<h3 id="m04-1" class="midashi03">別媒体と差別化するなら「特徴を活かす」</h3>
		<p>別媒体と差別化したいなら、まずは競合となる媒体にはどのようなものがあるのかを知っておく必要があります。DMの競合となる媒体は以下のとおりです。</p>
		<h4 class="midashi05">インターネット系媒体</h4>
		<p>ホームページ、PPC広告（Yahoo！JAPAN／Googleでの検索連動型広告・コンテンツ連動型広告）、メルマガ、ブログ、メール、バナー広告、Twitter、Facebook、インターネット動画広告、インターネットテレビ広告など</p>
		<h4 class="midashi05">リアル媒体</h4>
		<p>新聞、雑誌、テレビ、ラジオダイレクトメール、ニュースレター、FAXDM、チラシ、看板、ポスター、カタログなど</p>

		<p class="u-mt50">媒体によって特徴は異なり、性別や年齢、環境、業種、収入、環境など得意な分野も異なります。自社の業種業態や既存顧客の属性などを考慮し、どの媒体を使うのかを検討してください。</p>
		<p>また、近年では多くの人がインターネットを介して情報を入手しています。個人情報を入力せずに手軽に利用できるインターネットは、情報収集の手段として非常に優れているからです。</p>
