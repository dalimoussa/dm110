	<section id="m01">
		<h2 class="midashi02">DMの市場規模はどのくらい？</h2>
		<p>DMの市場規模を、株式会社電通が公表している「2021年 日本の広告費」などの統計データをもとに、さまざまな観点から解説します。</p>

		<h3 id="m01-1" class="midashi03">日本の総広告費</h3>
		<p>株式会社電通の「2021年 日本の広告費」によると、2021年の日本の総広告費は6兆7,998億円となっています。</p>
		<p><img src="/images/DM_matome/DM_sijyou_kibo_sub1.png" width="1500" height="1030" alt="日本の総広告費推移" decoding="async" loading="lazy"></p>
		<p>総広告費は2019年まで年々上昇傾向にありましたが、2020年は新型コロナウイルス感染症の影響を受け、大幅に落ち込みました。2021年にはコロナ禍の影響が緩和したことから、媒体によって差はありますが、市場は落ち込みから回復しつつあります。</p>

		<h3 id="m01-2" class="midashi03">DMの広告費</h3>
		<p>広告媒体はマスコミ4媒体広告、インターネット広告、プロモーションメディア広告に大別されます。それぞれ該当する媒体は以下のとおりです。</p>
		<h4 class="midashi05">マスコミ4媒体広告</h4><p>新聞、雑誌、ラジオ、テレビメディア（地上波テレビ・衛星メディア関連）</p>
		<h4 class="midashi05">インターネット広告</h4><p>新聞デジタル、雑誌デジタル、ラジオデジタル、テレビメディアデジタル、物販系ECプラットフォーム広告費、インターネット広告制作費</p>
		<h4 class="midashi05">プロモーションメディア広告</h4><p>屋外、交通、折込、DM、フリーペーパー、POP、イベントほか</p>
		<p class="u-mt30">「2021年 日本の広告費」によると、プロモーションメディア広告に分類されるDMの広告費は、2021年で3,446億円（前年比104.7％　構成比5.1％）です。2019年は3,642億円、2020年は3,290億円となっており、他媒体同様に新型コロナウイルス感染症の影響を受けながらも、市場は回復していることがわかります。</p>
		<p class="u-mb0">DMや折込広告の回復傾向は他媒体よりも比較的良好だと見られており、これは、コロナによる在宅消費がDMや折込広告の需要を高めたためと考えられます。</p>
		<p class="u-mt0"><img src="/images/DM_matome/DM_sijyou_kibo_sub2.png" width="1500" height="1280" alt="日本の総広告費表" decoding="async" loading="lazy"></p>
		<p><img src="/images/DM_matome/DM_sijyou_kibo_sub3.png" width="1500" height="1100" alt="媒体別構成比" decoding="async" loading="lazy"></p>

		<h3 id="m01-3" class="midashi03">【ヤマト運輸】クロネコDM便の件数</h3>
		<p>続いて、ヤマト運輸、佐川急便、日本郵政の発送実績から、それぞれの発送状況の特徴を解説します。まずはヤマト運輸の小口貨物取扱実績から発送数を見ていきます。</p>
		<p>クロネコDM便の件数は2021年度で約8億件となっており、総件数は年々減少傾向にあります。</p>
		<p><img src="/images/DM_matome/DM_sijyou_kibo_sub4.png" width="1500" height="1000" alt="ヤマト運輸 小口貨物取扱実績の推移" decoding="async" loading="lazy"></p>

		<h3 id="m01-4" class="midashi03">【佐川急便】発送物の件数</h3>
		<p>佐川急便の発送物は2021年で1,423百万個となっており、そのうち1,369百万個が飛脚宅配便となっています。2021年度の発送物数は2020年度よりも増えています。</p>
		<p><img src="/images/DM_matome/DM_sijyou_kibo_sub5.png" width="1500" height="1000" alt="佐川急便 取扱個数実績（デリバリー事業）の推移" decoding="async" loading="lazy"></p>

		<h3 id="m01-5" class="midashi03">メール便・ゆうメール便・国内郵便の推移</h3>
		<p>一般社団法人日本ダイレクトメール協会の「広告メディアとしてのDMの現状」によると、メール便の数量は減少しているものの、ゆうメールは順調に数量が増えています。</p>
		<p><img src="/images/DM_matome/DM_sijyou_kibo_sub6.png" width="1500" height="1000" alt="メール便・ゆうメール便・国内郵便の推移" decoding="async" loading="lazy"></p>
		<p class="u-mt30">また、総務省が発表する「令和4年版 情報通信白書」によると、2021年度の総引受郵便物等物数は、191億9,273万通・個となっています。総引受郵便物等物数は年々減少傾向にあり、特に郵便物は近年大きく数量を減らしています。</p>
		<p><img src="/images/DM_matome/DM_sijyou_kibo_sub7.png" width="1500" height="1000" alt="総引受郵便物等物数の推移" decoding="async" loading="lazy"></p>

		<h3 id="m01-6" class="midashi03">【日本郵便】年賀葉書の発行枚数</h3>
		<p>日本郵政が発行した年賀葉書の発行枚数は2022年用で約19億枚となっています。発行数は年々数億枚単位で減少しており、この傾向は今後も続くと予想されます。</p>
		<p><img src="/images/DM_matome/DM_sijyou_kibo_sub8.png" width="1500" height="1000" alt="年賀葉書の発行枚数の推移" decoding="async" loading="lazy"></p>

		<h3 id="m01-7" class="midashi03">【日本郵便】元旦に配達された年賀郵便物数</h3>
		<p>元旦に配達された年賀状は、2021年で1,179百万通となっており、年々数量は減少傾向になっています。今後も減少傾向は続くと見られています。</p>
		<p><img src="/images/DM_matome/DM_sijyou_kibo_sub9.png" width="1500" height="1000" alt="年賀郵便物元旦配達物数の推移" decoding="async" loading="lazy"></p>
