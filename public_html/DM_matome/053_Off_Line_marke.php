		<h2 class="midashi02">自社ホームページを見てもらうためのDM活用術</h2>
		<p>インターネットからの集客には、おもにSEOやWeb広告、SNS関連があります。しかし、ノウハウが体系化されつつある現在、インターネット関連での集客で採算が取れる状態に持っていくのは厳しくなっています。</p>
		<p>SEOとWeb広告を例に挙げて、インターネット集客が厳しいとされる理由を紹介します。</p>

		<h3 id="m07-1" class="midashi04">SEO（検索した言葉で10位以内に入る）の場合</h3>
		<ul class="list-decimal u-ml30">
			<li>検索結果の1ページ目10位以内に入るのには時間がかかる。キーワードにもよるが、上位表示には1年かかると言われている</li>
			<li>上位表示にかかるコストが高い</li>
			<li>GoogleやYahoo!の判断基準が変わると、順位が大きく変動する</li>
			<li>継続的にお客様のためになる情報を発信し続けないと順位が落ちる</li>
			<li>比較サイトや上場企業が上位に表示される傾向にある</li>
		</ul>

		<h3 id="m07-2" class="midashi04">Web広告（GoogleやYahoo!広告）の場合</h3>
		<ul class="list-decimal u-ml30">
			<li>自社で広告を管理するのはハードルが高い</li>
			<li>広告代行会社に依頼しても成果が出にくい</li>
			<li>設定方法やガイドラインが常に進化しているため、自社内でWeb広告担当者を育成しづらい</li>
			<li>競合他社のレベルが上がり採算を合わすのが難しい</li>
		</ul>

		<p class="u-mt50">SEOとWeb広告、どちらにおいてもその目的は自社のホームページをお客様に見てもらうことです。インターネット集客が難しくなっている今、増えている手法はDMによるホームページへの誘導です。</p>
		<p>従来のように、DMを見てもらい商品やサービスを買ってもらうことを目的とした内容にするのではなく、ホームページに来てもらうことを目的にした内容でDMを作成し、発送します。特にBtoBでは良い効果が出ていますが、BtoCの場合でも顧客情報があれば効果も出やすくなっています。</p>
