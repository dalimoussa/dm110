	<section id="m01">
		<h2 class="midashi02">オフラインマーケティングとはインターネットを介さずに行うマーケティングのこと</h2>
		<p>オフラインマーケティングは、インターネットを介さない（＝オフラインの）マーケティング活動の総称です。オフラインマーケティングの代表的な手法には、次のようなものがあります。</p>

		<div class="box box--yellow">
		<ul class="list-circle">
			<li>テレビCM</li>
			<li>新聞広告</li>
			<li>DM</li>
			<li>FAXDM</li>
			<li>チラシ</li>
			<li>雑誌広告</li>
			<li>テレアポ</li>
			<li>イベント（セミナー・展示会など）</li>
		</ul>
		</div>

		<p class="u-mt50">反対に、インターネットを介した（＝オンラインの）マーケティング活動は、オンラインマーケティングと呼びます。代表例は、次のとおりです。</p>

		<div class="box box--yellow">
		<ul class="list-circle">
			<li>Webサイト</li>
			<li>SNS</li>
			<li>メール</li>
		</ul>
		</div>
	</section>


	<section id="m02">
		<h2 class="midashi02">オフラインマーケティングの重要性</h2>
		<p><img src="/images/DM_matome/Off_Line_marke_sub1.jpg" width="1980" height="1320" alt="Offline" decoding="async" loading="lazy"></p>
		<p>近年は、インターネットのみで集客することが厳しくなっています。</p>
		<p>例えば、メルマガの開封率は、以前と比べて下がっています。これは、多くの企業がメルマガを発行するようになったことや、迷惑メールが蔓延していることなどにより、メルマガそのものを受け付けない消費者が増えているのが原因です。</p>
		<p>Webサイトによる集客に関しては、GoogleやYahoo!JAPANといった検索エンジンが、どの企業のサイトを検索上位に表示させるか決めています。そのため、検索エンジン側の仕様変更により、売上が突然減るリスクを抱えています。</p>
		<p>このような背景から、オフラインマーケティングが見直されているのです。</p>
		<p>また、どの媒体で商品・サービスを探すか、どの媒体で購入に至るかは、人によって異なります。オンラインマーケティングだけを実施している場合、DMやチラシなどのオフラインマーケティングと相性が良いターゲットの集客機会を逃してしまいます。</p>
		<p>できるだけ多くの集客経路を確保するには、オフラインマーケティングが欠かせません。</p>
	</section>


	<section id="m03">
		<h2 class="midashi02">オフラインマーケティングのメリット・デメリット</h2>
		<p><img src="/images/DM_matome/Off_Line_marke_sub2.jpg" width="1980" height="1320" alt="オフラインマーケティングのメリット・デメリット" decoding="async" loading="lazy"></p>
		<p>ここでは、オンラインマーケティングとも比較しつつ、オフラインマーケティングのメリット・デメリットを紹介します。</p>

		<h3 id="m03-1" class="midashi03">オフラインマーケティングのメリット</h3>
		<p>WebサイトやSNSなどのオンラインマーケティングは、ユーザーが検索する意思を持っていないと情報を届けられないことも多く、集客までに時間がかかりがちです。</p>
		<p>一方、オフラインマーケティングは、短期間で確実に顧客へ情報を届けられるのがメリットです。特に、DMやチラシなどの紙の情報は保存性が高く、手元に置いて読み返してもらいやすい手法です。</p>
		<p>また、多くのユーザーへ一律に情報発信する手法が多いオンライン施策と異なり、オフライン施策では、顧客ごとに対応・提案を最適化しやすいのが特徴です。顧客と直接的なコミュニケーションを取ることもできます。</p>
		<p>その他、オンラインマーケティングと比較したオフラインマーケティングのメリットは、次のとおりです。</p>

		<div class="box box--yellow">
		<ul class="list-circle">
			<li>他社に真似されにくい<br>（オンライン施策は誰でも内容を見ることができるため真似されやすい）</li>
			<li>情報の信頼性が高い<br>（オンライン施策はインターネット上に情報があふれていることから信頼されにくい）</li>
		</ul>
		</div>

		<h3 id="m03-2" class="midashi03">オフラインマーケティングのデメリット</h3>
		<p>オフラインマーケティングでは、オンラインマーケティングのように「不特定多数に一斉にアプローチする」ことはできません。したがって、アプローチできる人数が限られること、手間や新規顧客の獲得コストがかかりやすいことがデメリットです。</p>
		<p>また、オンラインマーケティングは分析ツールが豊富なため、成約に至るまでの効果を測定しやすいのに対し、オフラインマーケティングは詳細な分析が難しい場合があります。</p>
		<p>紙の情報に関しては、あとから間違いに気付いても修正できない点も弱みです。</p>
	</section>


	<section id="m04">
		<h2 class="midashi02">オフラインマーケティングでの代表的な施策方法8つ</h2>
		<p>ここでは、オフラインマーケティングの代表的な施策方法の特徴を紹介します。</p>
		<p><img src="/images/DM_matome/Off_Line_marke_sub3.png" width="1500" height="940" alt="オフラインマーケティングの代表的な施策方法" decoding="async" loading="lazy"></p>

		<h3 id="m04-1" class="midashi03 u-mt0">1.テレビ・新聞</h3>
		<p>テレビCMや新聞広告は、信頼性が高いのが特徴です。</p>
		<p>特にテレビCMは、テレビに映ること自体が価値となり、ブランド力が向上します。また、ほかの施策と異なり、動画で配信できるのもメリットです。</p>
		<p>一方の新聞広告には、地域を限定した施策を実施できる強みがあります。</p>
		<p>ただし、テレビCM・新聞広告による施策は、メリットばかりではありません。テレビCMは、実施コストが高い、宣伝時間が限られるといったデメリットがあります。</p>
		<p>新聞も、毎日または定期的に新たなものが発行されるため、繰り返し見てもらいにくく、効果は一時的です。加えて、新聞そのものの購読者数は減少傾向にあります。</p>

		<h3 id="m04-2" class="midashi03">2.DM</h3>
		<p>不特定多数への宣伝となるテレビCM・新聞広告に対し、DMは宛先を限定できるメリットがあります。既存顧客や法人をターゲットとしたDMの効果は大きく、長く続きます。</p>
		<p>また、試供品や割引券などの特典（オファー）をつけることで、開封率や閲読率の向上が可能です。</p>
		<p>加えて、DMは発送したあと、どのくらいの反応があったのか、効果を測定しやすい施策です。測定した数値から分析と改善を行うことで、DMの効果を最大化できます。</p>
		<p>一方で、効果的なDMの内容を考えるのには時間がかかります。加えて、郵送する場合、個人情報の厳重な対策が必要です。</p>
		<p>DMについて、さらに詳しくは以下の記事をご覧ください。</p>
		<p><a href="https://www.dm110.jp/DM_matome/DM_toha/"><img src="/images/DM_matome/btn_DM_toha.png" width="760" height="126" alt="DMの詳細はこちら" decoding="async" loading="lazy"></a></p>

		<h3 id="m04-3" class="midashi03">3.FAXDM</h3>
		<p>FAXDMは、印刷・発送コストがかからないため、高いコストパフォーマンスを発揮します。また、FAXDMは相手の手元に届いた時点で中身がわかる状態になっているため、開封率は非常に高い点が強みです。</p>
		<p>ただし、白黒印刷となるFAXDMは、写真やイラストなどをきれいに印刷できないため、訴求効果が下がるデメリットがあります。また、受信者側のインクや用紙を消費するため、クレームに発展する恐れがあります。</p>
		<p>郵送のDMと同様に、個人情報の取り扱いにも注意が必要です。</p>

		<h3 id="m04-4" class="midashi03">4.ニュースレター</h3>
		<p>自社発行の新聞であるニュースレターは、顧客とのコミュニケーションツールの一つです。商品の「売り込み」ではなく、会社や商品に「興味を持ってもらう」ための施策で活用されます。</p>
		<p>そのため、顧客の役に立つ情報や、会社に親しみを持てる内容を織り込むのが特徴です。顧客にメリットがある内容のため、何度発行しても嫌がられにくく、顧客との接触機会を増やせます。</p>
		<p>ただし、商品を売り込むものではないことから、ニュースレターがどのように売上に寄与したかなど、効果を確認しにくいデメリットもあります。</p>
		<p>ニュースレターの効果や作り方などについては、以下の記事をご覧ください。</p>
		<p><a href="https://www.dm110.jp/DM_matome/Newsletter_kouka/"><img src="/images/DM_matome/btn_Newsletter_kouka.png" width="760" height="126" alt="ニュースレターの効果はこちら" decoding="async" loading="lazy"></a></p>
		<p><a href="https://www.dm110.jp/DM_matome/Newsletter_tukurikata/"><img src="/images/DM_matome/btn_Newsletter_tukurikata2.png" width="760" height="126" alt="ニュースレター作り方はこちら" decoding="async" loading="lazy"></a></p>

		<h3 id="m04-5" class="midashi03">5.チラシ</h3>
		<p>チラシは配布エリアを限定できるため、地域密着型の施策で効果を発揮します。特に、60歳以上をターゲットとする施策では、費用対効果を期待できます。ただし、地域性が影響するため、テストを実施して判断してください。</p>
		<p>店舗や駅前に設置したり、ポストに投函したりしたチラシは見てもらいやすく、場所もとらないため、保存されやすい点もメリットです。</p>
		<p>一方、チラシのデメリットとしては、効果が持続しにくいこと、他社に内容を真似されやすいことなどが挙げられます。</p>
		<p>チラシのさらに詳しいメリット・デメリットやDMとの違いなどについては、以下の記事をご覧ください。</p>
		<p><a href="https://www.dm110.jp/DM_matome/DM_tirasi/"><img src="/images/DM_matome/btn_DM_tirasi.png" width="760" height="126" alt="DMとチラシの違いはこちら" decoding="async" loading="lazy"></a></p>

		<h3 id="m04-6" class="midashi03">6.雑誌</h3>
		<p>雑誌ごとにターゲットが定まっているため、自社の広告をどの雑誌に掲載するかによって顧客を絞り込めます。広告の掲載回数が増えるほど、認知度も高まりやすいのが特徴です。</p>
		<p>また、どの雑誌に・何回掲載されたかといった履歴は、今後のアピールポイントになります。</p>
		<p>ただし、広告は思い立ってすぐに掲載できるものではなく、審査や修正手続きに時間がかかります。また、掲載できる情報量も限られるため、自由度は低めです。</p>

		<h3 id="m04-7" class="midashi03">7.テレアポ</h3>
		<p>テレアポ（電話営業）は、見込み客を発見・掘り起こし、営業につなぐために使われます。</p>
		<p>見込み客と1対1で直接話せるため、即効性があります。また、電話番号さえわかれば良いため、BtoBにも使いやすい手法です。</p>
		<p>テレアポのデメリットは、しつこいとかえってイメージを下げるリスクがあることや、クレームが発生するリスクがあることです。状況によっては、担当者の精神的な負担も懸念されます。</p>

		<h3 id="m04-8" class="midashi03">8.イベント</h3>
		<p>自社セミナーや展示会などのイベントにて、担当者が商品についてPRするのも有効な施策です。特に、確度の高い見込み客を取り込みたいときに適しています。</p>
		<p>また、すぐに成約に至らなくても、多くの来場者にパンフレットなどを持ち帰ってもらえれば認知拡大が見込めます。</p>
		<p>しかし、イベントの規模によっては費用がかさんでしまうため、費用対効果をきちんと考えなければなりません。</p>
	</section>


	<section id="m05">
		<h2 class="midashi02">オフラインマーケティング成功の秘訣は3つ</h2>
		<p>オフラインマーケティングを実施する際は、次の3つのポイントを心がけてください。</p>

		<h3 id="m05-1" class="midashi03">ターゲットや目的に合わせて効果的な手法を選ぶ</h3>
		<p>ターゲットや目的により、適切な手法は異なります。</p>
		<p>例えば、認知度を高める目的ならマス広告が有効ですが、そのなかでも若年層をターゲットとするなら雑誌広告を選びます。</p>
		<p>また、自社イベントの来場者のデータなどから、ターゲットの氏名・住所・ニーズなどがわかっているなら、DMを活用するのがおすすめです。</p>

		<h3 id="m05-2" class="midashi03">メッセージやデザインを工夫する</h3>
		<p>オフラインマーケティングは、ユーザーにとって「入り口」の役割になることも多くあります。</p>
		<p>そのため、相手の心に響く、不安を解消するメッセージ（キャッチコピー）やデザインを考えてください。具体的な数字を盛り込み、印象に残すのも効果的です。</p>
		<p>効果的なキャッチコピーの作り方については、以下の記事をご覧ください。</p>
		<p><a href="https://www.dm110.jp/DM_matome/catch_copy/"><img src="/images/DM_matome/btn_catch_copy2.png" width="760" height="126" alt="キャッチコピーの作り方はこちら" decoding="async" loading="lazy"></a></p>

		<h3 id="m05-3" class="midashi03">効果を測定する</h3>
		<p>オフラインマーケティングの実施後は、効果測定が重要です。効果を測定することで、活動が成功したかどうかを客観的に把握できます。</p>
		<p>効果測定時の指標の例として、DMでは「LTV（Life Time Value：ライフタイムバリュー）」、折込チラシでは「反響数」「反響率」が挙げられます。</p>
		<p>DMの効果測定の指標である「LTV」とは、「自社と取引を始めた顧客が、生涯でどれくらいの利益をもたらしてくれるか（＝顧客生涯価値）」を示すものです。1年間の総粗利を、同じく1年間に購買活動をした顧客数で割ると、顧客1人当たりのLTVがわかります。</p>
	</section>


	<section id="m06">
		<h2 class="midashi02">オフライン×オンラインを組み合わせよう</h2>
		<p>ここまで、オフラインマーケティングについて解説してきましたが、オフライン施策とオンライン施策を融合すれば、さらにマーケティングの成果を高められます。</p>
		<p>昨今はインターネットの普及により、顧客の検索能力・情報収集力が上がっています。よって、オフライン施策とオンライン施策を組み合わせた次のようなマーケティングが可能です。</p>
		<p>例1：DMやチラシに記載した2次元バーコードからWebサイトへ誘導する<br>
			例2：スマートフォンアプリからオーダー可能にすることで、実店舗で並ばずに買えるようにする</p>
