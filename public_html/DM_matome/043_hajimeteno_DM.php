	<section id="m01">
		<h2 class="midashi02">ダイレクトメール（DM）とは</h2>
		<p>ダイレクトメール（DM）とは、商品やサービスを訴求するために送る印刷物のことです。商品・サービスのターゲットなどによって、個人宛てに送る場合もあれば、法人宛てに送る場合もあります。</p>
		<p>ダイレクトメール（DM）のおもなメリット・デメリットは、次のとおりです。</p>

		<table class="table01">
			<tr><th>メリット</th>
				<td><ul class="list-circle">
					<li>宛先を限定し、ターゲットに直接情報を届けられる</li>
					<li>媒体を工夫すれば、一度にたくさんの情報を届けられる</li>
					<li>テストによるPDCAを回しやすい</li>
					<li>他社に内容を真似されにくい</li>
					<li>既存顧客向けのもの・法人向けのものは費用対効果が良い</li>
				</ul></td></tr>
			<tr><th class="nowrap">デメリット</th>
				<td><ul class="list-circle">
					<li>一定のコストがかかる</li>
					<li>時間や手間がかかる</li>
					<li>開封してもらうための工夫が求められる</li>
					<li>個人情報を適切に管理する体制を整えなければならない</li>
					<li>新規顧客向けのものは費用対効果が悪い</li>
				</ul></td></tr>
		</table>
	</section>


	<section id="m02">
		<h2 class="midashi02">ダイレクトメール（DM）全体の流れ</h2>
		<p>DMの顧客リストの作成方法を3つ紹介します。</p>
		<p><img src="/images/DM_matome/hajimeteno_DM_sub1.png" width="1500" height="1000" alt="ダイレクトメール（DM）全体の流れ" decoding="async" loading="lazy"></p>

		<h3 id="m02-1" class="midashi03">STEP1：ターゲットの明確化</h3>
		<p>ダイレクトメール（DM）で最も重要といえるのが、「誰に情報を届けるのか」を明確にすることです。</p>
		<p>なるべく多くの人に見てもらいたいからといって、ターゲットを決めずに作成すると、内容が薄くなり期待する効果が得られません。</p>

		<h3 id="m02-2" class="midashi03">STEP2：ダイレクトメール（DM）に入れる要素の検討</h3>
		<p>ダイレクトメール（DM）には、申込用紙・返信用封筒・パンフレット・オファー（特典・プレゼント）などを同封できます。ターゲットが決まったら、何を同封すべきかを考えてください。</p>
		<p>なかでも、割引特典や商品に関するプレゼントなどのオファーは、開封率に影響すると考えられるため、ターゲットや自社の商品・サービスを踏まえて選択します。</p>
		<p>ダイレクトメール（DM）に同封する内容物について、詳しくは以下の記事をご覧ください。</p>
		<p><a href="https://www.dm110.jp/DM_matome/DM_fuunyuubutsu/"><img src="/images/DM_matome/btn_DM_fuunyuubutsu.png" width="760" height="126" alt="DMの内容物の詳細はこちら" decoding="async" loading="lazy"></a></p>

		<h3 id="m02-3" class="midashi03">STEP3：内製・外注を検討</h3>
		<p>ダイレクトメール（DM）の作成・発送には、時間や手間がかかります。自社のリソースだけでは、すべての工程に対応するのは難しいかもしれません。</p>
		<p>そこで、デザインや印刷、発送などの工程を外注すれば、効率的に進められます。ただし、外注する工程が増えるほどかかる費用も高額になるため、どのくらいの範囲を外注するかは、内製する場合のコストと比較して判断してください。</p>
		<p>ダイレクトメール（DM）の外注について、詳しくは以下の記事をご覧ください。</p>
		<p><a href="https://www.dm110.jp/DM_matome/sakusei_gaityuu/"><img src="/images/DM_matome/btn_sakusei_gaityuu.png" width="760" height="126" alt="DM作成の外注に関してはこちら" decoding="async" loading="lazy"></a></p>

		<h3 id="m02-4" class="midashi03">STEP4：ダイレクトメール（DM）の内容の決定</h3>
		<p>ダイレクトメール（DM）の効果を最大化するためには、内容の工夫が求められます。</p>
		<p>内容のなかでも特にポイントとなるのが、キャッチコピーです。キャッチコピーがターゲットに刺さらないと、読み進めてもらえません。キャッチコピーを考える際は、次のポイントを意識してください。</p>
		<ul class="list-circle u-ml30">
			<li>顧客との対話からヒントを得る</li>
			<li>小学生でもわかるような簡単な表現にする</li>
			<li>数値や実例を盛り込む</li>
		</ul>
		<p>より具体的なキャッチコピーの作り方や注意点については、以下の記事で解説しています。</p>
		<p><a href="https://www.dm110.jp/DM_matome/catch_copy/"><img src="/images/DM_matome/btn_catch_copy.png" width="760" height="126" alt="キャッチコピーの作り方はこちら" decoding="async" loading="lazy"></a></p>

		<h3 id="m02-5" class="midashi03">STEP5：印刷</h3>
		<p>自社でダイレクトメール（DM）を印刷するなら、用紙やインクの準備が必要です。一方で、外注先に依頼する場合は、デザインデータを用意して送付します。</p>
		<p>なお、DM発送代行会社なら、発送だけでなく印刷から対応しているケースが一般的です。DM発送代行会社に依頼する際は、デザインデータと宛名リストを持ち込んでください。</p>

		<h3 id="m02-6" class="midashi03">STEP6：発送作業</h3>
		<p>印刷が完了したら、封入・封緘、宛名貼りをし、運送業者に引き渡します。効果的なダイレクトメール（DM）にするために、「どのような順番で封入するか」も考えます。</p>
		<p>発送作業において、自社のリソースの確保が難しい場合は、封入・封緘からDM発送代行会社に依頼するのがおすすめです。</p>
