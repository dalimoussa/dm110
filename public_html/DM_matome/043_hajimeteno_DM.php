	<section id="m09">
		<h2 class="midashi02">ダイレクトメール（DM）のポイント7：持ち戻り品のデータ化</h2>
		<p>ダイレクトメール（DM）の発送は、「持ち戻り品のデータ化」という作業もともないます。具体的には、住所不明や受け取り拒否などで戻ってきたダイレクトメール（DM）をデータ化し、状況把握に役立てたり、次回発送時の参考にしたりします。</p>
		<p>戻ってきたダイレクトメール（DM）きちんと処理しないと、次のような状況に陥るかもしれません。</p>

		<div class="box box--yellow">
		<ul class="list-circle">
			<li>受け取り拒否された相手に再度ダイレクトメール（DM）を送ってトラブルになる</li>
			<li>無駄なダイレクトメール（DM）にコストをかけてしまい、費用対効果が悪くなる</li>
		</ul>
		</div>

		<p>会社の信用に影響する懸念もあるため、データ化は重要です。</p>
		<p>ただし、データ化の作業には思いのほか時間やコストがかかり、自社で対応するのは容易ではありません。そこで、データ化を行ってくれるDM発送代行会社を選び、発送からデータ化まで一括して任せるのがおすすめです。</p>
