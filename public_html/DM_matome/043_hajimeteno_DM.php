	<section id="m03">
		<h2 class="midashi02">ダイレクトメール（DM）のポイント1：発送目的と発送回数の決定</h2>
		<p>ここから、ダイレクトメール（DM）作成・発送の流れに沿って、ポイントを解説していきます。</p>
		<p>前提として、ダイレクトメール（DM）を発送する目的は、「売上や粗利を上げること」です。ダイレクトメール（DM）を「作ること」や「送ること」が目的にならないよう、注意してください。</p>
		<p>また、初めてのダイレクトメール（DM）では、少なくとも3回は発送するのがおすすめです。多くのケースでは、まずは1回だけ出してみて、思ったより良い反応・結果が得られたら継続しようと考えます。しかし、1回の結果だけで今後の方向性を決めてしまうと、大きな損失につながりかねません。</p>
		<p>もし、「予算が足りないため、複数回の発送を前提にできない」という場合は、次のような対応を検討してください。</p>

		<div class="box box--yellow">
		<ul class="list-circle">
			<li>予算内で3回発送できるだけの件数に絞る</li>
			<li>VIP顧客だけに送る</li>
			<li>発送コストを抑えられる媒体にする</li>
			<li>自社ホームページと連携する内容にし、封入枚数を減らす</li>
		</ul>
		</div>

		<p>ダイレクトメール（DM）の発送回数について、詳しくは以下の記事をご覧ください。</p>
		<p><a href="https://www.dm110.jp/DM_matome/DM_hindo/"><img src="/images/DM_matome/btn_DM_hindo.png" width="760" height="126" alt="DMの最適な発送頻度・回数・タイミングはこちら" decoding="async" loading="lazy"></a></p>
	</section>


	<section id="m04">
		<h2 class="midashi02">ダイレクトメール（DM）のポイント2：発送先の選定</h2>
		<p>先述のとおり、ダイレクトメール（DM）で最も重要なのが、発送先です。</p>
		<p>ダイレクトメール（DM）と聞くと、新規顧客をターゲットとするイメージがあるかもしれません。しかし、実際に効果が高いのは、既存顧客向けのものです。</p>
		<p>条件にもよりますが、既存顧客の反応率は、新規顧客の10～20倍以上となるケースも少なくありません。既存顧客のつなぎとめには、「5対25の法則」があり、5％の離脱を防げれば、25％の利益がアップすると考えられています。したがって、ダイレクトメール（DM）で既存顧客のつなぎとめを目指すことは、利益向上に効果的といえます。</p>
		<p>ただし、良い反応が得られるダイレクトメール（DM）かどうかは、実際に出してみないとわかりません。最初からすべての既存顧客に出すのではなく、LTV（ライフタイムバリュー）が良い上位20％だけに絞り、採算が取れそうかテストするのがおすすめです。（※）<br>
		<small>※LTV（ライフタイムバリュー）：取引を始めてから終えるまでの期間に、顧客が自社にどれくらいの利益をもたらすかを算出した指標</small></p>
		<p>ダイレクトメール（DM）の発送先については、以下の記事で解説しています。</p>
		<p><a href="https://www.dm110.jp/DM_matome/hassousaki/"><img src="/images/DM_matome/btn_hassousaki.png" width="760" height="126" alt="DMの発送先の詳細はこちら" decoding="async" loading="lazy"></a></p>
	</section>


