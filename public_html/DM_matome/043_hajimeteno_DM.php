	<section id="m10">
		<h2 class="midashi02">ダイレクトメール（DM）のポイント8：結果検証</h2>
		<p><img src="/images/DM_matome/hajimeteno_DM_sub4.jpg" width="1980" height="1320" alt="結果検証" decoding="async" loading="lazy"></p>
		<p>ダイレクトメール（DM）の成否を判断するには、「損益分岐点」を把握する必要があります。損益分岐点は、ダイレクトメール（DM）にかかった総コストを、粗利益単価で割ることで算出可能です。</p>
		<p>ただし、ダイレクトメール（DM）を一度出して赤字になったからといって、安易にやめないでください。なぜなら、結果を個別に見ると赤字でも、LTVでプラスになっていれば成功といえるからです。</p>
		<p>1回目のテスト結果を検証したら、結果が良かったほうのダイレクトメール（DM）と、それに変更を加えたダイレクトメール（DM）の2種類を用意し、2回目のテストを実施します。3回目も同様に、2回目で結果が良かったものと、変更を加えたものの2種類のダイレクトメール（DM）を用意してテストします。</p>
		<p>このように、結果を踏まえて何度もテストを繰り返すことが重要です。また、視点を変えて、ニュースレターの発送も検討してください。ニュースレターについては、以下の記事で解説しています。</p>
		<p><a href="https://www.dm110.jp/DM_matome/Newsletter_kouka/"><img src="/images/DM_matome/btn_Newsletter_kouka.png" width="760" height="126" alt="ニュースレターの効果はこちら" decoding="async" loading="lazy"></a></p>
