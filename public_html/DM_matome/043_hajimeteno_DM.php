		<p>ダイレクトメール（DM）を出す際に気になるのが、「採算が取れるか」という点です。より良いパターンのダイレクトメール（DM）を見つけるためには、いわゆる「ABテスト」が欠かせません。</p>
		<p>具体的には、一度に2種類のダイレクトメール（DM）を作成し、同時に発送することで、ターゲットの反応を比較します。ただし、まったく内容の異なるものを用意するのではありません。キャッチコピーやイラスト、オファー（特典・プレゼント）など1箇所（1要素）だけを変更します。</p>
