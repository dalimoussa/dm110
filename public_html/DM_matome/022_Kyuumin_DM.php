		<h2 class="midashi02">顧客の再休眠を防ぐためにすべき3つのこと</h2>
		<p>休眠顧客へアプローチしたあとは、再度顧客が離れてしまわないように対策を講じる必要があります。</p>
		<p>一般的に、5％の離脱顧客を防げたら、利益が25％アップするといわれています。実際に、5％の離脱顧客を防いで、実質的に粗利が30％以上増えたという結果も出ています。</p>
		<p>この「5対25の法則」と呼ばれる法則を取り入れ、顧客と定期的にコンタクトをとり、信頼関係をより深めるように工夫してください。</p>
		<p><img src="/images/DM_matome/Kyuumin_DM_sub3.png" width="1500" height="800" alt="顧客の再休眠を防ぐ！3つの方法" decoding="async" loading="lazy"></p>

		<h3 id="m04-1" class="midashi03 u-mt0">顧客との接触回数を増やす</h3>
		<p>顧客の離脱を防ぐために最も重視すべきは、顧客との接触回数です。接触の機会を増やすことで、離脱率を大きく減らせます。</p>
		<p>顧客との接触方法はいくつかありますが、コストパフォーマンスの高いニュースレターの利用がおすすめです。可能な限り毎月接触する機会を設け、最低でも3ヵ月に1回は接触できるようにします。</p>

		<h3 id="m04-2" class="midashi03">転居対策を行う</h3>
		<p>転居によって住所が変更され、DMが届かなくなった結果、顧客が離れてしまう、というパターンがあります。</p>
		<p>このような離脱を防ぐために、転居した場合に転居先を教えてもらえるような仕組みを作ります。通常の発送物やニュースレターなどに、転居に関する事項を追加すると有効です。</p>
		<p>ただし、転居対策をしすぎるとコストが多くかかってしまいます。顧客がもたらす利益とのバランスを見ながら、対策にかけるコストはどれくらいか、検討してみてください。</p>

		<h3 id="m04-3" class="midashi03">顧客の興味を惹くような対策を講じる</h3>
		<p>顧客の興味を惹きつけられると、離脱率を減らせます。</p>
		<p>DMの内容を他者に話した際に、感心されたり興味を持ってもらえたりすると、顧客はDMに価値を見出し、より一層興味を持つようになります。顧客にとって役立つ情報をDMに盛り込んで、顧客の興味を惹きつけることが大切です。</p>
		<p>また、お買い上げ金額に応じて、プレゼントや割引などの特典に差をつけるのも有効です。自分は特別な顧客であると思ってもらえれば、商品やサービスへの関心も高まります。</p>
