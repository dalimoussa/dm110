		<h2 class="midashi02">休眠顧客にアプローチすべき理由</h2>
		<p>以前、商品やサービスを利用していたものの、今ではまったく利用しなくなっている顧客を「休眠顧客」と呼びます。</p>
		<p>多くの企業は、休眠顧客の掘り起こしよりも、新規顧客の獲得に目を向けがちです。しかし、新規顧客の獲得は、休眠顧客へアプローチするよりも時間や労力がかかりがちです。DMの効果を上げるためにも、休眠顧客へのアプローチを積極的に行うほうが成果を上げやすいといえます。</p>
		<p>休眠顧客は、一度商品やサービスに興味を持った経験があるため、その魅力を再度認識してもらえれば、長くサービスを利用してもらえるかもしれません。また、休眠顧客へアプローチするなかで、休眠に至った理由がわかれば、今後のサービス改善にもつながります。</p>
		<p>なお、休眠顧客の細かい判断基準は企業ごとに異なります。休眠顧客の基準は、次の見出しで詳しく解説していますので、自社に合った基準を設定してみてください。</p>
