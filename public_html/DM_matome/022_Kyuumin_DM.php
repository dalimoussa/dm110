	<section id="m02">
		<h2 class="midashi02">優先すべき休眠顧客の選別方法</h2>
		<p><img src="/images/DM_matome/Kyuumin_DM_sub1.jpg" width="1980" height="1320" alt="" decoding="async" loading="lazy"></p>
		<p>つい最近休眠顧客になった方や、2年以上休眠顧客となっている方など、休眠顧客の状態はさまざまです。</p>
		<p>すべての休眠顧客に同じようにアプローチしてしまうと、良い結果は得られません。休眠顧客の状況に合わせて、アプローチの優先順位や手法などを柔軟に変更することが重要です。</p>
		<p>休眠顧客に対して、どのような優先順位でアプローチを行うか判断する際は、「休眠した理由」「休眠した時期」「休眠前の消費行動」の3つの基準をもとにするのがおすすめです。</p>
		<p><img src="/images/DM_matome/Kyuumin_DM_sub2.png" width="1500" height="800" alt="休眠顧客を選別する3つの判断基準" decoding="async" loading="lazy"></p>
		<p>3つの基準について、それぞれ内容を詳しく見ていきます。</p>

		<h3 id="m02-1" class="midashi03">基準（1）休眠した理由</h3>
		<p>商品やサービスの内容に不満がある、値上げした、スタッフの対応が悪い、特に理由もなく休眠したなど、休眠の理由は人それぞれです。休眠した理由に合わせてアプローチできれば、休眠顧客のサービス利用再開につながります。</p>
		<p>例えば、サービスの不満を理由に休眠顧客となった場合、サービスの不満点を解消すれば、顧客がサービス利用を再開してくれる可能性が高まります。</p>
		<p>休眠した顧客が他社商品に移行した場合、移行先の商品との比較が自然と行われます。移行した商品が思っていたよりも良くないことを感じることもあります。その場合に、戻るきっかけになるDMを届けることにより復帰につながることもあります。</p>
		<p>しかし、休眠した理由を正確に知ることは困難です。アンケートなどを利用して、休眠理由を確認する方法を検討してみてください。</p>

		<h3 id="m02-2" class="midashi03">基準（2）休眠した時期</h3>
		<p>休眠した時期によって顧客を選別するのも有効です。ただし、どの程度の期間を基準に選別するのか、明確な指標はありません。休眠期間の基準設定は、自社の商品やサービスの特徴をふまえて決定してください。</p>
		<p>休眠を開始してすぐの顧客へ送るDMと、休眠から半年や数年経っている顧客へのDMとでは、休眠期間の短い顧客へのDMのほうが効果的です。休眠期間が長い顧客ほど、サービスへの興味・関心は薄れており、サービス再利用の見込みも少なくなります。</p>
		<p>早めに顧客に連絡を入れて、サービスを忘れられないような工夫をしてください。定期購入の顧客には、定期購入の一時停止・解約の申し出があったときに、購入をやめる理由を聞いてみるのがおすすめです。</p>
		<p>ただし、休眠してから1年以上経過しているから、という理由だけで顧客へのアプローチを断念してしまうのはおすすめできません。以下のようなケースにある顧客は、サービスの利用見込みも考えられるため、DMが有効になります。</p>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>サービスの利用にいたる決定打がない</li>
			<li>乗り換え先のサービスに不満を感じている</li>
			<li>再度サービス利用したくなった</li>
			<li>サービスの利用をやめてから何かしらの不都合を感じている</li>
		</ul>
		</div>
		<p>なお、休眠顧客へのDMでは、過度な売り込みをしてはいけません。ご挨拶状や詫び状などの形で、顧客へアプローチしてください。コストはかかりますが、手書きのDMにするのもおすすめです。</p>

		<h3 id="m02-3" class="midashi03">基準（3）休眠前の消費行動</h3>
		<p>休眠前の消費行動には、顧客が休眠に至った理由が隠れている場合があります。以下の4つのポイントをおさえて調査し、重要な顧客を洗い出してみてください。</p>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>購入頻度</li>
			<li>一度の購入金額</li>
			<li>総購入金額</li>
			<li>支払いの状態</li>
		</ul>
		</div>
		<p>購入の頻度が高く、一度の購入金額が多い顧客は、再度利用してもらったときのポテンシャルも大きくなります。そのような重要顧客へは、ある程度コストをかけてでも、再利用してもらえるよう工夫してみてください。</p>

		<h3 id="m02-4" class="midashi03">どの基準からDMを送るべき？</h3>
		<p>「休眠した理由」「休眠期間」「休眠前の消費行動」の3つの基準を紹介しましたが、実際にどの基準を優先してDMを送るべきなのでしょうか。</p>
		<p>休眠した理由を正確に把握することができない場合、休眠理由を第一優先にしてDMの送付先を決めるのは困難です。よって、明確なデータがある場合に限り、休眠理由を優先して送付先を決めます。</p>
		<p>より正確なデータをもとに送付先の優先順位を決めるなら、自社が持つ購入期間、購入回数、購入送金額、休眠期間を調べてください。これらのデータから、休眠期間と休眠前の消費行動を明らかにできます。</p>
		<p>送付先の選別では、売上にどのように貢献するかを考えることが重要です。一般的に購入回数の多い顧客を優先し、次に購入期間・購入総金額、最後に休眠期間の順に、発送する顧客を選別します。</p>
		<p>ただし、BtoBの場合、高額商品、一生に何度も購入しない商品など業種や業態などにより異なりますので注意してください。</p>


