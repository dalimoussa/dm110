	<section id="m01">
		<h2 class="midashi02">紙媒体とは？</h2>
		<p><img src="/images/DM_matome/Kami_baitai_sub1.jpg" width="1980" height="1321" alt="" decoding="async" loading="lazy"></p>
		<p>そもそも「紙媒体」とは、DM・ニュースレター・チラシ・新聞・雑誌など、紙に印刷された情報を伝えるメディアのことです。ここでは、紙媒体を活用するメリットやデメリットを解説します。</p>

		<h3 id="m01-1" class="midashi03">紙媒体のメリット</h3>
		<p>紙媒体は、信頼性が高いのが特徴です。発行後は内容を修正できないため、発行前にいくつものチェックを経ており、それが信頼性の高さにつながっています。</p>
		<p>また、使用する紙の素材・厚さや加工方法によって、多彩な表現ができるのもメリットです。例えば、和紙を使い印象に残る手触りにしたり、ホチキス止め・折り加工などを施して読みやすい形状にしたりといった表現方法があります。細かいところまで表現を工夫すれば、相手に気持ちが伝わりやすくなります。</p>
		<p>さらに、紙媒体は視認性に優れています。視認性とは、「対象物を見るときの瞬間的な見やすさの度合い」のことです。</p>
		<p>パソコンやスマートフォンの画面のように、限られた範囲に情報が表示される場合、画面をスクロールしないと全体像がわかりません。しかし、紙媒体なら実際に手に取れるため、パッと見ただけで全体像をつかめます。視認性の高さは、大切な情報を伝える際に、双方の認識のズレによるトラブルを減らすうえでも重要です。</p>
		<p>その他のメリットには、「もの」として手元に残せるため何度も読み返せることや、受け取った人しか内容がわからずまねされにくいことなどが挙げられます。</p>

		<h3 id="m01-2" class="midashi03">紙媒体のデメリット</h3>
		<p>インターネット上なら、ページを拡大・追加すれば好きなだけ情報を掲載できますが、紙媒体の場合、伝えられる情報量に限度があります。使用する紙の大きさに応じて、掲載する情報を適切に取捨選択しなければなりません。</p>
		<p>また「紙媒体のメリット」で説明したとおり、発行前にいくつものチェックを経るため、発行までに時間を要します。発行した紙媒体を修正する場合は、再度印刷・配布する必要があり、その分コストもかかります。</p>
		<p>なお、プロモーションの成果を出すためには、紙媒体でもWeb媒体でも「テスト」が欠かせません。しかし紙媒体は、作成から印刷・配布までに時間がかかるうえ、それが開封されたか・反応があったかなども把握しにくく、テスト結果を得るのに時間がかかります。</p>
	</section>


	<section id="m02">
		<h2 class="midashi02">紙媒体のおもな種類とそれぞれの特徴</h2>
		<p><img src="/images/DM_matome/Kami_baitai_sub2.png" width="1500" height="1000" alt="紙媒体の主な種類" decoding="async" loading="lazy"></p>
		<p>代表的な5種類の紙媒体と、それぞれの特徴を見ていきます。</p>

		<h3 id="m02-1" class="midashi03">DM</h3>
		<p>DM（Direct Mail：ダイレクトメール）とは、商品やサービスのターゲットとなる個人・法人宛に、売り込みを目的として届ける印刷物のことです。</p>
		<p>DMには、宛先を限定できる・まねされにくい・効果が持続しやすいといったメリットがあります。特に既存顧客に向けたDMは、費用対効果が大きくなります。</p>
		<p>新規顧客に対しては、DMで直接的な成果を出すのではなく、DMで興味を引き、インターネットで集客する方法が有効です。</p>
		<p>一方、効果的なDMを作るには、内容はもちろん、デザインや封筒なども工夫しなければなりません。そのため、発送するまでに時間やコストがかかります。</p>

		<h3 id="m02-2" class="midashi03">ニュースレター</h3>
		<p>ニュースレターは、いわば顧客への「お便り」です。DMが売り込みを目的とするのに対し、ニュースレターは顧客の役に立つ情報や、親しみを持てる情報を届けることを目的とします。</p>
		<p>ニュースレターで成果を出すには、月1回程度のペースで発送を継続するのが重要です。顧客との接触を増やすことで、好感度の向上や信頼関係の構築が期待できます。</p>
		<p>しかし逆にいうと、ニュースレターは「定期的」かつ「顧客の興味を引く内容」で作成しなければならず、ネタが尽きる可能性があります。一度始めたニュースレターを中断すると顧客からの印象が悪くなるため、始める前に、継続できるかしっかりと検討しなければなりません。</p>
		<p>ニュースレターは継続することで効果が上がっていく特殊な紙媒体で、他の紙媒体では得られないメリットが多いのが特徴です。</p>
		<p>ニュースレターについて詳しくは下記ページをご覧ください。</p>
		<p><a href="https://www.dm110.jp/DM_matome/Newsletter_tukurikata/"><img src="/images/DM_matome/btn_Newsletter_tukurikata.png" width="760" height="126" alt="ニュースレターの作り方はこちら" decoding="async" loading="lazy"></a></p>
		<p><a href="https://www.dm110.jp/DM_matome/Newsletter_kouka/"><img src="/images/DM_matome/btn_Newsletter_kouka.png" width="760" height="126" alt="ニュースレターの効果はこちら" decoding="async" loading="lazy"></a></p>

		<h3 id="m02-3" class="midashi03">チラシ</h3>
		<p>チラシは、店舗や駅に設置したり、新聞に折り込んだりして、不特定多数の人の目に触れるものを指します。</p>
		<p>チラシのメリットは、届けたい情報によって配布する地域や時期を限定できることです。例えば新規店舗をオープンする際に、その店舗がある地域の住人に対し、オープン前の一定期間だけ周知できます。なかでも、主婦層やファミリー層向けの情報が得意です。</p>
		<p>なお、「紙媒体とは？」の章で「紙媒体はまねされにくい」と説明しましたが、宛先を限定しないチラシの場合は例外で、内容をまねされやすいことがデメリットです。また、チラシにより得られる効果は一時的になります。</p>

		<h3 id="m02-4" class="midashi03">ポスティング</h3>
		<p>ポスティングとは、チラシや冊子などをポストに投函する手段のことです。</p>
		<p>ポストに入るサイズのものなら、比較的自由に投函物を決められます。また、自社で直接投函すれば人件費がかからないため、コストを大幅に削減可能です。</p>
		<p>一方、投函業務を自社で行う場合も、ポスティング業者に委託する場合も、投函できる数には限りがあります。また、そもそもポスティングを禁止している住宅もあるため、注意しなければなりません。</p>

		<h3 id="m02-5" class="midashi03">新聞広告</h3>
		<p>新聞広告は、新聞の紙面に掲載される広告のことです。新聞に折り込まれるチラシなどは、新聞広告に含まれません。</p>
		<p>新聞広告にはさまざまなルールが存在するため、新聞広告を掲載するには、新聞社の窓口となる広告会社や、新聞社の審査を受ける必要があります。したがって、新聞広告は「広告会社や新聞社のお墨付き」という見方ができることから、信頼性が高いのがメリットです。また、チラシやポスティングのように、情報を届ける地域や時期を限定できます。</p>
		<p>しかし、注意しなければならないのが、昨今では新聞の購読者数が減っている点です。また、過去の新聞を何度も読み返すケースは少なく、新聞広告も一度しか見られない可能性があります。</p>
		<p>なお、購読者数は減っていますが高齢者の購読率が高いため、高齢者をターゲットにした商品の場合は費用対効果が良くなることもあります。</p>

		<h3 id="m02-6" class="midashi03">雑誌広告</h3>
		<p>雑誌には、発行するペースによって季刊誌・月刊誌・隔週誌などがあり、これらに掲載する広告を雑誌広告といいます。</p>
		<p>雑誌広告のメリットは、雑誌の読者の属性を考慮し、ターゲットを絞り込めることです。また、印刷面の美しさが劣る新聞広告に比べ、雑誌広告はカラーできれいに印刷できます。雑誌に掲載される回数が増えれば増えるほど、ターゲットからの認知度が高まり、掲載された回数は実績としてアピールポイントにもなります。</p>
		<p>一方で、雑誌広告は掲載までに時間がかかります。また、雑誌ごとに広告を掲載するスペースは決まっているため、掲載できる情報量が限られる点もデメリットです。</p>
	</section>


	<section id="m03">
		<h2 class="midashi02">紙媒体とWeb媒体の違いは？</h2>
		<p><img src="/images/DM_matome/Kami_baitai_sub3.png" width="1500" height="1000" alt="紙媒体とWeb媒体の違い" decoding="async" loading="lazy"></p>
		<p>紙に印刷された情報を伝える紙媒体に対し、「Web媒体」はインターネット上で公開する広告のことです。Web媒体のおもな種類は、次のとおりです。</p>

		<div class="box box--yellow">
		<ul class="list-circle">
			<li>ホームページ</li>
			<li>SNS</li>
			<li>ブログ</li>
			<li>PPC広告（検索連動型広告・コンテンツ連動型広告）</li>
			<li>バナー広告</li>
			<li>インターネット動画広告</li>
			<li>インターネットテレビ広告</li>
		</ul>
		</div>

		<p>インターネットの普及を受けてWeb媒体は主流になりつつありますが、紙媒体とWeb媒体のどちらが優れているか、一概にはいえません。</p>
		<p>例えば、特定のターゲットにアプローチすることが多い紙媒体に対し、Web媒体は不特定多数に向けて情報を発信し、顧客からの接触を受動的に待つのが特徴です。新規顧客の獲得単価は、紙媒体よりもWeb媒体のほうが通常低くなります。</p>
		<p>しかし、宛先を絞って能動的にアプローチできないため、Web媒体では届けたい情報が届かないといったことも起こり得ます。また、紙媒体は個人情報の取り扱いに注意しなければなりませんが、Web媒体では、個人情報に加えてウイルス対策も欠かせません。</p>
		<p>紙媒体とWeb媒体には上記のような違いがあることを理解したうえで、ケースごとに適した媒体を活用するのがおすすめです。</p>
		<p>なお現在、紙媒体とWeb媒体を融合して使う方法が費用対効果を上げています。まずは紙媒体で興味を持ってもらい、Webに誘導し、最終的にWeb上で集客する方法です。</p>
	</section>


	<section id="m04">
		<h2 class="midashi02">顧客層によって紙媒体を使い分けよう</h2>
		<p><img src="/images/DM_matome/Kami_baitai_sub4.jpg" width="1980" height="1317" alt="" decoding="async" loading="lazy"></p>
		<p>紙媒体は、既存顧客と新規顧客で使い分けるのがポイントです。ここでは、顧客層別に、おすすめの紙媒体や活用方法を解説します。</p>

		<h3 id="m04-1" class="midashi03">既存顧客</h3>
		<p>既存顧客をつなぎ止めるなら、DMを活用してください。</p>
		<p>一般的に、DMは売り込みを目的としますが、既存顧客にDMを出す際は、売り込み色を強くしないのがコツです。売り込み色を抑え、既存顧客にメリットがある内容にすれば、何度も発送しやすくなります。</p>
		<p>一度限りのDMだと忘れられてしまうリスクがありますが、何度もDMを出すことで、既存顧客の流出を阻止できます。</p>

		<h3 id="m04-2" class="midashi03">新規顧客</h3>
		<p>新規顧客を集客するなら、費用対効果の観点からDMは候補外となります。ただし、Web媒体とDMを組み合わせる方法は有効です。具体的には、最初にDMに興味を持ってもらい、詳しい内容を伝えるためにホームページへ誘導し、そこから購入につなげる方法です。</p>
		<p>DMからホームページへ誘導するためのポイントは、次のとおりです。</p>

		<div class="box box--yellow">
		<ul class="list-circle">
			<li>A4サイズのハガキを使い、開封の手間をなくす</li>
			<li>DMにホームページのURL（トップページ）を記載する</li>
			<li>DMの内容について、より詳しく説明しているホームページのURL（個別ページ）を記載する</li>
			<li>ホームページを見ると特典があることをDMに明記する</li>
			<li>ホームページに簡単にアクセスできるようQRコードなどを活用する</li>
		</ul>
		</div>

		<p>また、新規顧客の集客には、ポスティングやチラシもおすすめです。</p>
		<p>ポスティングで成果を出すコツは、まずは自ら行うことです。自分でポスティングすると、地域住民と出会う機会が増え、新しい発見や思わぬ反響が得られる可能性があります。一方、チラシで成果を出すポイントは、特典を付けること・配布地域を絞ること・定期的に配布することです。</p>
		<p>その他、業界専門の雑誌に広告を掲載する選択肢もあります。費用対効果を踏まえて検討してください。</p>
	</section>


	<section id="m05">
		<h2 class="midashi02">紙媒体は今後どうなる？</h2>
		<p>新型コロナウイルス感染症の流行をきっかけに、在宅での仕事が増え、顧客と直接会う機会が減りました。今後は、顧客との関係性をいかに維持するかが課題となります。</p>
		<p>そのような背景から改めて注目されているのが、手間をかけることで顧客との関係性を維持・向上できる、ニュースレターやDMです。</p>
		<p>また、「顧客層によって紙媒体を使い分けよう」の章で説明したとおり、今後はインターネットとの連携がますます重要視されそうです。DMをはじめとする紙媒体に加え、ホームページなどのWeb媒体にも力を入れていく必要があります。</p>
	</section>


