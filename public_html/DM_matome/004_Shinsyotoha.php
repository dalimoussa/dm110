	<section id="m01">
		<h2 class="midashi02">信書とは郵便法と信書便法に定義された「通信手段」</h2>
		<p><img src="/images/DM_matome/Shinsyotoha_sub1.jpg" width="1980" height="1320" alt="" decoding="async" loading="lazy"></p>
		<p>郵便法と信書便法において、「信書」とは「特定の受取人に対し、差出人の意思を表示し、または事実を通知する文書」と定義されています。</p>
		<p>また、この定義における「特定の受取人」「意思を表示し、または事実を通知する」「文書」とは、それぞれ以下を表します。</p>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>特定の受取人：差出人がその意思の表示または事実の通知を受ける者として特定に定めた者のこと</li>
			<li>意思を表示し、または事実を通知する：差出人の考えや思いを表し、または現実に起こり、もしくは存在する事柄等の事実を伝えること</li>
			<li>文書：文字・記号・符号等、人の知覚によって認識することができる情報が記載された紙その他の有体物のこと（電磁的記録物を送付しても信書の送達には該当しません）</li>
		</ul>
		</div>
	</section>


	<section id="m02">
		<h2 class="midashi02">DMは信書に該当する？</h2>
		<p>商品などの広告を内容として、同一内容の文書を多数の受取人にあてて差し出す形態をとるいわゆるDMは、信書に該当するのでしょうか。</p>
		<p><img src="/images/DM_matome/Shinsyotoha_sub2.png" width="1500" height="900" alt="信書に該当するDM,信書に該当しないDM" decoding="async" loading="lazy"></p>
		<p>DMの場合、差出人が特定の受取人を選別し、受取人に対して商品の購入等を勧誘する文書を送付するものは信書に該当します。</p>
		<p>例えば、以下のようなものは信書に該当するDMです。</p>

		<div class="box box--yellow">
		<ul class="list-circle">
			<li>文書自体に個々の受取人が記載されている</li>
			<li>個々の受取人の記載がない場合でも、商品の購入等利用関係があることを示す文言が記載されている</li>
			<li>個々の受取人の記載がない場合でも、契約関係等差出人との間において特定の関係にある者への意思の表示または事実の通知である旨の文言が記載されている</li>
			<li>個々の受取人の記載がない場合でも、その他の差出人が特定の受取人に差し出す趣旨が明らかとなる文言が記載されている</li>
		</ul>
		</div>

		<p>ただし、以下のような場合には、DMは信書に該当しません。</p>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>その内容が公然あるいは公開たりうる事実のみであり、専ら街頭における配布や新聞折り込みを前提として作成されるチラシのような場合</li>
			<li>専ら店頭における配布を前提として作成されるパンフレットやリーフレットのような場合</li>
		</ul>
		</div>
	</section>


	<section id="m03">
		<h2 class="midashi02">【具体例】信書に該当するもの</h2>
		<p><img src="/images/DM_matome/Shinsyotoha_sub3.png" width="1500" height="1300" alt="信書に該当するもの,信書に該当しないもの" decoding="async" loading="lazy"></p>
		<p>ここからは、信書に該当するものと該当しないものを具体的に解説します。信書に該当するものの具体例は、以下のとおりです。</p>

		<h3 id="m03-1" class="midashi03">書状</h3>
		<p>書状は、考えや用件などの意思の表示、または事実を通知する文書です。そのため、差出人から特定の受取人にその内容を伝えるために送付する場合、書状は信書に該当します。</p>

		<h3 id="m03-2" class="midashi03">請求書に類するもの</h3>
		<p>請求書は、代金を請求するという意思の表示、または事実を通知する文書です。そのため、差出人から特定の受取人にその内容を伝えるために送付する場合、請求書は信書に該当します。</p>
		<p>請求書に類するものには、納品書・領収書・見積書・願書・申込書・申請書・申告書・依頼書・契約書・照会書・回答書・承諾書などがあります。</p>

		<h3 id="m03-3" class="midashi03">会議招集通知に類するもの</h3>
		<p>会議招集通知は、会議への出席を要請するという意思の表示、または事実を通知する文書です。そのため、差出人から特定の受取人にその内容を伝えるために送付する場合は、会議招集通知も信書に該当します。</p>
		<p>会議招集通知に類するものには、結婚式等の招待状、業務を報告する文書などがあります。</p>
		<p>ただし、特定の人と限らない文書は信書に当たらない場合もあります。</p>

		<h3 id="m03-4" class="midashi03">許可書に類するもの</h3>
		<p>許可書は、許可するという意思を表示し、または事実を通知する文書です。そのため、差出人から特定の受取人にその内容を伝えるために送付する場合は、信書に該当します。</p>
		<p>許可書に類するものには、免許証・認定書・表彰状などがあります。</p>

		<h3 id="m03-5" class="midashi03">証明書に類するもの</h3>
		<p>証明書は、ある事項が真実であることや間違いがないことの事実の通知、または意思を表示する文書です。そのため、差出人から特定の受取人にその内容を伝えるために送付する場合は、信書に該当します。</p>
		<p>証明書に類するものには、印鑑証明書納税証明書・戸籍謄本・住民票の写しなどがあります。</p>
	</section>


	<section id="m04">
		<h2 class="midashi02">【具体例】信書に該当しないもの</h2>
		<p>信書に該当しないものの具体例は、以下のとおりです。</p>

		<h3 id="m04-1" class="midashi03">書籍に類するもの</h3>
		<p>書籍は、広く一般に対して発行されるものです。つまり、書籍に記載された内容は特定の受取人に対するものではないので、信書には該当しません。</p>
		<p>書籍に類するものには、新聞・雑誌・会報・会誌・手帳・カレンダー・ポスターなどがあります。</p>

		<h3 id="m04-2" class="midashi03">カタログ</h3>
		<p>カタログとは、系統的に編さんされた商品、申込方法、商品の広告等が印刷された商品紹介集（一般的には冊子としたもの）です。</p>
		<p>カタログは利用者一般に対して発行されるもので、特定の受取人に対するものではないので、信書には該当しません。</p>

		<h3 id="m04-3" class="midashi03">小切手に類するもの</h3>
		<p>小切手は流通性を有する証券であって、証券が流通する際に必要とされる事項を記載したものです。</p>
		<p>小切手も特定の受取人に対する意思の表示、または事実を通知する文書ではないので、信書には該当しません。</p>
		<p>小切手に類するものには、手形・株券などがあります。</p>

		<h3 id="m04-4" class="midashi03">プリペイドカードに類するもの</h3>
		<p>プリペイドカードは、金銭の支払手段として使用するために発行されるもので、使用時の注意事項が記載されるのが一般的です。</p>
		<p>そのため、特定の受取人に対する意思の表示、または事実を通知するものではないことから、プリペイドカードは信書には該当しません。</p>
		<p>プリペイドカードに類するものには、商品券・図書券があります。</p>

		<h3 id="m04-5" class="midashi03">乗車券に類するもの</h3>
		<p>乗車券は、鉄道やバスなどの交通機関に乗るために発行されるものであり、一般的には乗車する際の注意事項が記載されています。</p>
		<p>したがって、特定の受取人に対する意思の表示、または事実を通知するものではないので、乗車券に類するものは信書には該当しません。</p>
		<p>乗車券に類するものには、航空券・定期券・入場券があります。</p>

		<h3 id="m04-6" class="midashi03">クレジットカードに類するもの</h3>
		<p>クレジットカードは、金銭の支払手段としての機能を有するものです。その記載文が物と密接に関連している場合には信書に該当しません。</p>
		<p>キャッシュカードやローンカードも、クレジットカードと同様の扱いとなります。</p>

		<h3 id="m04-7" class="midashi03">会員カードに類するもの</h3>
		<p>会員カードは、会員であることの確認などの機能を有するものであり、当該カードを使用する際に必要となる注意事項が記載されています。</p>
		<p>記載内容は特定の受取人に対する意思の表示、または事実を通知するものではないため、会員カードは信書には該当しません。</p>
		<p>会員カードに類するものには、入会証・ポイントカード・マイレージカードなどがあります。</p>
	</section>


	<section id="m05">
		<h2 class="midashi02">信書に該当するDMの送り方</h2>
		<p><img src="/images/DM_matome/Shinsyotoha_sub4.jpg" width="1980" height="1320" alt="" decoding="async" loading="lazy"></p>
		<p>信書に該当するDMを送る場合、送る方法に注意しましょう。</p>

		<p>日本国憲法第21条2項「検閲は、これをしてはならない。通信の秘密は、これを侵してはならない」に基づき、信書の秘密は確保されなければなりません。<br>
		<i>出典：<a href="https://elaws.e-gov.go.jp/document?lawid=321CONSTITUTION" target="_blank" rel="noopener noreferrer"><cite>日本国憲法第二十一条</cite></a></i></p>

		<p>民間事業者による信書の送達に関する法律には、信書の秘密の保護が明記されており、信書便事業には総務省の許可が必要と定められています。</p>
		<p>総務省の許可がない事業所が信書を送達したり、許可がない事業所に送達を依頼したりすると、3年以下の懲役または300万円以下の罰金に処されます。信書の秘密を侵したり、信書便物を開いたりした場合にも罪に問われるため、信書の取扱いには十分ご注意ください。</p>
		<p>信書を送れるサービスには、日本郵便の定形郵便・定形外郵便・レターパック・スマートレターや、佐川急便の飛脚特定信書便があります。なお、ヤマト運輸では信書の発送はできません。</p>

		<p><img src="/images/DM_matome/Shinsyotoha_sub5.png" width="1500" height="1940" alt="日本郵便 信書発送の可否" decoding="async" loading="lazy"></p>
