	<section id="m01">
		<h2 class="midashi02">DMのオファー（特典）とは？</h2>
		<p><img src="/images/DM_matome/DM_offer_sub1.jpg" width="1980" height="1320" alt="" decoding="async" loading="lazy"></p>
		<p>DMのオファーとは、顧客の行動を後押し、開封率や反応率、売上などの向上につなげるための特典のことです。実際、オファーはDMの開封率や閲読率の向上に寄与しています。</p>

		<h3 id="m01-1" class="midashi03">DMにおけるオファー（特典）の重要性</h3>
		<p>DMには、①発送先の選別、②オファー（特典）、③DMの内容という3つの要素があります。成果の出るDMを作成するには、これらの要素を重視して作成しなければなりません。</p>
		<p>重要度の比重は、一般的に①発送先の選別が40％、②オファーが30％、③DMの内容が30％といわれています。しかし、弊社では①発送先の選別が50％、②オファーが30％、③DMの内容が20％という結果が出ています。</p>
		<p><img src="/images/DM_matome/DM_offer_sub2.png" width="1500" height="1000" alt="オファー（特典）が30％" decoding="async" loading="lazy"></p>
		<p>つまり、DMの内容も重要であるのはさることながら、それ以上にオファーの存在が重要だといえます。</p>
		<p>一般社団法人日本ダイレクトメール協会の「DMメディア実態調査2021」によると、オファーの存在は、実際にDMの開封率に影響を与えている旨のデータが出ています。</p>

		<p class="u-mb0">◆DMや郵便物の開封・閲読する情報内容（購入・利用経験あり／上位5項目）</p>
