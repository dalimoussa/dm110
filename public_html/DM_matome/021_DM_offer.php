	<section id="m02">
		<h2 class="midashi02">DMで使われるオファー（特典）の種類</h2>
		<p>オファー（特典）にはどのような種類があるのでしょうか。おもなオファーを5つの項目に分けて解説します。</p>
		<p><img src="/images/DM_matome/DM_offer_sub3.png" width="1500" height="1000" alt="DMで使われるオファー（特典）の種類" decoding="async" loading="lazy"></p>

		<h3 id="m02-1" class="midashi03">プレゼント</h3>
		<p>プレゼントは、DMのなかに異物があると開けたくなる、捨ててしまうのがもったいない、という顧客心理をついたオファーです。</p>
		<p>プレゼントには、ボールペンやカレンダー、押し花、花の種、ストラップ、お守り、小冊子、小銭入れ、鈴、石鹸、箸など、さまざまな種類があります。自社に関係の深い商品やサービスをプレゼントに選んでください。</p>
		<p>ただし、オファーとしてプレゼントを使用する場合は、景品表示法にも注意しなければなりません。景品表示法については記事後半で詳しく解説していますので、併せてご確認ください。</p>

		<h3 id="m02-2" class="midashi03">金額（割引・無料・キャッシュバック）</h3>
		<p>値引きは顧客にメリットが伝わりやすいことから、オファーとしても定番です。特に「無料」のオファーの効力は強く、送料無料、入会金無料など、さまざまなパターンで利用されています。</p>
		<p>1本購入すると1本サービスするなど、購入時にさらに商品をつけることでお得感を出す方法もあります。また、特に価格が高いサービスを売り込む際には、サービス利用後や商品購入後に一定金額を割り戻すキャッシュバックのオファーがおすすめです。</p>
		<p>ただし、割引や無料サービスを売りにすると、価格だけを目的に集まる顧客が増えてしまいます。割引・無料・キャッシュバックの多用は避けてください。</p>

		<h3 id="m02-3" class="midashi03">支払い方法・支払い期限</h3>
		<p>分割払いを可能にしたり、支払い方法を複数用意したりするなど、支払い方法や期限に焦点をあてたオファーもあります。</p>
		<p>商品やサービスの価格を落とすことなく、顧客の購入ハードルを下げられるメリットがあるため、効果的に使用してみてください。</p>

		<h3 id="m02-4" class="midashi03">保証</h3>
		<p>保証関連のオファーには、サービス保証期間をつけたり、サービスに満足できない場合に返金したりするといったものがあります。</p>
		<p>「サービスが合わなかったらどうしよう…」という顧客の不安を解消でき、安心感を与えられるのがメリットです。</p>
		<p>大きな保証は、サービスや商品への自信の表れと受け取られますが、保証が行き過ぎるとトラブルが発生する可能性があるため注意が必要です。</p>

		<h3 id="m02-5" class="midashi03">その他</h3>
		<p>家族割や友人割など、周囲の人を巻き込むタイプのオファーや、抽選でサービスを受けられる抽選型のオファーなど、上記以外にもオファーにはさまざまな種類があります。</p>
		<p>企業の特徴やブランドを活かし、自社に合ったオファーを選択することが大切です。</p>
	</section>


	<section id="m03">
		<h2 class="midashi02">DMのオファーは誰に送るべき？</h2>
		<p>DMオファーというと新規顧客獲得が思い浮かぶのではないでしょうか？</p>
		<p>DMで効果を上げている会社様は、新規顧客以外にも以下のような送り先に送っています。</p>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>新規顧客</li>
			<li>VIP客</li>
			<li>1度だけ購入した人</li>
			<li>購入期間が空いている人</li>
			<li>離脱客</li>
			<li>定期的に少量購入顧客</li>
			<li>まだ購入いただいていない他商品</li>
			<li>購入者以外の家族</li>
			<li>記念日を迎えた個人や会社</li>
			<li>見積書を提出した会社</li>
			<li>名刺交換した会社</li>
			<li>商談がストップした会社・個人</li>
			<li>買い替え時期を迎えた会社・個人</li>
		</ul>
		</div>
		<p>新規顧客以外へDMオファー送り、好結果になるケースも少なくありません。</p>

		<h3 id="m03-1" class="midashi03">DMのオファーで効果がある送り先</h3>
		<p>DMの送り先と同様に、既存顧客へのオファーも効果が期待できます。<br>既存顧客へのオファーで期待できる効果は、複数あります。</p>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>離脱率防止</li>
			<li>売上アップ</li>
			<li>紹介</li>
			<li>関係性の強化　など</li>
		</ul>
		</div>
		<p>効果が特に期待できる送り先はVIP客になります。目に見えない効果もあるため、VIP客へのオファー付きDMもテストしてみてください。</p>
	</section>


	<section id="m04">
		<h2 class="midashi02">DMにオファー（特典）をつける際の注意点</h2>
		<p>顧客を引き付けるオファー（特典）ですが、その利用には注意すべき点もあります。オファー利用の注意点を4つ解説します。</p>

		<h3 id="m04-1" class="midashi03">オファーの選定は慎重に行う</h3>
		<p>オファーの種類やオファーを提供するタイミングは、慎重に検討してください。</p>
		<p>特に注意が必要なのが、商品やサービスを無料にするタイプのオファーです。無料のオファーで集客すると、オファーを欲しい人ばかりが集客され、オファーがなくなると同時に顧客も減り、サービスのリピート利用につながりません。場合によってはリピート顧客がゼロになることもあります。</p>
		<p>また、自社のサービスに合わないオファーを選ばないようにすることも大切です。</p>
		<p>過去には、販促施策として自社のサービスの価値を上げられない特典を付けたことにより、解約率が高い顧客の割合が増えた事例もあります。この事例では、減った顧客を取り戻そうと、さらなる特典施策を打ち、大量加入しては大量解約していく悪循環に陥ってしまいました。</p>
		<p>オファー選びを間違うと、売上につながらないどころか、減収になってしまう可能性もあるのです。</p>
		<p>このような事態を防ぐためにも、オファーを使用したら、オファーのみを目的とする顧客の割合や継続購入状況などの調査を行い、オファーの効果を確認することをおすすめまします。</p>

		<h3 id="m04-2" class="midashi03">オファーは正確に伝える</h3>
		<p>特典は一つひとつ、タイトルと内容、メリットを丁寧に説明してください。顧客にオファーが正確に伝わらなければ、オファーの効果がなくなってしまうからです。</p>
		<p>オファーの内容は何か、可能であれば写真やイラストもふまえて、詳細を顧客に伝えます。</p>
		<p>DMの作成者はDMの内容をよくわかっているため、オファーがしっかりと顧客に伝わるか判断できない場合もあります。その場合は、第三者にDMを見てもらい、内容をスムーズに理解できるかを確認してみてください。</p>

		<h3 id="m04-3" class="midashi03">景品表示法に注意する</h3>
		<p>プレゼントや割引などを集客の目玉にするときは、景品表示法にも注意してください。</p>
		<p>景品表示法とは、景品類の最高額や総額を規制することで、行き過ぎた景品提供を防ぎ、一般消費者の利益を保護することを目的とした法律です。</p>
		<p>DMのオファーは、懸賞によらず、商品・サービスの購入者や利用者、来店者などに等しく提供される「総付景品」にあたります。法律に定められた景品類の最高額を守ってオファーを提供してください。</p>
		<p>また、プレゼントや割引だけでなく、「先着●名様」など、決まった人数に提供される景品類も、原則として、総付景品に区分されます。</p>
		<p>以下は総付景品の一例です。オファーが総付景品に該当するか確認してみてください。</p>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>開店当日に来店した全員に粗品をプレゼント</li>
			<li>先着●名様に賞品をご提供</li>
			<li>申込者全員に記念品を送付</li>
			<li>商品Aをご購入の方全員に粗品Bを贈呈</li>
		</ul>
		</div>
		<p>消費者などに総付景品を提供する場合の限度額は、以下のとおり定められています。総付景品をつける商品・サービスの価格（取引価格）が「1,000円未満か、1,000円以上か」で最高額が変わる点に注意してください。</p>
		<p class="u-mb0">【総付景品の限度額】</p>
		<table class="table01">
			<tr><th>取引価額</th><th>景品類の最高額</th></tr>
			<tr><td>1,000円未満</td><td>200円</td></tr>
			<tr><td>1,000円以上</td><td>取引価額の10分の2</td></tr>
		</table>
		<p>引用：<a href="https://www.caa.go.jp/policies/policy/representation/fair_labeling/premium_regulation/" target="_blank" rel="noopener noreferrer"><cite>消費者庁「景品規制の概要」</cite></a></p>

		<h3 id="m04-4" class="midashi03">発送方法によりオファーに制限が出ることもある</h3>
		<p>オファーとしてプレゼントを同封する場合、プレゼントの厚みや重さによって発送方法に制限が出る可能性があります。</p>
		<p>例えば、メール便の場合、厚さの規格は2cm～3cm以内となっているため、これを超えるオファーは選択できません。</p>
		<p>発送方法によって制限は変わります。発送方法に合ったオファーを選択するか、オファーに合わせて発送方法を選択してください。</p>
	</section>


