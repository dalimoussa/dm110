	<section id="m04">
		<h2 class="midashi02">既存顧客の分類</h2>
		<p><img src="/images/DM_matome/repeat_ritu_sub2.jpg" width="1980" height="1320" alt="" decoding="async" loading="lazy"></p>
		<p>リピート率向上のための施策は、すべての既存顧客に対して一律に行うのではなく、顧客を分類し、分類に合わせて施策を変えるとより効果的です。</p>
		<p>リピート回数や購入金額をもとに顧客を分類すると、既存顧客はおもに初回客・２回目客・リピート客・VIP客の4つに分類されます。</p>

		<div class="box box--yellow">
		<ul class="list-circle">
			<li>初回客：初めて購入した顧客</li>
			<li>2回目客：2回購入した顧客</li>
			<li>リピート客：優良顧客ほど購入金額は多くないが継続して購入している顧客</li>
			<li>VIP客：購入金額・回数が上位20％程度に位置する優良な継続顧客</li>
		</ul>
		</div>

		<p>初回客がリピートした場合とVIP客がリピートした場合とを比較すると、後者のほうが高い売上を期待できます。そのため、VIP客のリピート率を上げる施策を打つ場合は、ある程度コストをかけてでも、リピートしてもらえるようにアプローチすべきです。</p>
	</section>


	<section id="m05">
		<h2 class="midashi02">リピート回数もセットで考えよう</h2>
		<p>リピート率とリピート回数をセットで考えると、よりリピート率の問題点を可視化できます。リピート率とリピート回数の関係性を明らかにする際は、売上・粗利・販売個数・成約数・離脱客数の年計を調べることから始めてください。</p>
		<p>年計とは、特定の時期から起算した過去1年間のデータの総計です。例えば、2023年1月の年計を算出する際は、2022年2月から2023年1月までのデータを集計します。</p>
		<p>年単位でデータを集計するメリットは、季節によるデータの変動を無視できる点にあります。月々のデータのみを比較すると、データの季節変動を無視できず、データの傾向を読み取りづらくなってしまうのです。</p>
		<p>売上・粗利・販売個数・成約数・離脱客数の各データの年単位で集計したら、結果をグラフに落としこみ、数値の傾向を分析してください。各データの年計に極端な変化が見られた場合は変化の原因を探ると、課題などが見えてきます。</p>
		<p>売上などの傾向が明らかになったら、各リピート回数における再購入率も年単位で集計します。2回目の再購入率は「2回目の購入顧客数÷新規購入顧客数」で算出でき、3回目の再購入率は「3回目の購入顧客数÷2回目の購入顧客数」で算出できます。このようにして4回目、5回目と計算してください。</p>
		<p>以上の再購入率の傾向を読み取ると、多くの場合、2回目の購入に至る顧客数が少ないという結果が出ます。</p>
		<p>このパターン以外にも、リピートにはさまざまな状況があるため、グラフを見ながら傾向と課題を読み取ってください。この方法を用いれば、どの時点の顧客をフォローすべきかがわかります。</p>
	</section>


