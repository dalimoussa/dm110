	<section id="m01">
		<h2 class="midashi02">リピート率とは</h2>
		<p>商品・サービスを購入したすべての顧客のうち、どのくらいの顧客が再度購入したかを示す割合をリピート率といいます。リピート率が高いほど、顧客がその商品・サービスに満足し、もう一度利用したいと考えていることがわかります。</p>
		<p>リピート率は売上に直結する重要な指標です。マーケティングでは、売上だけでなく、リピート率も目標の一つにしてください。</p>

		<h3 id="m01-1" class="midashi03">リピート率の計算方法</h3>
		<p>リピート率は以下の計算式で求められます。</p>
		<p class="box box--blue">リピート率 ＝ 一定期間内のリピート顧客数 ÷ 累計の新規顧客数 × 100</p>
		<p>あるいは</p>
		<p class="box box--blue">当月のリピート率 ＝ 当月のリピート購入者数 ÷ 前月までの購入者数 × 100</p>
		<p>期間を指定せずリピート率を計算する場合もあれば、回数を絞り、1回目のリピート率、2回目のリピート率をそれぞれ計算する場合もあります。いつどの段階のリピート率を重視するかによって、リピート率算出に用いる数値を変えてください。</p>

		<h3 id="m01-2" class="midashi03">リピーター率との違い</h3>
		<p>リピート率と似ているマーケティング用語に、リピーター率があります。リピーター率は一定の期間内に商品・サービスを購入した全顧客のうち、何割がリピーターかを示す数値です。以下の計算式で求められます。</p>
		<p class="box box--blue">リピーター率 ＝ 一定期間内のリピート顧客数 ÷ 一定期間内の総顧客数 × 100</p>
		<p>あるいは</p>
		<p class="box box--blue">当月のリピーター率 ＝ 当月のリピート購入者数 ÷ 当月の購入者数 × 100</p>
		<p>リピーター率が高いほどリピート顧客数は多くなりますが、リピーター率が高すぎた場合、新規顧客を獲得できていないことを意味します。</p>
		<p>そのため、マーケティングでは、リピーター率よりもリピート率のほうが重視されます。リピーター率は、リピート率を評価する一指標に過ぎないからです。</p>
	</section>


	<section id="m02">
		<h2 class="midashi02">リピート率の重要性</h2>
		<p>リピート率は商品・サービスの広告効果を測る重要な指標です。効果を正しく測定できれば、必要な施策に注力し、不要な施策をそぎ落とせます。</p>
		<p>また、新規顧客獲得にかかるコストは、既存顧客のつなぎとめにかかるコストより高くなります。リピート率が高いほど、顧客獲得にかかるコストを低く抑えられるため、増収が見込めます。</p>
		<p>実際に、顧客離脱を5％防ぐことで、利益が25％増えるといわれています。メディアボックスを利用しているお客様のなかには、離脱率を5％防ぎ、実質的に30％以上の粗利が増えた方もいます。</p>
		<p>リピート率を向上させるためには、ニュースレターやダイレクトメール（DM）などを利用して顧客との接触頻度を増やし、より深い信頼関係を築けるように努めることが重要です。売上がなかなか増加せず悩んでいる方は、ぜひリピート率向上のための施策を実行してください。</p>
	</section>


