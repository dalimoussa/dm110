		<h3 id="m03-4" class="midashi03">顧客との接触回数を増やす</h3>
		<p>一度関係ができた顧客との接触回数を増やすのも、リピート率を上げる施策として有効です。接触回数が増加すると、顧客により商品やサービスを認知してもらえるようになります。</p>
		<p>ある商品の1ヵ月の平均的なリピート率が、60％だった場合を考えてみます。商品を購入した顧客が1,000人いたと仮定すると、1ヵ月後のリピート数は600人（1,000人×60％）になります。以降、リピート率60％を維持できれば、1年間の延べ購入者数は2,496人となり、当初獲得した顧客1,000人のおよそ2.5倍にのぼります。</p>
		<p>既存顧客をつなぎ止めるには、新規顧客獲得ほどのコストはかかりません。高い割合でリピートを継続してもらえれば、販促のコストパフォーマンスが良くなります。</p>
		<p>一度、商品・サービスを購入してもらったからといって安心せず、リピートしてもらえるように努めてください。</p>

		<h3 id="m03-5" class="midashi03">リピーターをフォローする</h3>
		<p>一度リピートしてもらった顧客にさらにリピートしてもらうには、リピーター限定の特典を用意するなど、リピーターになるメリットを増やすのも効果的です。</p>
		<p>また、業種・業態にもよりますが、同じ商品でも、リピート回数が増えるにつれ価格が安くなっていくシステムにしたことで、顧客の離脱率が下がった例もあります。</p>
		<p>購入後のサポートも、リピートにつながりやすい施策の一つです。サポートの具体例には、購入後のトラブル対応、より効果的な商品・サービスの利用方法の発信、メンテナンス時期のお知らせなどが挙げられます。</p>
		<p>商品・サービスをリピートする魅力やリピーターとしての特別感、商品・サービスへの愛着や親近感がわくような施策を実行してください。</p>
