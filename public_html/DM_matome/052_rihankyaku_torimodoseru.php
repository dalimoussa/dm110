	<section id="m01">
		<h2 class="midashi02">離反顧客とは「購入経験はあるが、現在は離れてしまった状態の顧客」のこと</h2>
		<p>初めに、離反顧客の概要を解説します。</p>

		<h3 id="m01-1" class="midashi03">休眠顧客との違い</h3>
		<p>離反顧客とは、自社商品・サービスを購入した経験があるものの、「再購入しない」「解約する」などして、自社から離れてしまった顧客のことです。</p>
		<p>離反顧客と似た言葉に「休眠顧客」があります。休眠顧客は、以前は自社商品・サービスを利用していたものの、現在はまったく利用していない顧客です。</p>
		<p>この説明だけ聞くと、離反顧客と休眠顧客は同じような意味に感じられるかもしれません。たしかに、双方を明確に区別するのは難しいですが、離反顧客は「商品・サービスに何らかの不満を持ち、すでに他社に乗り換えている」ケースが多いのがポイントです。</p>
		<p>一方、休眠顧客の場合は、過去に利用していた商品・サービスにマイナスイメージは持っておらず、単に長期にわたって利用がない状態を指します。</p>
		<p>本記事では離反顧客へのアプローチについて解説しますが、休眠顧客へのアプローチについては、以下の記事で解説しています。併せてご覧ください。</p>
		<p><a href="https://www.dm110.jp/DM_matome/Kyuumin_DM/"><img src="/images/DM_matome/btn_Kyuumin_DM.png" width="760" height="126" alt="休眠顧客向けのDM作成のコツはこちら" decoding="async" loading="lazy"></a></p>

		<h3 id="m01-2" class="midashi03">離反顧客を取り戻すのは休眠顧客よりも難しい</h3>
		<p>休眠顧客は、自社商品・サービスについて単に忘れているだけの可能性が高いため、魅力をあらためて認識してもらえれば、再び長く利用してもらえる見込みがあります。</p>
		<p>しかし、離反顧客はすでに他社に乗り換えており、厳密にいうともう「自社の顧客」ではありません。何らかの不満が他社へ乗り換えた原因となっているなら、その原因を見極め、解消する必要があります。</p>
		<p>このような点から、離反顧客を取り戻すのは簡単ではないといえます。</p>
	</section>


	<section id="m02">
		<h2 class="midashi02">顧客が離反するおもな原因は5つ</h2>
		<p>ここでは、顧客が離反してしまう代表的な原因を解説します。</p>
		<p><img src="/images/DM_matome/rihankyaku_torimodoseru_sub1.jpg" width="1560" height="1000" alt="顧客が離反するおもな原因は5つ" decoding="async" loading="lazy"></p>

		<h3 id="m02-1" class="midashi03 u-mt0">企業と顧客とのつながりの薄さ</h3>
		<p>新規顧客の離反原因として多いのが、企業が顧客と一定の関係を築けないことです。</p>
		<p>具体的に「◯◯という不満がある」というわけではなく、企業やブランド、商品・サービスに対する顧客の理解が浅く、愛着を持てていないのが特徴です。</p>
		<p>そのため、2回目の購入のときには商品・サービスのことを忘れており、選択肢に入れてもらえません。</p>

		<h3 id="m02-2" class="midashi03">商品やサービスへの不満</h3>
		<p>商品やサービスへの不満も、代表的な離反原因です。例えば、次の例が挙げられます。</p>

		<div class="box box--yellow">
		<ul class="list-circle">
			<li>既存ラインナップではニーズが満たされない</li>
			<li>在庫不足で必要なときに購入できない</li>
			<li>高価格で費用対効果が悪い</li>
			<li>欠陥や不具合が見られる</li>
		</ul>
		</div>

		<p>離反顧客は、このような不満を複数抱えていた可能性もあります。「トレンドに合う新商品が定期的に出る」「必要なときに確実に購入できる」など、競合他社の商品のほうが魅力的に感じられてしまうかもしれません。</p>

		<h3 id="m02-3" class="midashi03">顧客へのコミュニケーションに対する不安・不満</h3>
		<p>商品やサービスには満足していても、店舗での接客・コールセンター・カスタマーサービスなどでの顧客対応へ不満を抱いてしまうと、離反につながります。</p>
		<p>また、ECサイトの使いにくさや、注文・解約方法のわかりにくさなど、商品・サービスの購入に関するやり取りの方法への不満も考えられます。</p>

		<h3 id="m02-4" class="midashi03">購入動機の消失</h3>
		<p>次の例のように、顧客の年齢や家族構成の変化、住所の変更などで、商品への需要がなくなるケースがあります。</p>
		<p class="u-mb0">（例）</p>
		<table class="table01 u-mt0">
			<tr><th>対象商品</th><th>離反理由</th></tr>
			<tr><td>20代女性をターゲットとしている衣料品</td><td>年齢を重ね、デザインが合わなくなった</td></tr>
			<tr><td>一人暮らしの大学生・社会人向けの家電製品</td><td>結婚する・子どもが生まれるなどして、これまでの大きさや機能では不十分になった</td></tr>
		</table>

		<p class="u-mt30">このようなケースでは、同一の商品・サービスで顧客を呼び戻すことは困難です。しかし、関連商品などを提案する「クロスセル」や、過去に購入した商品と同種でより高価格帯の商品を提案する「アップセル」のアプローチを試みる余地はあります。</p>

		<h3 id="m02-5" class="midashi03">金銭的理由</h3>
		<p>企業やブランド、商品・サービスに対する信頼や愛着はあっても、顧客が許容できる価格のラインを超えている場合、離反につながります。これは、先述した「高価格で費用対効果が悪い」という離反原因とは別物です。</p>
		<p>商品・サービスの費用対効果には納得していても、顧客の生活環境が変わる・収入が減ることなどにより、その商品・サービスに割ける予算が減ることがあります。その結果、「欲しいけれど購入できない」といった状況になってしまうのです。</p>
		<p>また、顧客のなかでの優先順位が変わり、ほかの商品・サービスの購入を優先してしまうことでも、同様に予算が減って離反が起こり得ます。</p>
		<p>ただし、顧客自身の金銭的理由で離反したケースでは、商品・サービスへの信頼や愛着が衰えなければ、将来的に戻ってきてくれる可能性はあります。</p>
	</section>


	<section id="m03">
		<h2 class="midashi02">離反顧客へのアプローチは新規顧客獲得より重要</h2>
		<p>売上の向上を目指そうとすると、どうしても新規顧客の獲得に目を向けがちです。</p>
		<p>しかし、新規顧客の獲得は「認知してもらう」や「関心を高める」といった初期のアプローチから始まるため、時間やプロモーション費用がかさみます。ほとんどの業種で、新規顧客獲得コストはさらに上昇傾向です。</p>
		<p>一方の離反顧客は、一度は商品・サービスを購入した経験があることから、新規顧客よりも少ないステップで購入を促進できます。すなわち、ゼロから新規顧客を開拓するよりも、離反顧客へのアプローチに力を入れたほうが効率的なのです。</p>
	</section>


