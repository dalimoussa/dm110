	<section id="m01">
		<h2 class="midashi02">DMでの集客のカギは「ターゲット設定」と「開封率」</h2>
		<p>ここでは、DMの集客効果を考えるうえで欠かせない、「ターゲット設定」と「開封率」について解説します。</p>

		<h3 id="m01-1" class="midashi03">ターゲット設定</h3>
		<p>集客する際は、「顧客となり得る人」を集めることが大切です。そのためには、自社の商品やサービスに合わせてターゲットを設定する必要があります。</p>
		<p>DMには、設定したターゲットに直接アプローチできる利点がありますが、ターゲット設定がおろそかな状態だと、たとえ集客できたとしても、最終的に商品やサービスの利用・購入につながらない顧客ばかりが集まるといった状況になりかねません。</p>
		<p>一般顧客向けのDMなら、年齢や性別、居住地、年収などを、企業向けのDMなら、業界のニーズや企業が抱える課題、企業規模などを明確に設定することが重要です。</p>
		<p>内容やオファー（特典）をターゲットに合わせて決めれば、より刺さりやすいDMを作成でき、効果の薄いDMを作成してしまうリスクを避けられます。</p>

		<h3 id="m01-2" class="midashi03">開封率</h3>
		<p>ターゲットが商品やサービスの存在を知らなければ、集客にはつながりません。商品やサービスを認知してもらうためのDMを作成しても、そもそも開封してもらえなければ意味がないのです。</p>
		<p>そこで、DMでの集客は、ターゲットに合わせた内容・オファーにするのはもちろんのこと、開封率も重視する必要があります。具体的には、ターゲットが開封したくなるようなデザイン・キャッチコピーなどにこだわってください。</p>
		<p>開封率を高めるためのコツなどについては、以下の記事で詳しく説明しています。併せてご覧ください。</p>
		<p><a href="https://www.dm110.jp/DM_matome/DM_kaifuuritu/"><img src="/images/DM_matome/btn_DM_kaifuuritu.png" width="760" height="126" alt="DM開封率の詳細はこちら" decoding="async" loading="lazy"></a></p>
	</section>


	<section id="m02">
		<h2 class="midashi02">DMの集客効果を最大化するための5つのポイント</h2>
		<p>先述の内容を踏まえたうえで、集客に効果的なDMにするためには、さらなるポイントがあります。ここでは、DMの集客効果を高めるためのポイントを5つ解説します。</p>
		<p><img src="/images/DM_matome/DM_syuukyaku_sub1.png" width="1500" height="1250" alt="DMの集客効果を最大化する5つのポイント" decoding="async" loading="lazy"></p>

		<h3 id="m02-1" class="midashi03">既存顧客にアプローチする</h3>
		<p>「集客」と聞くと、新規顧客をターゲットにするものとイメージする方もいるかもしれません。</p>
		<p>しかし、新規顧客を集客するのにかかるコストは上昇しています。また、接触したことのない個人の新規顧客へ突然DMを発送すると、「なぜ住所を知られているのか」と警戒心を持たれ、逆効果になるケースもあります。</p>
		<p>そのため、新規顧客よりも費用対効果が高い、既存顧客（購入経験のある顧客）を中心にアプローチするのがおすすめです。一部の業種や業界を除くと、既存顧客へDMを発送している会社は少ないため、既存顧客へDMを出すこと自体が差別化につながります。</p>
		<p>効果的なDMの発送先に関しては、以下の記事も併せて参考にしてください。</p>
		<p><a href="https://www.dm110.jp/DM_matome/hassousaki/"><img src="/images/DM_matome/btn_hassousaki.png" width="760" height="126" alt="DMの発送先の詳細はこちら" decoding="async" loading="lazy"></a></p>

		<h3 id="m02-2" class="midashi03">顧客のニーズが高いタイミングでDMを送る</h3>
		<p>DMを発送する際は、タイミングを検討してください。ターゲットとなる顧客のニーズが低いタイミングでDMを送ると、開封率や反応率が上がらず、効果が見込めません。</p>
		<p>具体的には、顧客が商品・サービスを実際に利用すると考えられるタイミングではなく、より前の「顧客が購入準備を始めるタイミング」で送付するのがポイントです。</p>
		<p>例えば、対象となるのがリース商品の場合は、リースが満了するタイミングではなく、「顧客が買い替えを検討するタイミング」でのDM発送を意識します。</p>
		<p>ただし、顧客がどのタイミングで商品に不満を抱くか予想がつかない場合もあるため、買い替えたくなるような機能を紹介した内容や、お得情報などを盛り込んだDMを定期的に発送することも重要です。</p>
		<p>また、実際にお客様がどのタイミングで商品を再度購入したいと思うかはわかりません。データに基づいて考えるのも一つの手ですが、定期的にDMで案内を送ることで接触頻度が増やし、離脱率を下げるのもおすすめです。その際は、費用対効果を見るためのテストを行ってください。</p>

		<h3 id="m02-3" class="midashi03">顧客のレスポンスやアクションを促す</h3>
		<p>DMを受け取った顧客が、DMを読むだけでなく、購入や問い合わせなどの具体的な行動を起こせるよう、次のような工夫をしてください。</p>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>DMを受け取った人限定のクーポン券を付ける</li>
			<li>特別セールの情報を載せる</li>
			<li>商品の申込書を添付する</li>
			<li>企業の連絡先を記載する</li>
		</ul>
		</div>
		<p>特にDMの強みの一つは、プレゼントや試供品などの封入物を入れられることです。メール便でDMを送付する際は、厚さ2cm以下になるよう意識しながら、封入物を選択してください。</p>
		<p>これにより、商品やサービスに興味を持ってくれた顧客の取りこぼしが少なくなります。</p>

		<h3 id="m02-4" class="midashi03">インターネットとDMを連携させる</h3>
		<p>アプローチする対象が新規顧客でも既存顧客でも、インターネットとDMを連携させる方法は有効です。</p>
		<p>具体的には、集客施策をDMで完結させるのではなく、DMから自社ホームページへ誘導する方法です。DMでは伝えきれない情報をホームページで提示し、商品やサービスの必要性をより実感してもらったうえで、利用・購入につなげます。効果的に訴求するために、DMの内容に合わせて、ホームページ内に専用のページを追加する方法もおすすめです。</p>
		<p>通常、集客施策として、インターネットの検索サイトでホームページを上位表示させたり、インターネット広告を打ち出したりするには、大変な労力とコストがかかります。</p>
		<p>コロナ以降、インターネットとDMを連携させて集客につなげる方法が増え始めています。自社で直接発送先を絞り、その発送先に合った内容やプレゼントを入れたDMを送り、興味を持ってもらうことでホームページに誘導します。</p>

		<h3 id="m02-5" class="midashi03">DMテストを繰り返し行う</h3>
		<p>効果の高いDMにするには、一度に2種類以上のDMを発送し、顧客の反応を比較することが不可欠です。</p>
		<p>ターゲット設定や開封率を意識してDMを作成できたとしても、それが最適なDMかは誰にもわかりません。そこで、複数のDMの成果を比較するDMテストを実施します。</p>
		<p>DMテストをする際には、キャッチコピーやオファーの種類など、1ヵ所（1要素）のみを変更するのがポイントです。</p>
		<p>ただし、DMテストのたびに全顧客にDMを送ると、コストやデータ収集の時間がかかります。効率的にデータを蓄積していくためには、発送先を全体の10％程度に絞り、小さいテストを繰り返すことが大切です。</p>
		<p>DMテストに関しては、以下の記事も併せて参考にしてください。</p>
		<p><a href="https://www.dm110.jp/DM_matome/DM_Abtest/"><img src="/images/DM_matome/btn_DM_Abtest.png" width="760" height="126" alt="DMテスト（ABテスト）のコツはこちら" decoding="async" loading="lazy"></a></p>
	</section>


	<section id="m03">
		<h2 class="midashi02">DMで集客を行う際の注意点と対策</h2>
		<p class="u-mt0"><img src="/images/DM_matome/DM_syuukyaku_sub2.jpg" width="1980" height="1320" alt="送れるもの・送れないもの" decoding="async" loading="lazy"></p>
		<p>最後に、DMで集客する際の注意点や対策を紹介します。</p>


		<h3 id="m03-1" class="midashi03">コストの高さ</h3>
		<p>ほかの集客方法に比べると、DMの発送にかかるコストは割高な傾向にあります。</p>
		<p>そこでおすすめなのが、「ゼロコストDM」から始めることです。ゼロコストDMとは、次のような工夫をし、お金をかけずにDMを顧客の手元に届けることを意味します。</p>

		<div class="box box--yellow">
		<ul class="list-circle">
			<li>商品の納品書や請求書に同梱する</li>
			<li>商品に同梱する</li>
			<li>顧客を訪問する際に持参する</li>
		</ul>
		</div>

		<p>また、最初から「全部で◯件のDMを送らなければならない」と考えないことも大切です。予算が限られている場合、まずは予算内で発送できる件数に発送先を絞り、比較テストを実施します。そのテスト結果により得られたデータをもとに、予算交渉する方法が有効です。</p>
		<p>その他、コストを抑えるためには、次のような方法もあります。</p>

		<div class="box box--yellow">
		<ul class="list-circle">
			<li>封筒タイプのDMではなく、A4ハガキDMにする</li>
			<li>自社ホームページと連携させ、DMの枚数を減らす</li>
		</ul>
		</div>

		<h3 id="m03-2" class="midashi03">印刷・発送の手間</h3>
		<p>自社でDMを印刷・発送する場合は、次のような作業が発生するため、一定の手間や時間がかかります。</p>

		<div class="box box--yellow">
		<ul class="list-circle">
			<li>紙の裁断</li>
			<li>インク・紙のセッティング</li>
			<li>きちんと印刷できているかのチェック</li>
			<li>封筒への封入・封緘</li>
			<li>宛名シールの貼り付け</li>
			<li>検品</li>
			<li>発送</li>
		</ul>
		</div>

		<p>加えて、上記作業を行う場所や、完成したDMを保管する場所も確保しなければなりません。これらの点を踏まえ、自社での対応が現実的でない場合は、DM発送代行業者への外注を検討してください。</p>
	</section>


