	<section id="m01">
		<h2 class="midashi02">手書き風フォントがDMで効果的な理由</h2>
		<p>新規顧客向けのDMは、反応率が1％あれば成功といわれます。</p>
		<p>ここで、手書きのDMを以下の方法で発送した事例を紹介します。</p>
		<ul class="list-circle u-ml30 u-mr10">
			<li>1回目：発送部数60通</li>
			<li>2回目：発送部数260通（1回目の送付先＋200通）</li>
		</ul>

		<p>この事例では、1回目は1件の成約、2回目は3件の成約につながりました。DMの反応率は、「レスポンスの件数÷DMの発送部数×100」で求められるため、以下のとおりとなります。（※）</p>

		<ul class="list-circle u-ml30 u-mr10">
			<li>1回目：1件÷60通×100≒1.67％</li>
			<li>2回目：3件÷260通×100≒1.15％</li>
		</ul>

		<p>（※ 本来、DMの反応率を計算する際は、「問い合わせ」「資料請求」などの行動（レスポンス）も含めますが、今回は便宜的に成約に至った件数のみを考慮します。）</p>
		<p>1回目が1.67％、2回目が1.15％と、成約に至った件数のみを考慮しても、反応率が1％を超えていることがわかります。</p>
		<p>このように、手書きのDMの反応率が高まりやすい理由は、次のとおりです。</p>

		<div class="box box--yellow">
		<ul class="list-circle">
			<li>直筆の郵便物を受け取る機会が少なく、興味をそそられるため</li>
			<li>大切な内容が書かれているのではと思うため</li>
			<li>自分のためにひと手間かけてくれたと感じるため</li>
			<li>手紙のように思えて捨てにくくなるため</li>
			<li>温かみがあり信頼感が増すため</li>
			<li>売り込み感が減るため</li>
		</ul>
		</div>

		<p>なお、今回紹介した事例の商品・サービスの概要は以下のとおりです。</p>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>年次契約（継続率が高いサービス）</li>
			<li>BtoB商品</li>
			<li>年間契約1件あたり50万円以上</li>
		</ul>
		</div>
		<p>ただし、DMの発送部数が多い場合、すべてのDMを直筆で書くのは現実的ではありません。そこでおすすめなのが、手書き風フォントです。</p>
