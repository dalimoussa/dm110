	<section id="m02">
		<h2 class="midashi02">手書き風フォントのメリット</h2>
		<p>ここでは、DMで手書き風フォントを活用するメリットを解説します。</p>

		<h3 id="m02-1" class="midashi03">人の温かみを演出できる</h3>
		<p>手書き風フォントにはアナログ感があり、人間味が出るのが特徴です。DMを作成した「人」の存在を感じることで、信頼度が高まりやすくなります。</p>
		<p>特に、顧客の声や顧客への問いかけ、挨拶文など、会話調の文章にマッチします。個性や味わいを演出したいケースなどにもおすすめです。</p>

		<h3 id="m02-2" class="midashi03">やわらかい印象を与えられる</h3>
		<p>手書き風フォントの多くは丸みを帯びているため、ゴシック体や明朝体にはない「やわらかさ」を出せるのもメリットです。やわらかい印象を活かして、子ども向けDMのフォントにも使えます。</p>
		<p>また、売り込み感を抑えることで受取人の警戒心を下げられ、反応率の向上につながります。</p>

		<h3 id="m02-3" class="midashi03">興味を引く</h3>
		<p>画一的なフォントで印刷された郵便物と比べると、直筆の郵便物を受け取る機会は多くありません。そのため、手書き風フォントには、一目見たときに興味を引く効果があります。</p>
		<p>また、「DMらしさ」が薄れ、手紙のように「大切なものが書かれているのでは」と興味を持たれやすくなります。</p>
		<p>さらに、実際に直筆で書いているわけではありませんが、手書きの「丁寧」な印象が残り、「他の人とは異なる対応を取ってくれた」などと特別感を抱いてもらえるのもメリットです。</p>
	</section>


	<section id="m03">
		<h2 class="midashi02">手書き風フォントのデメリット</h2>
		<p>DMで手書き風フォントを使用する際には、いくつか知っておくべき点もあります。ここでは、手書き風フォントの3つのデメリットを紹介します。</p>

		<h3 id="m03-1" class="midashi03">手書きではないことにあとから気付かれると落胆されやすい</h3>
		<p>フォントの種類によっては、直筆ではないことに気付きにくいものもあります。</p>
		<p>実際に、ご年配の方が手書き風フォントのDMを受け取った際に、手書きだと思い込んで感動したケースがありました。しかし、その後ご家族から手書き風フォントであると知らされ、落胆されたとのことです。</p>
		<p>このように、あとから直筆ではないことに気付かれると、相手の落胆を招く可能性があるため注意が必要です。</p>

		<h3 id="m03-2" class="midashi03">フォントによっては整った印象にならない</h3>
		<p>独特の丸みがあり、可愛らしさを強調したフォントは、一見幼稚な印象になりがちです。また、リアルな手書き感のあるフォントの場合は、統一感が薄れ、煩雑に見えてしまうことがあります。</p>
		<p>フォントの選び方によっては、DMの見栄えが悪くなってしまうため、用途を踏まえて適切なフォントを選ぶことが大切です。</p>

		<h3 id="m03-3" class="midashi03">フリーフォントが多い</h3>
		<p>手書き風フォントの多くは、個人が開発したフリーフォントであり、フォントごとに利用規約が異なります。フォントを使用する際は、それぞれの利用規約をあらかじめ確認してください。</p>
		<p>また、フォントの使用によるトラブルには責任を持ってもらえない点や、急に配布を停止されフォントが使用できなくなる可能性がある点も、考慮する必要があります。</p>

