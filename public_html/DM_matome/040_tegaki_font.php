	<section id="m05">
		<h2 class="midashi02">DMにおすすめ！手書き風フォント3選</h2>
		<p>先述のとおり、手書き風フォントにはさまざまな種類があります。どれを選べば良いか迷ってしまう方のために、DMにおすすめのフォントを3つ紹介します。</p>

		<h3 id="m05-1" class="midashi03">toCなら「みかちゃんフォント」が基本</h3>
		<p>個人向けDMの場合は、「みかちゃんフォント」がおすすめです。みかちゃんフォントは、親しみやすく可愛らしいフォントで、JIS第2水準漢字など、比較的難しい漢字も収録されています。</p>
		<p>手書きであるかのように感動してもらえることがあるのも、このフォントです。</p>

		<h3 id="m05-2" class="midashi03">幅広い用途に使える「ちはやフォント＋」</h3>
		<p>「ちはやフォント＋」は、やわらかい雰囲気と丁寧さを感じさせるフォントです。手書きながらも整った印象があり、DMを含め幅広い用途で活用可能です。また、みかちゃんフォントと同様に、女性向けの可愛らしいデザインにもマッチします。</p>
		<p>ちはやフォント＋は、漢字のなかでも特に使用頻度の高いJIS第1水準漢字に対応しています。</p>

		<h3 id="m05-3" class="midashi03">力強い印象を与えたいなら「藍原筆文字楷書」</h3>
		<p>可愛らしさよりも力強さを重視したい方におすすめなのが、毛筆の太字フォント「藍原筆文字楷書」です。</p>
		<p>力強さと読みやすさを兼ね備えており、ひらがな・カタカナ・漢数字・記号など対応範囲が広いため、さまざまな用途に活用できます。例えば、DMのほか、チラシや年賀状などにも用いられています。</p>
	</section>


