		<p>なお、材質によってコストが大きく変わる点には注意が必要です。紙封筒に印刷するよりも、透明封筒の中に入れる紙に印刷するほうが、コストを抑えられます。また、DMテストの際も、紙封筒は何度も封筒印刷が必要になるため、透明封筒のほうがコスト面では優れています。</p>
