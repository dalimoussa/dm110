	<section id="m04">
		<h2 class="midashi02">DMを封筒で送るデメリット</h2>
		<p>メリットの多いDM封筒ですが、デメリットもあります。</p>
		<p>紙封筒の場合、封筒料金や印刷料金などのコストがかかります。発送方法によってはさらにコストがかかるため、費用をトータルで把握しなければなりません。</p>
		<p>DM封筒は取り扱いにも注意が必要です。紙封筒は湿度や温度の影響を受けやすく、また透明封筒の場合は、寒さにより封筒が壊れる可能性もあります。封筒の材質やメーカーにより最低温度には差が出るため、発送する時期や地域によって最適なものを選ばなければなりません。</p>
		<p>なお、透明封筒はビニールで宛名ラベルは紙のため、分別ゴミとして扱う必要がある場合があります。</p>
	</section>


