		<h3 id="m01-1" class="midashi03">定形封筒と定形外封筒の違い</h3>
		<p>封筒は定形封筒と定形外封筒に分けられ、送れるもののサイズや重さ、発送時にかかる料金が異なります。</p>

		<h4 class="midashi05">定形封筒</h4>
		<p>短辺9cm～12cm以内、長辺14cm～23.5cm以内、厚さ1cm以内、封入物と合わせた重さ50g以内のもの</p>

		<h4 class="midashi05">定形外封筒</h4>
		<p>定形封筒以外のもの。さらに規格内と規格外に分かれる</p>
		<p>規格内：短辺9cm～25cm以内、長辺14cm～34cm以内、厚さ3cm以内、封入物と合わせた重さ1kg以内<br>
			規格外：短辺、長辺、厚さの合計が90cm以内、長辺60cm以内、封入物と合わせた重さ4kg以内</p>

		<p class="u-mt30">一般的に、定形封筒より定形外封筒のほうが料金は高くなり、また、定形外封筒の場合、規格内より規格外のほうが料金は高くなります。</p>

		<h3 id="m01-2" class="midashi03">封筒サイズの選び方</h3>
		<p>封筒サイズは、発送料金と封入内容を考慮して選択してください。</p>
		<p>封筒サイズが異なると、発送料金も異なります。また、封入時に内容物を折る作業が必要な場合は、折作業料金が必要になるため、発送代行料金も高くなるのです。</p>
		<p>なお、クロネコDM便を利用して、上記の表で示したサイズの封筒を送る場合、発送料金がサイズ問わずすべて同じになります。</p>
		<p>さらに、封入内容によっても封筒サイズは変わります。</p>
		<p>封入物を三つ折りにすると反応率が下がる可能性があるため、例えば、封入枚数が多い、紙が厚い、封入物にきれいな写真やイラストが使われている場合は、折らずに封入できる封筒が必要です。一方、手書きのDMやVIPに送るDMの場合は、洋形4号や洋形4号中2重封筒など、小さめの封筒が適しています。</p>
