		<p>DMの発送コストを抑える際、封筒にまつわるコストは見逃されやすい傾向です。ここでは、封筒のサイズ、材質、厚さをポイントに、発送コスト削減の方法を紹介します。</p>

		<h3 id="m05-1" class="midashi03">封筒のサイズを変更する</h3>
		<p>郵便局で発送する場合、封筒のサイズが変わると発送料金も変わります。定形郵便物で送れる最大のサイズは長形3号封筒のため、長形3号までサイズを小さくできれば、発送費の削減につながります。</p>
		<p>ただし、長形3号封筒にA4用紙を入れようとすると、三つ折りにしなければなりません。折作業料金が追加されるため、発送料金が安くても全体だと割高になってしまう可能性があります。</p>
		<p>一方、クロネコDM便や佐川飛脚ゆうメール便は、封筒サイズを問わない料金設定のため、折作業料金が発生しないA4封筒や角形2号封筒で発送するのがおすすめです。</p>
		<p>発送料金だけでなく、折作業料金も含めて総合的に封筒サイズを判断してください。</p>

