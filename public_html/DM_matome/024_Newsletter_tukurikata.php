		<p><a href="https://www.dm110.jp/Newsletter_daikou_kaisya.html"><img src="/images/DM_matome/btn_Newsletter_daikou_kaisya.png" width="760" height="126" alt="おすすめのニュースレター作成代行会社はこちら" decoding="async" loading="lazy"></a></p>

		<h3 id="m06-4" class="midashi03">顧客に合わせてフォントを選択する</h3>
		<p>ニュースレターの見た目のなかでも、特にフォントは、対象となる顧客の性別や年齢を考えて選びます。</p>
		<p>注目を集めるなら目立つフォントを選べば良いと考えがちですが、「目立つ＝見慣れていない」ということでもあり、逆に読みにくい印象を与える可能性があります。</p>
		<p>そのため、多くの人が見慣れているMicrosoft Wordの基本フォント（MS 明朝）や、Microsoft Excelの基本フォント（MS Pゴシック）のほか、縦書きの場合は、新聞で使われているフォントを基準にするのがおすすめです。</p>
		<p>また、対象顧客の年齢が50代以上の場合、見やすいフォントを選んだうえで、A4をB4またはA3に拡大して印刷する方法が有効です。</p>
		<p>ニュースレターでは実際に手書きしたものを原本にして、それを印刷する方法がよく使われます。あるいは手書きフォントを使う方法もあります。手書きにすることにより、目立ち度と好感度は大きく変わります。</p>

		<h3 id="m06-5" class="midashi03">タイトルは慎重に設定する</h3>
		<p>ニュースレターのタイトルには、「絶対にこうでなければならない」という決まりはありません。ただし、ニュースレターのタイトルは通常途中で変更はできないため、慎重に考えてください。</p>
		<p>タイトルはニュースレターの印象を左右するため、顧客の立場から見て「読みやすいか」「わかりやすいか」「電話口でも言いやすいか」を考える必要があります。したがって、タイトルの案ができてもすぐには決めず、数日経ってからあらためて見直してください。</p>
		<p>一般的に長続きしている会社のニュースレターのタイトルは、以下のとおりです。</p>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>短いタイトル</li>
			<li>わかりやすいタイトル</li>
			<li>親しみやすいタイトル</li>
			<li>絞り込みすぎていないタイトル</li>
		</ul>
		</div>
		<p>号数が進むにつれて愛着が湧いてくるため、突飛なタイトルは避けることをおすすめします。また、会社名や商品名をそのまま使用したタイトルや、無駄に文字数が多いタイトル、読んだだけでは内容のイメージが湧かないタイトルは、避けたほうが無難です。</p>

		<h3 id="m06-6" class="midashi03">専門用語の使用は避ける</h3>
		<p>理解できない言葉が3回続くと、顧客がニュースレターを読むのをやめてしまう確率が高まります。顧客に出すニュースレターは、基本的に専門用語をなるべく使わず、小学生や中学生が読んでもわかる言葉に置き換えてください。</p>
		<p>専門用語の使用が避けられない場面では、イラストや表・グラフを使うなど、視覚的にわかりやすくする工夫が必要です。</p>
		<p>また、専門用語の意味を完璧に理解してもらおうとして、長々と説明したり、いろいろな言葉に置き換えたりすることで、さらに難しい内容になるケースがあります。顧客がすべての意味を理解できるに越したことはありませんが、途中で離脱されるリスクを高めないよう注意しなければなりません。</p>

		<h3 id="m06-7" class="midashi03">過度な売り込みは避ける</h3>
		<p>毎回のニュースレターに売り込みの内容が含まれる場合、それはニュースレターではなく、DMやセールスレターだと顧客に認識されます。また、最近は直接的な売り込みをすることで、ニュースレターの反応率が下がる傾向にあります。</p>
		<p>これらの点を踏まえ、ニュースレターに売り込みの内容を含めるなら、3回に1回から5回に1回ほどの頻度にしてください。さらに、初回のニュースレターでは売り込みをせず、顧客との関係がある程度築けてからにすると効果的です。</p>

		<h3 id="m06-8" class="midashi03">同じネタをうまく使い回す</h3>
		<p>ニュースレターを継続して発行しようとすると、「ネタが枯渇する」という悩みが出てきます。</p>
		<p>しかし、顧客はニュースレターの内容をすべて覚えているわけではないため、顧客にとって大切なこと・忘れてほしくないことは、何回書いても問題ありません。実際に、以前のニュースレターと同じネタを取り扱ったときに、「今回の内容は良いですね」などと、初めて見たような反応をする顧客が何人もいらっしゃいました。</p>
		<p>同じ内容を何回も書いたとしても、顧客のためになることなら、ほとんどの場合は不快に思われず、むしろ頭に焼き付けてもらいやすくなります。</p>
		<p>同じネタを使い回す際は、以下のポイントを意識してみてください。</p>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>実例を加える</li>
			<li>実例の内容を変える</li>
			<li>キーワードを変える</li>
			<li>発信者の立場を変える</li>
			<li>対象顧客を変える</li>
			<li>イラストや表を加える</li>
			<li>発行時期を変える</li>
		</ul>
		</div>
		<p>このように見せ方を工夫すれば、同じネタでも印象や文面を変えられます。</p>

		<h3 id="m06-9" class="midashi03">同じ封筒を使う</h3>
		<p>先述のとおり、ニュースレターを送る際はA4透明封筒を使い、中身が見えるようにします。そのおもな目的は、以下の2点です。</p>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>自社からのニュースレターだと顧客がすぐにわかるようにするため</li>
			<li>一目で顧客の興味を引くため</li>
		</ul>
		</div>
		<p>また、中身が見える封筒なら、先入観で捨てられてしまうリスクを減らせます。</p>
		<p>上記の目的を踏まえ、市販のA4透明封筒ではなく、自社独自のニュースレター専用封筒を作っている会社もあります。</p>

		<h3 id="m06-10" class="midashi03">宛名ラベルの位置を考える</h3>
		<p>封筒に貼る宛名ラベルの位置によって、ニュースレターのキャッチコピーの効果が減ってしまったり、伝えたいことが伝わりにくくなったりする可能性があります。そのため、ニュースレターを出す場合は、宛名ラベルの位置まで考えなければなりません。</p>
