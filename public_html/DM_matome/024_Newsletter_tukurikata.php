	<section id="m06">
		<h2 class="midashi02">ニュースレターを成功させる作り方10のコツ</h2>
		<p><img src="/images/DM_matome/Newsletter_tukurikata_sub4.png" width="1500" height="1500" alt="ニュースレター作り方 10のコツ" decoding="async" loading="lazy"></p>
		<p>ニュースレター作成を成功させるためのコツを紹介します。</p>

		<h3 id="m06-1" class="midashi03">継続して発行する</h3>
		<p>ニュースレターは、顧客との接触回数を増やし、顧客とより親密な関係になることを目的とするため、「継続して発行すること」が何よりも重要です。</p>
		<p>しかし、ニュースレターの発行を継続するのは難しくもあります。「ニュースレター作成に割ける時間がない」「テーマやネタが決められない」といった状況になると、発行が数回で途絶えてしまうかもしれません。</p>
		<p>先述のとおり、必要に応じてニュースレター作成代行会社を活用するなど、定期的に発行を続けられる仕組みを整えてください。</p>
		<p>具体的なニュースレターの継続方法としては下記が有効です。</p>

		<h4 class="midashi05">1. ネタ探しは日常の中にある</h4>
		<p>日常のちょっとしたことを気にしながらメモを取ることを心がけてください。</p>
		<h4 class="midashi05">2. 居酒屋のラフな雰囲気のなか、みんなで雑談しながら作成会議をする</h4>
		<p>非常識ですが、少し酔っているときの方が良い案が浮かぶときも少なくありません。どうしても案が出ないときには、居酒屋での出来事を書くという手もあります。</p>
		<h4 class="midashi05">3. スタッフの昔話を聞く</h4>
		<p>小学生や中学生時代のことを聞く方法はよく使われている方法です。意外な面白い話が出てきます。</p>

		<h3 id="m06-2" class="midashi03">ターゲットに合わせた内容にする</h3>
		<p>ニュースレターでは、読み手となる顧客についてきちんと理解し、ニーズに応えなければなりません。「ここでしか手に入らない」と感じてもらえるような情報を中心に、ニュースレターの内容を構成してください。</p>
		<p>ニーズに応えられているか判断するためには、ニュースレターの感想を顧客に直接聞く、読者アンケートを実施するなどの方法がおすすめです。</p>
		<p>ある通販会社では、社長がVIP客のところに訪問し対談をして、その結果をニュースレターやホームページに掲載することで効果を上げています。</p>

		<h3 id="m06-3" class="midashi03">見た目を重視する</h3>
		<p>良いデザイン・構成のニュースレターにするためには、まず、以下のように自社のキャラクターや前提条件を明確にすることが大切です。</p>
		<p>・会社のキャラクター（家族的なのか、組織的なのか）<br>
		・目的（関係性を強化するか、売り込みを少し入れるか）<br>
		・前提条件（親しみやすくするか、理論的にするか）　など</p>

		<p>これらを明確にしたうえで、以下の項目について自社に合うものを考えてみてください。</p>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>写真やイラスト</li>
			<li>フォント</li>
			<li>見出し</li>
			<li>コーナーごとの囲み</li>
			<li>太字や下線などの装飾</li>
			<li>余白の取り方</li>
		</ul>
		</div>

		<p>また、どのような会社でも、ニュースレターの見栄えを良くするために共通するポイントは、以下のとおりです。</p>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>フォントは原則1種類のみにする</li>
			<li>適切な行間を保つ</li>
			<li>1文節は短めにする</li>
			<li>読みやすさを意識して句読点を入れる</li>
			<li>箇条書きできるものは箇条書きにする</li>
		</ul>
		</div>
