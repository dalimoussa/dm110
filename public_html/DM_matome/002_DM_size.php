		<h3 id="m03-2" class="midashi03">（2）インパクトの大きさから選ぶ</h3>
		<p>DMのサイズが大きいほど、受け手が得るインパクトは大きくなります。ただし、A4サイズを超えると、郵便受けに入らないなどの弊害が出ることも想定しておかなければなりません。</p>
		<p>インパクトを重視しつつも弊害を出さないようにするためには、サイズを大きくするのではなく、正方形や円形、型抜きはがきなどの変わった形状にするのがおすすめです。</p>

		<h3 id="m03-3" class="midashi03">（3）載せたい情報量から選ぶ</h3>
		<p>DMの情報量は、反応率に影響します。</p>
		<p>例えば、通常発送できる郵便物のなかで最小サイズの官製はがきは、発送コストも最安ですが、必要な情報を載せるには面積が足りない可能性があります。パンフレットなどを封入することも不可能ですし、申込用紙としても使うのも困難です。そのため、必要な情報を載せきれなかったり、余白がなくなり視覚的に読みにくくなったりして、反応率が下がってしまいます。</p>
		<p>そこで、DMのサイズを選ぶ際には、あらかじめ載せたい情報量を把握してから、サイズを選ぶようにしてください。はがきのサイズを大きくしたくない場合は、圧着式のDMにするのがおすすめです。</p>
