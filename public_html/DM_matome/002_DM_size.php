	<section id="m03">
		<h2 class="midashi02">DMのサイズの選び方</h2>
		<p><img src="/images/DM_matome/DM_size_sub2.jpg" width="1980" height="1320" alt="" decoding="async" loading="lazy"></p>
		<p>DMのサイズは、次の3つの観点を意識して選んでみてください。</p>
		<ol class="list-decimal u-ml30 u-mr10">
			<li>コストと粗利のバランスから選ぶ</li>
			<li>インパクトの大きさから選ぶ</li>
			<li>載せたい情報量から選ぶ</li>
		</ol>

		<p>それぞれの選び方のポイントについて、以下で紹介していきます。</p>

		<h3 id="m03-1" class="midashi03">（1）コストと粗利のバランスから選ぶ</h3>
		<p>新規顧客の獲得や売上の向上を目的にDMを発送する場合、DMにかかるコストだけに注目するのはNGです。</p>
		<p>コスト単体よりも、以下の点を意識してみてください。</p>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>DMコストと粗利額を比較して採算が取れるのか</li>
			<li>狙った顧客を集客できるか</li>
		</ul>
		</div>
		<p>DMは媒体により発送料金が変わるため、「DMコスト＜粗利額」とするためには、ケースに応じて最適な媒体を選ぶことが大切です。つまり、「発送料金が安いから官製はがきを利用する」という選択は、必ずしも適しているとは限りません。</p>
		<p>新規顧客の獲得の成果は、次の計算式で求められる顧客1人あたりの「顧客獲得単価」によって判断できます。</p>

		<p class="box box--blue">顧客獲得単価 ＝ DM発送費用 ÷ 顧客獲得数</p>

		<p>顧客獲得単価は、官製はがきよりも、A4はがきや封筒を使用したDMのほうが安くなることもよくあります。</p>

		<h4 class="midashi04">DMサイズあたりのコスト</h4>
		<p>DMは、情報を多く載せれば反応率が上がるわけではありませんが、DM反応率を上げたい場合はそれなりの文字数が必要になります。例外としてお知らせや割引案内など、内容が単純なものは官製はがきがベターです。</p>
		<p>また、伝えたい内容に加え、申込用紙やパンフレットなどの封入物もある場合は、封入物に合うサイズの封筒も必要です。</p>

