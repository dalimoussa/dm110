		<h3 id="m02-1" class="midashi03">官製はがき</h3>
		<p>官製はがきとは、最初から切手が印刷されてある郵便はがきを指します。第二種郵便物に該当し、発送（購入）料金は、全国一律で1通あたり63円です。</p>
		<p>官製はがきの面積は、A4サイズの4分の1ほどなので、他のサイズのDMと比べると載せられる情報量は限られます。案内や連絡事項など、要点を絞った情報を掲載する際に適してサイズです。</p>

		<h3 id="m02-2" class="midashi03">A4はがき・A4圧着はがき</h3>
		<p>A4はがきやA4圧着はがきは、いわば「官製はがきのA4サイズ版」です。</p>
		<p>官製はがきと同様に、宛名ラベルを貼ればそのまま発送できるため、封入したいA4用紙が1～3枚の場合は、A4はがきやA4圧着はがきの活用を考えてみてください。封筒に用紙を入れる作業がなくなる分、コストダウンにもつながります。また、開封作業なくキャッチコピーなどを見ていただくことができるため、新規顧客向けによく使われます。</p>

		<h3 id="m02-3" class="midashi03">長3封筒</h3>
		<p>長3封筒は、A4用紙を3つ折りにして封入するタイプです。封筒に用紙を入れる作業に加え、用紙を3つ折りにする作業にもコストがかかります。</p>
		<p>定形郵便物なので、発送料金は25g以内なら84円、50g以内なら94円です。</p>
		<p>DM用にはあまり使われません。ただし、特別な人や特別な内容で使用すれば、反応率を上げることができる封筒です。</p>

		<h3 id="m02-4" class="midashi03">角2封筒・A4封筒（透明封筒など）</h3>
		<p>角2封筒・A4封筒は、いずれもA4サイズの封入物ならそのまま入れられるタイプです。小冊子やカタログ、DVD、サンプル品なども、封筒の厚さが原則2cmまでなら同梱できます。載せたい情報量が多くても対応できる点がメリットです。</p>
		<p>クロネコDM便の場合、長3封筒でも角2封筒でも発送料金は同じになります。</p>
