	<section id="m01">
		<h2 class="midashi02">DMのサイズに規定はない！</h2>
		<p>DMのサイズに規定はなく、はがきサイズやA4サイズなど、どのようなサイズのものでもDMとして郵送できます。また、DMは形状についても決まりがありません。そのため、箱型のDMや仕掛けが飛び出すタイプのDMといった、立体的なものも制作可能です。</p>
		<p>ユニークな発想に基づき制作されるDMは、定番サイズのDMよりも、制作コストや発送コストがかかりやすいものの、顧客へインパクトを与えられます。</p>
		<p>箱状や飛び出すDMよりもコストが低い型抜きDMは、反応率を上げたい場合によく使われます。まずはテストしてみることをおすすめします。</p>
	</section>


