	<section id="m05">
		<h2 class="midashi02">まとめ</h2>
		<p>DMのサイズや形状に規定はありませんが、よく使われる定番サイズには、次のような種類があります。</p>

		<div class="box box--yellow">
		<ul class="list-circle">
			<li>官製はがき</li>
			<li>A4はがき</li>
			<li>A4圧着はがき</li>
			<li>長3封筒</li>
			<li>角2封筒</li>
			<li>A4透明封筒</li>
			<li>洋4封筒（手書き封筒で効果があります）</li>
		</ul>
