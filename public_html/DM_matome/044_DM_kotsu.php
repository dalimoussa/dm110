	<section id="m01">
		<h2 class="midashi02">DM文章作成のテクニック＆コツ7選</h2>
		<p>ここでは、DMの文章を作成するうえで知っておきたい、テクニックやコツを紹介します。</p>

		<h3 id="m01-1" class="midashi03">1. 結論を一番初めに書く</h3>
		<p>通常は起承転結で最後に結論を書くのが一般的ですが、DMの場合は初めにお客様の興味を引き付けることができなければ、次に読み進めてもらえません。</p>
		<p>結論を最初に書くだけで生まれる効果は、以下のとおり複数挙げられます。</p>

		<div class="box box--yellow">
		<ul class="list-circle">
			<li>最後まで読まないお客様に言いたいことを伝えられる</li>
			<li>読み進めてもらえる確率が高まる</li>
			<li>成約率が高まる</li>
			<li>全体の文字量を減らせる</li>
		</ul>
		</div>

		<h3 id="m01-2" class="midashi03">2. 「他でもないあなた」を意識</h3>
		<p>DMで重要なのは、「出だし」です。DMの冒頭部分を見て、「このDMは自分に関係がない・自分の役に立たない」と感じると、そこで読むのをやめてしまいます。</p>
		<p>具体的には、「お客様各位」「皆様へ」といった大勢へ呼びかけたDMは、メッセージがぼやけます。そのため、ターゲットとなるペルソナを設定し、「特定の人（あなた）に向けた文章」を書くことがポイントです。</p>
		<p>ペルソナを設定する際は、以下のような項目を細かく検討してください。</p>

		<div class="box box--yellow">
		<ul class="list-circle">
			<li>地域</li>
			<li>業種</li>
			<li>業態</li>
			<li>業歴</li>
			<li>抱えている課題や悩み</li>
			<li>購入した商品・サービス</li>
		</ul>
		</div>

		<p>地域や業種を踏まえるなら「◯◯区で××を経営している方へ」、購入した商品を踏まえるなら「〇〇をお買い上げいただいた方へ」といった出だしが考えられます。そのほか、しつこくならない程度に「名前」で呼びかけるのも手です。</p>

		<h3 id="m01-3" class="midashi03">3. キャッチコピーで「読み手のメリット」を訴求</h3>
		<p>設定したペルソナは、キャッチコピーにも活かしてください。キャッチコピーでは、「このDMを読めば得をする」ということを、ペルソナが直感的に理解できるよう表現します。</p>
		<p>キャッチコピーを作る際の具体的なコツや注意点などは、以下の記事で解説しています。併せてご覧ください。</p>
		<p><a href="https://www.dm110.jp/DM_matome/catch_copy/"><img src="/images/DM_matome/btn_catch_copy.png" width="760" height="126" alt="キャッチコピーの作り方はこちら" decoding="async" loading="lazy"></a></p>

		<h3 id="m01-4" class="midashi03">4. 内容を理解しやすいよう「具体的」に</h3>
		<p>曖昧な表現は内容を理解しにくくなるだけでなく、想定と異なる受け取り方をされる可能性があります。</p>
		<p>DMでは文章を数字に置き換える、擬音語や擬態語でリアルに表現するといった方法で、できるだけ具体的に書くことを心がけてください。</p>
		<p>文章によっては、数字への置き換えが難しいケースもあります。観点を変えても数値化できない場合は、誰が読んでも解釈が一致する言葉を選んでください。</p>

		<h3 id="m01-5" class="midashi03">5. 時間を取らせないよう「シンプル」に</h3>
		<p>DMの内容は、とにかくシンプルが基本です。長々とした文章や難しい言葉が多用された文章は、読む気を消失させてしまいます。</p>
		<p>パッと見て全体像がわかる、かつ一度で理解できる文章にする必要があります。そのためには、一文を短くして端的に表現するのがコツです。また、専門用語の使用は極力避けてください。</p>

		<h3 id="m01-6" class="midashi03">6. 売り込むのではなく「共感」を得て購買意欲を刺激</h3>
		<p>DMの冒頭で、いきなり商品やサービスを売り込む手法は敬遠されます。読み手の購買意欲を高めるためには、商品やサービスを認知してもらったうえで、興味・共感を得られる話題につなげる必要があります。</p>
		<p>共感を得る重要性は、消費者の購買心理モデル「AIDA（アイーダ）の法則」からも伺えます。「AIDA」とは、以下の頭文字を取ったものです。</p>

		<div class="box box--yellow">
		<ul class="list-circle">
			<li>Attention（注目）：商品・サービスを認知する</li>
			<li>Interest（興味）：商品・サービスに興味を持ったり、共感したりする</li>
			<li>Desire（欲求）：商品・サービスを購入したいと感じる</li>
			<li>Action（行動）：実際に商品・サービスを購入する</li>
		</ul>
		</div>

		<h3 id="m01-7" class="midashi03">7. 「追伸」もうまく活用</h3>
		<p>DMの文章が完成したら、商品のイチ押し情報を追伸に記載するのもテクニックです。追伸は、手紙で最も印象に残る部分ともいわれています。</p>
		<p>例えば、「◯月◯日に関連新商品発売予定」「在庫わずか！なくなり次第終了」などの情報を記載し、DMのメリットや限定感をあらためて訴求してください。</p>
	</section>


	<section id="m02">
		<h2 class="midashi02">心理的テクニックで訴求効果アップ！ DMに使える心理効果7選</h2>
		<p>初めて見聞きする会社からDMが届いた場合、通常は警戒心を抱きます。そこで、ターゲットの警戒心を解くために、心理学をうまく取り入れることで良い反応が期待できます。</p>
		<p>今回は、さまざまな心理的テクニックのなかから、特にDMに取り入れやすい7つを紹介します。ターゲットの購入意欲の強さや段階に応じて、使い分けてください。</p>
		<p><img src="/images/DM_matome/DM_kotsu_sub1.png" width="1500" height="1080" alt="DMに使える心理効果7選" decoding="async" loading="lazy"></p>

		<h3 id="m02-1" class="midashi03">1. ザイオンス効果（単純接触効果）</h3>
		<p>ザイオンス効果は単純接触効果とも呼ばれます。何度も接触するうちに親近感が増したり、好感度が高まったりする効果です。</p>
		<p>商品やサービスにまったく関心がない相手も、ザイオンス効果の活用で最終的に購入へつなげられます。</p>
		<p>ただし、同じ内容のDMを何度も送付するだけでは逆効果です。相手の反応をチェックしながら、アプローチの仕方に変化をつける必要があります。</p>

		<h3 id="m02-2" class="midashi03">2. バーナム効果</h3>
		<p>バーナム効果は、本当は誰にでも当てはまる内容が、「自分のことをいっている」と思わせる心理効果です。</p>
		<p>例えば、占いやおみくじ、血液型診断などはバーナム効果が活用されています。DMでは、多くの人が抱えている悩みについて「◯◯にお悩みではありませんか」と問いかけると、「自分のためのDMだ」と思ってもらえます。</p>
		<p>DMのバーナム効果を高めるには、ターゲットの情報収集や分析が鍵となります。</p>

		<h3 id="m02-3" class="midashi03">3. ツァイガルニク効果</h3>
		<p>ツァイガルニク効果は、答えを知らされるよりも、答えを知らされずに中断されるほうが気になるという心理効果です。「続きはWebで」とするテレビCMは、ツァイガルニク効果を活かした代表例です。</p>
		<p>DMでも問い合わせや資料申し込みにつなげるため、このテクニックが用いられています。例えば、DM内では商品の概要紹介にとどめたうえで、「商品愛用者が実感している“本当の”メリットとは？」などと続きが気になる文章を取り入れると効果的です。</p>

		<h3 id="m02-4" class="midashi03">4. バンドワゴン効果</h3>
		<p>バンドワゴン効果とは、「周りが持っていると欲しくなる」「大勢が支持するものを持っていると安心する」という心理効果を指します。特に日本人は、協調を重んじること、流行り物が好きな傾向にあることから、バンドワゴン効果が有効とされています。</p>
		<p>DMでの具体例は、BtoCなら「当店人気No.1商品」といったキャッチコピー、BtoBなら「大手企業◯社への導入実績あり」といったアピールなどが挙げられます。</p>
		<p>バンドワゴン効果の逆パターンとして、「スノッブ効果」があります。スノッブ効果は、周りが持っていないものを手に入れることで優越感を覚える心理効果です。</p>
		<p>具体的には、「一日5名様限定」「記念モデル」「日本初上陸」などのキーワードが挙げられます。</p>

		<h3 id="m02-5" class="midashi03">5. カリギュラ効果</h3>
		<p>カリギュラ効果は、「見てはいけないといわれると見たくなる」ように、特定の行為を禁止されるとかえってやりたくなる心理効果です。日本の民話『鶴の恩返し』にも、カリギュラ効果が反映されています。</p>
		<p>心理的テクニックのなかでは比較的高度ですが、うまく活用できればDM開封率を上げられます。例えば、「真剣にお悩みの方は開封してください」ではなく、「真剣にお悩みの方以外は開封禁止」とするほうが効果的です。</p>

		<h3 id="m02-6" class="midashi03">6. 暗黙の前提</h3>
		<p>暗黙の前提とは、世間の常識など、一般的に大半の人が共有している事柄を指します。</p>
		<p>暗黙の前提をDMで応用する場合は、あたかも「参加するのは当然」であるかのように話を進め、イベントへの参画意識を持ってもらうといった方法が挙げられます。</p>

		<h3 id="m02-6" class="midashi03">7. ウィンザー効果</h3>
		<p>ウィンザー効果とは、第三者から情報が伝わるほうが、信頼感や信ぴょう性が増す心理効果です。</p>
		<p>商品やサービスを実際に利用した第三者の意見として、DM内で「お客様の声」「モニターレビュー」を紹介する手法は、ウィンザー効果の応用といえます。</p>
	</section>


