	<section id="m04">
		<h2 class="midashi02">効果を高めるために！ DMでは表やグラフも活用してみよう</h2>
		<p>DMでは「わかりやすさ」が重要ですが、文章だけで表現するのは難しいケースもあります。視覚的にわかりやすくするには、表やグラフを用いることも検討してください。</p>
		<p>特にグラフには、演出を加えてより効果を高めた「詐欺グラフ」と呼ばれる手法があります。詐欺グラフは、テレビや新聞などでもよく活用されています。</p>
		<p>ここでは、詐欺グラフの代表例を5つ紹介します。</p>

		<h3 id="m04-1" class="midashi03">1. 目盛りを「0」から始めない</h3>
		<p>棒グラフの縦軸の目盛りは、本来「0」を起点とする必要があります。</p>
		<p>しかし、あえて「0」ではない数字から始めることで、比較対象との差をより大きく見せられます。</p>
		<p><img src="/images/DM_matome/DM_kotsu_sub3.png" width="1500" height="880" alt="目盛りを「0」から始めない" decoding="async" loading="lazy"></p>

		<h3 id="m04-2" class="midashi03">2. 縦軸を使わない</h3>
		<p>棒グラフの目盛りを「0」から始めない手法の応用編として、そもそも縦軸を使わない手法もあります。</p>
		<p>例えば、商品の利用者数を比較する棒グラフにおいて、縦軸を使わずに過去数年間で利用者数が急増したように見せることもできます。</p>
		<p><img src="/images/DM_matome/DM_kotsu_sub4.png" width="1500" height="1000" alt="縦軸を使わない" decoding="async" loading="lazy"></p>

		<h3 id="m04-3" class="midashi03">3. 遠近法を活用する</h3>
		<p>棒グラフを立体的にし、奥から手前にかけて並べることで、手前の項目をより大きく見せる方法です。</p>
		<p>前年比で実際には数値が減ったデータでも、遠近法により増えているような錯覚に陥ります。</p>
		<p><img src="/images/DM_matome/DM_kotsu_sub5.png" width="1500" height="1080" alt="遠近法を活用する" decoding="async" loading="lazy"></p>

		<h3 id="m04-4" class="midashi03">4. 分類の粒度を変える</h3>
		<p>比較対象となる項目は、同じ粒度で分類するのが基本です。しかし、詐欺グラフにおいては、あえて分類の粒度を変えることもあります。</p>
		<p>例えば、商品購入者の年代を比較するグラフにおいて、本来は「10代／20代／30代／40代……」とすべきところ、「10～20代／30～40代／50代……」などと分類します。これにより、まとめた年代に特に人気があるように見せられます。</p>
		<p><img src="/images/DM_matome/DM_kotsu_sub6.png" width="1500" height="940" alt="分類の粒度を変える" decoding="async" loading="lazy"></p>

		<h3 id="m04-5" class="midashi03">5. 比率を歪める</h3>
		<p>円グラフの中心点をずらすなどして、面積の比率を変える詐欺グラフです。グラフに記載した数値に注目すれば正確な内容はわかるものの、一目見たときの印象を変えられます。</p>
		<p>具体的には、本来2番目に割合が多い項目を、最も割合が多いように見せるといった演出です。</p>
		<p><img src="/images/DM_matome/DM_kotsu_sub7.png" width="1500" height="1100" alt="比率を歪める" decoding="async" loading="lazy"></p>
