	<section id="m01">
		<h2 class="midashi02">DMの開封率とは？</h2>
		<p>DMの開封率とは、「発送したDM数」に対する「開封されたDM数」の割合です。例えば、100通のDMを発送し、そのうち50通が開封された場合、DMの開封率は「50÷100×100％＝50％」となります。</p>
		<p>また、開封率と似た言葉に反応率があります。DMの反応率とは、発送したDM数に対する「レスポンス件数」の割合です。「レスポンス」は、インターネットでの検索や商品の購入・資料請求・会員登録など、DMを受け取ったことによる行動を指します。</p>
		<p>電子メールを使ったDMの場合は、自社で開封率や反応率を測定できます。しかし、ハガキや封筒を使った郵送DMの場合、正確な開封率は自社で把握できません。</p>
	</section>


	<section id="m02">
		<h2 class="midashi02">DMの開封率に関するデータ</h2>
		<p>一般社団法人日本ダイレクトメール協会が公表している「DMメディア実態調査2021」によると、調査対象となった合計2,105通のDMの開封率は、67.6％でした。発送したDMのうち、3割程度は開封されていないことがわかります。</p>
		<p><img src="/images/DM_matome/DM_kaifuuritu_sub1.png" width="1500" height="900" alt="DMの開封・閲読率は、67.6％" decoding="async" loading="lazy"></p>
		<p>また、DMの開封率は宛先別によっても大きく異なります。具体的には、本人宛のDMの開封率は79.5％と高い一方で、宛名がないDMの開封率は37.3％に留まりました。</p>
		<p><img src="/images/DM_matome/DM_kaifuuritu_sub2.png" width="1500" height="900" alt="自分宛のDMの開封・閲読率は79.5％、宛名なしのDMの開封・閲読率は37.3％" decoding="async" loading="lazy"></p>
