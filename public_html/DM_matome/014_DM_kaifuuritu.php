	<section id="m03">
		<h2 class="midashi02">開封率アップはDM成功のカギ</h2>
		<p>DM施策を成功させるには、顧客がDMを受け取ったあとに「どのように処理しているか」という点に注目することが大切です。</p>
		<p>DMを受け取った顧客が、その中身を確認したうえで「自分には関係ない」「今は不要だ」などと判断し、処分するのは仕方がありません。しかし、DMが開封されずに捨てられてしまうことだけは避けたいところです。</p>
		<p>では、DMの開封率をアップさせるには、どのような方法があるのでしょうか。</p>
	</section>


	<section id="m04">
		<h2 class="midashi02">DMを成功につなげる開封率アップの8つのコツ</h2>
		<p><img src="/images/DM_matome/DM_kaifuuritu_sub3.jpg" width="1980" height="1321" alt="" decoding="async" loading="lazy"></p>
		<p>ここでは、DMの開封率をアップさせる8つのコツについて、ポイントや注意点を交えながら解説します。</p>


		<h3 id="m04-1" class="midashi03">ターゲットを最初に決める</h3>
		<p>開封率アップのコツのなかでも重要なのが、ターゲットの選定です。訴求したい内容をふまえてターゲットを決め、ターゲットの興味・関心などに即したDMにすると開封率が上がります。</p>
		<p>ターゲットを決める際は、少なくとも「毎回購入してくれる顧客」と「前回のDMで購入しなかった顧客」の2つに分けて考えます。</p>
		<p>また、より細かく考えるなら、以下の「ターゲットマーケティングの4Step」の手順に沿って実施してください。</p>
		<p><img src="/images/DM_matome/DM_kaifuuritu_sub4.png" width="1500" height="900" alt="ターゲットマーケティングの4Step" decoding="async" loading="lazy"></p>
		<div class="box box--yellow">
		<ul class="list-decimal">
			<li>顧客の情報を広く集める</li>
			<li>集めた情報を整理し、個人の場合は年齢・性別・職業・住所など、法人の場合は会社の規模・業種・所在地などで顧客を分類する</li>
			<li>分類した顧客ごとに、自社に対しどのようなニーズがあるかを検討する</li>
			<li>顧客が自社に求めるものを提供する</li>
		</ul>
		</div>

		<h3 id="m04-2" class="midashi03">ドアオープナーを活用する</h3>
		<p>「ドアオープナー」とは、DMの開封を促す仕組みのことです。具体的には、DMの封筒にボールペンなどを入れて膨らみを付け、「中身を知りたい」「そのまま捨てるのはもったいない」という心理を働かせる手法を指します。</p>
		<p>ドアオープナーに使えるのは、ボールペンのような筆記用具のほか、カレンダーや化粧品の無料サンプルなどさまざまです。</p>
		<p>ただし、これらを同封しただけで、必ずDMの開封率が上がるわけではありません。ドアオープナーを活用しつつ、キャッチコピーなどで開封したいと思わせる必要があります。また、封入するものと、宣伝したい商品・サービスを関連付けるのもポイントです。</p>
		<p>なお、DMの発送方法によって封筒の厚さの制限が異なるため、あらかじめ確認しておいてください。</p>

		<h3 id="m04-3" class="midashi03">DMの中身に興味を持たせる</h3>
		<p>封筒を見ただけでDMの中身がわかるようにすると、「このDMを開封するとメリットがある」と顧客が判断しやすくなり、開封率アップにつながります。</p>
		<p>DMを受け取った顧客が、封筒の表面を見るか裏面を見るかはわからないため、両面に訴求効果がある内容を記載してください。例えば「クーポンのお知らせ」や「特典の封入」など、中身が具体的にイメージできる表現にし、開封するメリットをアピールします。</p>
		<p>透明のビニール封筒でDMを発送する場合は、透けて見える紙のヘッドコピーやイラスト・写真を活用することで、さらに訴求力を高められます。</p>

		<h3 id="m04-4" class="midashi03">封筒選びにこだわる</h3>
		<p>「私信なのでは？」「重要な内容が含まれているのでは？」と感じられる封筒にすると、開封率が上がります。特におすすめなのが、外側が白色・内側が青色の2重になっている封筒です。</p>
		<p>また、封筒の開けやすさも重視してください。顧客がDMの中身に興味を持っても、いざ開封しようとしたときに手間がかかると、開封意欲が薄れてしまいます。手で開けられるミシン目加工を施したり、どこから・どのように開封するのか説明を記載したりするなど工夫が必要です。</p>

		<h3 id="m04-5" class="midashi03">封筒の宛名や切手などを工夫する</h3>
		<p><img src="/images/DM_matome/DM_kaifuuritu_sub5.jpg" width="1980" height="1320" alt="" decoding="async" loading="lazy"></p>
		<p>開封率を上げるなら、宛名は必ず手書きにし、記念切手を貼ります。切手を貼るのに必要なスペースは、切手の枚数・大きさによって変わるため、「宛名を書いたら切手が貼れなくなった」とならないよう注意してください。</p>
		<p>また、封筒には「◯◯在中」と封入物を明記し、印鑑を押します。「売上を◯％アップできる資料在中」など、封筒の中身が一目でわかり、かつ開封するメリットが感じられるような表現にします。特に、法人向けのDMの場合は、「コスト削減」「売上アップ」のどちらかを盛り込むのがポイントです。</p>

		<h3 id="m04-6" class="midashi03">発送方法を工夫する</h3>
		<p>DMを発送する際は、郵送以外の発送方法を試してみてください。具体的には、以下の発送方法があります。</p>
		<table class="table01">
			<tr><th>請求書に同封する</th><td>請求書の封筒にDMやニュースレターを入れて、一緒に発送する方法です。見方を変えれば、無料でDMを発送することになります。</td></tr>
			<tr><th>商品に同梱する</th><td>購入された商品を宅急便などで発送する際に、DMを一緒に入れる方法です。DMを手に取ってもらう確率を上げるには、納品書とDMを透明な封筒に同封すること・枚数は1枚にすること・お得な情報を盛り込むことがポイントです。</td></tr>
			<tr><th>営業社員に持たせる</th><td>営業社員が顧客を訪問する際に、DMやニュースレターを顧客に直接渡す方法です。会話のネタにしたり、親近感を持ってもらったりするために、営業社員がその場で開封して、中身を一緒に見てもらえるのが理想です。</td></tr>
			<tr><th>宅急便で発送する</th><td>DMを箱に入れ、宅急便で発送する方法です。この方法は、どうしても開封してもらいたいDMに適しています。心を込めたプレゼントも同梱してください。</td></tr>
		</table>

		<h3 id="m04-7" class="midashi03">ベストな発送タイミングを見極める</h3>
		<p>DMは、ターゲットが最も興味を持ちやすいタイミングで発送することが重要です。例えば、給料日・ボーナス日・誕生日のように、商品の購買意欲が高まる日や、ターゲットにとって特別な日に合わせてDMを発送すると、開封率が上がります。また、季節ごとのイベントの時期や、新年・新生活のスタートのタイミングに合わせて発送するのも効果的です。</p>
		<p>既存顧客なら、これまでの商品・サービスの利用周期などもふまえて、発送タイミングを見極めてください。</p>

		<h3 id="m04-8" class="midashi03">過去にDMの反応がなかった人にも発送する</h3>
		<p>過去に反応がなかった人に再度DMを発送している会社は、ほとんどありません。しかし、これまで反応がなかった人にDMを再送することは、とても有効な方法です。</p>
		<p>人は忘れてしまった物事でも、何かのきっかけで思い出すことがあります。そのため、一度だけではなく、何度かDMを受け取ることで、ふとしたときに「以前このような会社からDMが届いたな」と思い出す確率を高められます。</p>
		<p>どのようなDMだと反応が得られやすいか比較テストをしつつ、根気よくDMの発送を繰り返すことが大切です。</p>
	</section>


