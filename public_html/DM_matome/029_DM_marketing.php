	<section id="m01">
		<h2 class="midashi02">ダイレクトマーケティングとは？</h2>
		<p>「ダイレクトマーケティング」とは、企業が顧客と直接的にコミュニケーションをとることで、顧客に商品購入などを働きかけるマーケティング手法です。</p>
		<p>企業が不特定多数に向けて一方的に発信する「マスマーケティング」と異なり、ダイレクトマーケティングでは、企業が顧客と1対1でのコミュニケーションを図ります。これにより、顧客一人ひとりのニーズに合った販促ができるのが大きなメリットです。</p>
		<p>ダイレクトマーケティングの手法には、DM（ダイレクトメール）や電子メール、FAX、電話、SNS、スマートフォンアプリ、レコメンデーションなどが挙げられます。</p>
	</section>


	<section id="m02">
		<h2 class="midashi02">DMは「宣伝や販売を目的としたダイレクトマーケティングツール」</h2>
		<p>DMは、商品やサービスを宣伝・販売するために、顧客に届ける紙媒体のことです。<br>ここでは、DMの効果や、マーケティングにDMを活用するメリット・デメリットを解説します。</p>

		<h3 id="m02-1" class="midashi03">マーケティングにもたらすDMの効果</h3>
		<p class="u-mb0">一般社団法人日本ダイレクトメール協会が、20～59歳の男女を対象に実施した「DMメディア実態調査2021」によると、本人宛てDMの開封・閲読率は79.5％でした。</p>
		<p class="u-mt0"><img src="/images/DM_matome/DM_marketing_sub1.png" width="1500" height="900" alt="DMの開封・閲読率" decoding="async" loading="lazy"></p>
		<p>すなわち、自分に向けて送られたはがきや封書などのDMは、8割程度の方が目を通しているのです。具体的なDMの内容としては、「新商品・サービスの案内」や「特売・セール・キャンペーンの案内」が多く見られました。</p>
		<p>また、本人宛てDMを受け取った総数に対する行動喚起率は、21％でした。行動喚起とは、DMの開封・閲読が「インターネットで検索する」「家族や友人との話題にする」「実際に購入・利用する」などの行動につながることです。年齢層別に見ると、特に20～30代で高い行動喚起効果がありました。</p>
		<p><img src="/images/DM_matome/DM_marketing_sub2.png" width="1000" height="840" alt="自分宛DMの行動喚起率は21.0％" decoding="async" loading="lazy"></p>
		<p>開封・閲読率は発送先の選定で大きく反応率が変わります。<br>当社データでは0％から100％までの幅があります。</p>
		<p>反応率100％を出したDMの詳細は以下よりご確認ください。</p>
		<p><a href="https://www.dm110.jp/DM_hannouritu_100.html"><img src="/images/DM_matome/btn_DM_hannouritu_100.png" width="760" height="126" alt="反応率100％DMの詳細はこちら" decoding="async" loading="lazy"></a></p>
		<p>DM反応率は0.1％だからダメ、3％だから良いという考えは良くありません。<br>反応率はただの指標であり、その反応率で粗利あるいはLTV（ライフタイムバリュー）を考えての判断を行ってください。</p>

		<h3 id="m02-2" class="midashi03">電子メール・FAXと比較！ DMのメリット・デメリット</h3>
		<p><img src="/images/DM_matome/DM_marketing_sub3.jpg" width="1980" height="1033" alt="" decoding="async" loading="lazy"></p>
		<p>先述のとおり、ダイレクトマーケティングの手法にはDMのほかにも、電子メールやFAXなどがあります。これらの媒体を比較して自社に合うダイレクトマーケティングの手法を選択してください。</p>
		<p>DMは、宛先が限定されること・作成に時間や手間がかかること・発送コストがかかることから、他社にまねされにくいのが特徴です。また、効果的なDMを出している会社が少ないため、内容だけでなく用紙や発送のタイミングなども工夫することで、他社と差別化できます。</p>
		<p>その他、比較テストがしやすいこと・既存顧客や法人宛てのDMは費用対効果が大きいこともメリットです。</p>
		<p>なお、DMは印刷や発送にコストがかかります。電子メールやFAXと比べると、作成から発送までにかかるコストが高いのがデメリットです。特に、新規顧客向けDMの場合は、費用対効果が悪くなります。</p>
		<p><img src="/images/DM_matome/DM_marketing_sub4.png" width="1500" height="1186" alt="DMのメリット・デメリット" decoding="async" loading="lazy"></p>

		<p class="u-mt50">電子メールは大量の顧客に対して一度に情報を伝えられる一方、件名のみでのアピールになるため、魅力を伝えづらく開封されにくいというデメリットがあります。また、大量のメールのなかに埋もれやすく、送付先の会社によっては特定のメール以外受信されないこともあります。このことから、DMのほうが開封してもらいやすいと考えられます。</p>
		<p><img src="/images/DM_matome/DM_marketing_sub5.png" width="1500" height="1186" alt="電子メールのメリット・デメリット" decoding="async" loading="lazy"></p>

		<p class="u-mt50">FAXは目に留まりやすいことから、開封率が高いのが特徴です。しかし、受信者側のインクや紙を使用するため、DMに比べてトラブルになりやすいと考えられます。クレームに対応するスタッフの育成や配信停止要求への対応が必要になるため、これらの体制を整えられるかも含めて検討してください。</p>
		<p><img src="/images/DM_matome/DM_marketing_sub6.png" width="1500" height="1400" alt="FAXのメリット・デメリット" decoding="async" loading="lazy"></p>

		<p class="u-mt50">電子メールやFAXと比較するとわかるように、DMにはDMならではの強みがあります。ただし、効果的なDMを作るのは難しく、時間がかかります。マーケティングにDMを活用する際は、最初から完璧なDMを目指すのではなく、比較テストを繰り返してブラッシュアップすることが大切です。</p>
	</section>


	<section id="m03">
		<h2 class="midashi02">マーケティングにDMを活用するなら用途で使い分け</h2>
		<p>DMのおもな用途は、「新規顧客の集客」「既存顧客へのフォロー・利用促進」「休眠顧客の掘り起こし」の3つです。マーケティングにDMを活用する場合、それぞれの用途に応じた工夫が求められます。</p>

		<h3 id="m03-1" class="midashi03">新規顧客の集客</h3>
		<p>新規顧客の集客にDMを活用する場合は、どのような方向性の内容にすべきかを見極めるため、少なくとも3回は比較テストが必要です。</p>
		<p>新規顧客といっても、「初めて資料請求をしてくれた顧客」「面談までは行えたが成約しなかった顧客」など、関係性はさまざまです。顧客との関係性をもとに、DMを出す頻度を考えてください。</p>
		<p>また、DMとインターネットをうまく組み合わせることが重要です。新規顧客を継続的に集め続けている会社は、ホームページやブログなども活用して、新規顧客になり得る人を洗い出しています。</p>
		<p>DMを活用した新規顧客の開拓について、詳しくは以下の記事をご覧ください。</p>
		<p><a href="https://www.dm110.jp/DM_matome/shinki_kaitaku_DM/"><img src="/images/DM_matome/btn_shinki_kaitaku_DM.png" width="760" height="126" alt="新規顧客向けのDM作成のコツはこちら" decoding="async" loading="lazy"></a></p>

		<h3 id="m03-2" class="midashi03">既存顧客へのフォロー・利用促進</h3>
		<p>「マーケティングにDMを活用するメリット」の項目で触れたとおり、費用対効果が大きいのは既存顧客宛てDMです。既存顧客宛てDMの反応率は、新規顧客宛てDMより一桁大きくなることが珍しくありません。</p>
		<p>既存顧客にDMを出す場合は、「5対25の法則」を覚えておいてください。5対25の法則とは、「既存顧客のうち5％の離脱を阻止できれば、利益が25％改善される」という法則です。</p>
		<p>既存顧客の5％の離脱阻止を実現するには、月に1回ほどDMを出して接触頻度を高めるのがポイントとされています。頻繁にDMを出す分、売り込み以外の内容を増やすことも忘れてはなりません。</p>

		<h3 id="m03-3" class="midashi03">休眠顧客の掘り起こし</h3>
		<p>休眠顧客を再び顧客に戻すのにかかるコストは、新規顧客を獲得するコストよりも低いため、DMによる休眠顧客の掘り起こしにも目を向けてください。</p>
		<p>休眠顧客が顧客に戻った際には、以前と同じような消費行動をとる傾向があります。したがって、過去の購入頻度や購入金額を分析すれば、優先してアプローチすべき休眠顧客がわかります。</p>
		<p>また、休眠顧客にDMを出す場合は、売り込みをしないのが基本です。最初は挨拶程度の内容に留め、反応を見ます。</p>
		<p>休眠顧客の選別方法や、休眠顧客宛てDMの挨拶文作成のコツなどについては、以下の記事をご覧ください。</p>
		<p><a href="https://www.dm110.jp/DM_matome/Kyuumin_DM/"><img src="/images/DM_matome/btn_Kyuumin_DM.png" width="760" height="126" alt="休眠顧客向けのDM作成のコツはこちら" decoding="async" loading="lazy"></a></p>
	</section>

	<section id="m04">
		<h2 class="midashi02">DMをマーケティングに効果的に活用する4つのコツ</h2>
		<p>DMをマーケティングに活かすために、押さえておくべきコツを紹介します。</p>

		<h3 id="m04-1" class="midashi03">CRMと連携する</h3>
		<p>CRMは「Customer Relationship Management」の略で、「顧客関係管理」という意味です。現在では、顧客関係を管理するためのシステムやツールも含めてCRMと呼んでいます。</p>
		<p>顧客管理システムという意味でのCRMには、顧客管理・顧客分析・営業進捗管理・プロモーション管理などの機能が搭載されています。CRMを活用すれば、顧客を属性別に分類・分析してDMの方向性を定めたり、最適なDM発送のタイミングを判断したりと、より顧客に合ったDMマーケティングが可能です。</p>

		<h3 id="m04-2" class="midashi03">RFM分析を行う</h3>
		<p>RFM分析とは、次の3つの指標をもとに顧客を分析・分類する手法です。</p>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>Recency：最終購入日</li>
			<li>Frequency：購入頻度</li>
			<li>Monetary：購入金額</li>
		</ul>
		</div>
		<p>RFM分析で優良と判断されるのは、「最近・何度も・たくさん」購入してくれている顧客です。ただし、重要視すべき指標は、業種や商品の特性などによって異なります。</p>
		<p>また、R・F・Mすべての指標が低い（＝最近は購入していない・購入頻度が低い・購入金額が少ない）顧客をアプローチの対象外とするかは、慎重に判断しなければなりません。</p>
		<p>注意点として、RFM分析を繰り返すことにより、条件に合った顧客数が減少していきます。減少する割合を考慮しつつRFM分析を行ってください。</p>

		<h3 id="m04-3" class="midashi03">DMの効果を測定する</h3>
		<p>一度DMを出してみたものの、得られた利益が作成・発送コストを下回った場合には、DMによるアプローチは失敗したと考えてしまうかもしれません。</p>
		<p>しかし、DMの効果を判断するうえで大切なのは、1回の粗利額ではなく「LTV（Life Time Value：ライフタイムバリュー）」です。LTVは顧客生涯価値と訳され、「自社と取引を始めた顧客が、生涯でどれくらいの利益をもたらしてくれるか」を示す指標です。一年間の総粗利を、その一年間に購買活動をした顧客数で割ると、顧客一人当たりのLTVの目安がわかります。</p>
		<p>また、商品を購入した顧客に「購入のきっかけは何か」「DMは見たか」という趣旨の質問をし、回答を分析するのも有効です。</p>

		<h3 id="m04-4" class="midashi03">DMテストを行う</h3>
		<p>先述のとおり、効果的なDMにするためには比較テストが必要です。最低2種類のDMを作成・発送し、それぞれに対する顧客の反応を比べてください。</p>
		<p>ただし、「ここを変えたからこのような結果になった」と明確にわかるように、DMは1つの要素だけを変えるのがポイントです。変更する要素の例は、次のとおりです。</p>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>キャッチコピー</li>
			<li>フォント</li>
			<li>用紙</li>
			<li>写真・イラスト</li>
			<li>枠線</li>
			<li>特典</li>
			<li>お客様の声</li>
			<li>事例</li>
			<li>発送のタイミング</li>
		</ul>
		</div>
		<p>DMテスト（ABテスト）のコツなどについては、以下の記事をご覧ください。</p>
		<p><a href="https://www.dm110.jp/DM_matome/DM_Abtest/"><img src="/images/DM_matome/btn_DM_Abtest.png" width="760" height="126" alt="DMテスト（ABテスト）のコツはこちら" decoding="async" loading="lazy"></a></p>
	</section>


	<section id="m05">
		<h2 class="midashi02">まとめ</h2>
		<p>ダイレクトマーケティングツールの一つであるDMは、効果的に活用すれば他社と差別化できます。ただし、より良いDMにするには、比較テストや効果測定が欠かせません。</p>
		<p>また、新規顧客・既存顧客・休眠顧客といったDMの宛先によって、内容や発送頻度を工夫する必要があります。CRMとの連携や、RFM分析による顧客分類をしながら、顧客一人ひとりのニーズに合ったアプローチを行ってください。</p>
		<p>株式会社メディアボックスが運営する<a href="https://www.dm110.jp/">DM発送代行センター</a>では、DM発送の受託部数を5万通以下に絞ることで、複雑な封入への対応を可能としています。用途に応じて異なるパターンのDMを発送したい場合や、DMテストを実施したい場合などは、ぜひ当社にご相談ください。</p>

