	<section id="m02">
		<h2 class="midashi02">工程別｜DM作成のおもな外注先</h2>
		<p>DMの作成・発送は、すべてを自社で行うのではなく、部分的に外注することで、効率的かつ効果的なDMにできます。ここでは、先述した工程別に、おもな外注先を紹介します。</p>
		<p><img src="/images/DM_matome/sakusei_gaityuu_sub1.png" width="1500" height="1200" alt="DMのメリット" decoding="async" loading="lazy"></p>

		<h3 id="m02-1" class="midashi03">1．DM作成前の準備（戦略策定・調査など）</h3>
		<p>DM作成前の段階では、目的を明確にする工程を踏む必要があります。DM発送での具体的な目的は、戦略と戦術に分かれます。</p>
		<p>戦略は、結果的に売上アップに関するものを策定するのが一般的です。そして、売上アップを目的にしたDM発送を行う場合には、以下のような戦術を考えます。</p>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>既存顧客のリピート促進</li>
			<li>新規顧客の獲得</li>
			<li>離脱顧客の呼び戻し</li>
			<li>紹介客の獲得</li>
		</ul>
		</div>

		<p>DM作成前の準備段階は、自社内で目的（戦略・戦術）をしっかりと定めたうえで、外注と協力することをおすすめします。</p>
		<p>DM作成前の準備を外注する場合には広告代理店がよく使われますが、自社内で目的が明確化できているのであれば、戦略策定や市場調査などを部分的に外注することも可能です。</p>
		<p>具体的な方法としては、戦略策定や市場調査などをその分野の専門家に聞くことが挙げられます。例えば、<a href="https://service.visasq.com/" target="_blank" rel="noopener noreferrer">ビザスク</a>（スポットコンサル）を利用して、1人だけでなく複数人から聞くのがおすすめです。</p>

		<h3 id="m02-2" class="midashi03">2．各種名簿に基づくターゲットの洗い出し</h3>
		<p>DMの作成・発送で最も重要となるのが、ターゲット（＝送付先）の洗い出しです。</p>
		<p>例えば、DM作成前の準備段階で「新規顧客の獲得」と目的を定めたなら、新規顧客がターゲットとなり、「既存顧客のリピート促進」が目的なら、必然的に既存顧客がターゲットとなります。</p>
		<p>ただし、新規顧客をターゲットとするDMは、費用対効果が低くなりやすいため注意してください。特に初めてDMを出す場合は、既存顧客をターゲットとすると効率的です。</p>
		<p>大まかなターゲットを決定したら、各種名簿を活用して発送先をリスト化します。発送リストの作成はリスト作成代行会社に外注すれば、業者または自社が保有するデータから発送リストを作成してくれます。</p>
		<p>発送リストの精度を上げるためには、ターゲットやリスト作成の目的を細かく共有しておくことが大切です。</p>

		<h3 id="m02-3" class="midashi03">3．DMの内容作成・校正（文章・デザイン・イラストなど）</h3>
		<p>ターゲットの洗い出しに成功したとしても、ターゲットに刺さらない内容のDMだと、期待する反応は得られません。わかりやすい文章を書くのはもちろんのこと、デザインやキャッチコピー、イラスト、写真などにもこだわる必要があります。</p>
		<p>市販のアプリやソフトを活用すれば、自社でもデザインを作成可能です。費用が抑えられるうえ、デザインの追加・変更も自由に行えます。また、人手や時間に余裕がない場合は、DM代行専門会社やデザイン会社に外注もできます。</p>
		<p>また、昨今ではクラウドソーシングを活用して、個人にDM作成を依頼する選択肢もあります。クラウドソーシングとは、仕事を頼みたい人と請け負いたい人をインターネット上でつなぐサービスのことです。</p>
		<p>クラウドソーシングは、企業に依頼する場合と比べて費用が割安で、柔軟な対応が期待できるメリットがあります。DMの内容作成・校正に関する業務を細分化し、一部だけ依頼することも可能です。</p>
		<p>ただし、クラウドソーシングで仕事を請け負う人のスキルレベルには大きな幅があるため、実績があり信頼できる相手を慎重に選んでください。</p>

		<h3 id="m02-4" class="midashi03">4．封筒や封入物の印刷</h3>
		<p>DMの発送件数にもよりますが、自社で封筒や封入物を印刷しようとすると、膨大な時間と手間がかかります。また、印刷作業を行う場所や印刷物を保管する場所も、確保しなければなりません。</p>
		<p>プリンターが壊れるなどのトラブルも考慮すると、印刷会社やDM発送代行会社に外注することをおすすめします。</p>
		<p>外注先を選ぶ際は、次のポイントをもとに検討してください。</p>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>希望部数の印刷が頼めるか</li>
			<li>かかるコスト（各種手数料含む）はどれくらいか</li>
			<li>納期遅延や印刷物破損などのリスクはないか</li>
			<li>急な変更などの融通が利くか</li>
			<li>実績はどれくらいか</li>
		</ul>
		</div>

		<h3 id="m02-5" class="midashi03">5．DMの発送（封入・封緘・発送・返品処理など）</h3>
		<p>DMの発送には、封入物を封筒に入れる「封入」や、封筒を閉じる「封緘」の作業などが付随します。</p>
		<p>自社で封入・封緘すれば、個人情報が外部に漏れる心配はありません。一方で、発送部数が増えれば増えるほど作業負担が増え、仕上がりのクオリティが低下・バラつくことが考えられます。</p>
		<p>ターゲットからの信頼を損なわないよう、ケースに応じてDM発送代行会社への外注を検討してください。プロが効率的に作業することで、結果的にコストが安く済むことも珍しくありません。</p>
		<p>外注先を選ぶ際は、封入・封緘ミスのチェック体制や、万が一ミスが発生した際の対応速度・損害の補償額を確認してください。</p>
		<p>また、DMの発送作業を外注する場合は、返品物の処理についてあらかじめ外注先と取り決めておく必要があります。具体的には、DMが住所不明などの理由で送り返された場合、外注先で廃棄するのか・自社に返送してもらうのかなどです。</p>

		<h3 id="m02-6" class="midashi03">6．データ処理（返品データ化・名簿編集など）</h3>
		<p>戻ってきたDMは、単に廃棄するのではなく、データ化することが重要です。データ処理を行わないと、次回も同じ宛先にDMを送付してしまい、無駄なコストがかかってしまったり、送付先の方とトラブルになったりする可能性があります。</p>
		<p>外注先から自社にDMを返送してもらい、自社でデータ化する方法もありますが、時間やコストがかかるためおすすめできません。できれば、発送を依頼した会社にデータ処理も併せて頼むのが理想です。</p>
		<p>なお、データ処理を無料で行ってくれる会社もあります。</p>
	</section>


