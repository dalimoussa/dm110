		<div class="box box--yellow">
		<ul class="list-circle">
			<li>やり方によってはコストダウンにつながる</li>
			<li>外注先への指示書の作成を通して、自社のDMも洗練されていく</li>
			<li>予算があればすべて丸投げできる（ただし検証が必要）</li>
		</ul>
