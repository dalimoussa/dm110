	<section id="m05">
		<h2 class="midashi02">DM発送代行会社選びの8つの基準</h2>
		<p>ここでは、DM発送代行会社を選ぶ際の基準を解説します。</p>
		<p><img src="/images/DM_matome/sakusei_gaityuu_sub4.png" width="1500" height="1424" alt="DM発送代行会社選びの8つの基準" decoding="async" loading="lazy"></p>

		<h3 id="m05-1" class="midashi03">得意とするDM発送件数と自社のニーズが合っているか</h3>
		<p>DM発送代行会社によって、得意とする発送件数が異なります。一般的に、DMの発送件数は、次の3パターンに大別できます。</p>
		<div class="box box--yellow">
		<p>（1）50通から3万通まで<br>
			（2）5,000通から10万通まで<br>
			（3）3万通以上</p>
		</div>
		<p>（1）のように、50通といった小口発送を通常業務とする会社は、ほとんどありません。なぜなら、発送にかかるコストと得られる利益が見合わないためです。50通からのDM発送を行っている会社は、大がかりな機械設備や自社ビルを持たないなどの工夫をし、内職さんの手を借りながら作業を行います。</p>
		<p>（2）の5,000通から10万通までのDM発送が得意な会社は、手作業または小型の機械で作業することもあります。</p>
		<p>（3）3万通以上の大口発送が得意な会社は、大型の機械を活用するのが特徴です。大口発送は低単価・短納期でできますが、少部数のみの依頼はコストパフォーマンスが悪くなります。</p>
		<p>DM発送代行会社を選ぶ際は、それぞれの会社が得意とするDMの発送件数と自社のニーズを照らし合わせてください。</p>

		<h3 id="m05-2" class="midashi03">DM担当者の作業負担が軽減されるか</h3>
		<p>ほとんどの場合、企業のDM担当者は、通常業務を行いながらDMに関する業務も担っています。そのため、DM担当者の作業負担を減らせるDM発送代行会社を選ぶことが重要です。例えば、営業電話をしつこくかけてくる、営業社員が突然訪問してくるといった無駄な時間を取らせる会社には注意してください。</p>
		<p>また、DMの発送手続きを進めるうえでは、「至急発送を止めなければならなくなった」「封入物の差し替えが必要になった」など、小さなトラブルや変更が度々発生します。トラブルにスムーズに対応するためには、「専任担当者」がいることがポイントです。専任担当者とは、いつでも連絡がつき、DM発送の依頼内容や進捗状況を把握できている人を指します。</p>
		<p>なお、営業社員が窓口の場合は注意が必要です。会議やお客様との商談中など、スムーズに連絡が取れないことがあります。</p>
		<h4 class="midashi05">質の高い専任担当者とは</h4>
		<p>特に、初めてDM発送代行会社を利用する方や、遅れが許されないDMを発送する方などは、専任担当者が欠かせません。専任担当者がつくと、問い合わせ時に電話をたらい回しされたり、毎回最初から状況を説明したりすることがなくなるため、ストレスが軽減されます。</p>
		<p>ただし、専任担当者は「形だけ」でないかを確認する必要があります。具体的な見分け方は、次のとおりです。</p>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>担当者は1人だけか</li>
			<li>見積もり後、3時間以内に返信があるか</li>
			<li>すぐに電話がつながるか</li>
			<li>メールの返信は3時間以内にあるか</li>
		</ul>
		</div>

		<p>上記の対応が取れない場合、その会社では、専任担当者が営業や現場の業務を兼務しているかもしれません。また、専任担当者をテレアポセンターに外注しているケースもあります。専任担当者は現場に精通しているべきであり、他の業務を兼任していないのが理想的です。</p>
		<p>なお、専任担当者は病気などで休む可能性もあります。専任担当者が休んだときには、どのような対応を取ってもらえるのかもチェックしてください。</p>

