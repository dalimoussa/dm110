		<p>DMで成果を上げるには、繰り返しDMを発送してデータを集め、次に発送するDMで見込める反応率や、得られる利益を予想できるようにすることが大切です。そのためには、DMの作成・発送を継続できる環境作りが欠かせません。</p>
		<p>そこで、DM作成に関する作業を分業化し、自社が苦手とする工程を外注すると、DM作成にかかる負担を減らせます。また、外注先のノウハウも獲得でき、結果的に自社の作業を効率化しやすくなります。</p>
