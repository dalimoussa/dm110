	<section id="m01">
		<h2 class="midashi02">ニュースレターで得られる効果とは</h2>
		<p>ニュースレターを出している会社のなかには、発行を10年以上継続している会社や、ニュースレターの作成部門を設けている会社もあります。そのような会社は、ポイントを押さえたニュースレターを出せば、きちんと効果が得られることをわかっているのです。</p>
		<p>具体例として</p>
		<div class="box box--yellow">
		<ul class="list-decimal">
			<li>支店の営業社員を減らしニュースレターに置き換えて成果を上げている</li>
			<li>社長自身がVIP客を中心に直接訪問しその内容をニュースレターに掲載し続けている</li>
			<li>ルート営業の社員にニュースレターを持たせ話題作りのきっかけにしている</li>
			<li>ニュースレターを保存版にしてもらえるように工夫している</li>
		</ul>
		</div>

		<p>その他にもニュースレターの使い方を工夫して自社の営業社員あるいは受付窓口に当たる存在として利用する会社様があります。</p>
		<p>ニュースレターで得られる具体的な効果は、次のとおりです。</p>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>信頼関係を築ける</li>
			<li>自社のイメージが良くなる</li>
			<li>紹介やリピートが増える</li>
			<li>離脱率が下がる</li>
			<li>一度離れた顧客が戻ってくる</li>
			<li>重要な連絡に目を通してもらいやすい</li>
			<li>顧客から感想をもらえる・購読率が上がるなど、うれしい場面が増える</li>
			<li>コロナ禍で営業が訪問できない代わりにニュースレターを使う</li>
			<li>自社商品が必要になったときの選択候補になる</li>
		</ul>
		</div>
		<p>上記の効果のなかから、いくつか取り上げて解説します。</p>

		<h3 id="m01-1" class="midashi03">顧客と信頼関係を構築できる</h3>
		<p class="uk-text-center"><img src="/images/DM_matome/Newsletter_kouka_sub1.png" width="680" height="320" alt="顧客との信頼関係構築" decoding="async" loading="lazy"></p>
		<p>ニュースレターを通して顧客と接点を持っていると、顧客からファンレターが届いたり、店頭で声をかけられたりするようになり、信頼関係の深まりを実感できます。<br>これは、顧客に適した内容のニュースレターとその送付頻度の影響によるものです。</p>
		<p>顧客と信頼関係を築けると、次のようなメリットが得られます。</p>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>自社の商品やサービスを覚えてもらえる</li>
			<li>電話をかけたときの対応が良くなる</li>
			<li>購入時期になると顧客が自発的に声をかけてくれる</li>
			<li>思いもよらない顧客から注文が入る</li>
		</ul>
		</div>

		<h3 id="m01-2" class="midashi03">ブランドイメージが向上する</h3>
		<p class="uk-text-center"><img src="/images/DM_matome/Newsletter_kouka_sub2.png" width="680" height="320" alt="ブランドイメージ向上" decoding="async" loading="lazy"></p>
		<p>顧客に役立つ情報が豊富に盛り込まれているなど、内容の充実したニュースレターは、顧客の満足度を高めます。また、ニュースレターを通じて顧客の知識を増やし、商品やサービス購入の判断基準を明確にすることで、自社のイメージが上がります。</p>
		<p>その結果、顧客が自社や自社商品・サービスに抱くイメージが向上し、売上も伸びやすくなります。</p>

		<h3 id="m01-3" class="midashi03">顧客の離脱率が下がる</h3>
		<p class="uk-text-center"><img src="/images/DM_matome/Newsletter_kouka_sub3.png" width="680" height="320" alt="顧客の離脱率減少" decoding="async" loading="lazy"></p>
		<p>顧客と信頼関係を構築できるニュースレターは、既存顧客のつなぎ止め（離脱防止）にも有効です。新規顧客の獲得ももちろん大切ですが、既存顧客の離脱阻止に注力することで、効率的な利益の増加につながります。</p>
		<p>業種や業態によるものの、毎年30％程度の顧客が離脱することは珍しくありません。一方で、離脱する顧客を5％でも減らせれば、利益が25％以上増えるといわれています。</p>
		<p>ニュースレターを出している会社のなかには、顧客の離脱率を12％も減らした事例があり、ニュースレターで大幅な利益の改善に成功しています。</p>

		<h3 id="m01-4" class="midashi03">重要な連絡に役立つ</h3>
		<p class="uk-text-center"><img src="/images/DM_matome/Newsletter_kouka_sub4.png" width="680" height="320" alt="重要な連絡時" decoding="async" loading="lazy"></p>
		<p>顧客に連絡したいとき、多くのケースでメールが使われますが、そのメールは見られていない可能性を考える必要があります。特に、売り込みが強いメールを頻繁に送っている場合は、メールが見られない確率が高くなります。</p>
		<p>顧客に伝えるべき情報について「メールで連絡しました」といっても、顧客から「メールは見ていないからわからない」といわれるかもしれません。</p>
		<p>重要な連絡をしたいときは、メールと併せてニュースレターにも盛り込む・同封することで、目を通してもらいやすくなります。</p>
		<p>また、メールでの連絡と紙を使っての連絡では、紙での連絡に親切さを感じます。加えて、丁寧に対応している印象を持ってもらえるため、顧客とのトラブルが減り、顧客の離脱率の低減にもつながります。</p>

		<h3 id="m01-5" class="midashi03">購読率が向上する</h3>
		<p class="uk-text-center"><img src="/images/DM_matome/Newsletter_kouka_sub5.png" width="680" height="320" alt="購読率向上" decoding="async" loading="lazy"></p>
		<p>ニュースレターは、一度出してすぐに効果が得られるものではありません。しかし、継続して発行すれば効果が拡大します。</p>
		<p>最初はニュースレターにまったく興味がなかった顧客でも、何度かニュースレターを受け取るうちに、ニュースレターの一部内容に興味を持ち、そこから毎回見てくれるようになるケースもあります。また、担当者だけではなく、別の部門や支店の人がニュースレターを読むようになるなど、徐々に購読率が上がっていきます。</p>
		<p>反対にまったく興味を示さない人にも発送することになりますが、担当者が変われば考え方が変わり、興味を示してもらえることもあります。</p>

		<h3 id="m01-6" class="midashi03">コロナ禍で営業が訪問できない代わりにニュースレターを使う</h3>
		<p class="uk-text-center"><img src="/images/DM_matome/Newsletter_kouka_sub6.png" width="680" height="320" alt="訪問営業の穴埋め" decoding="async" loading="lazy"></p>
		<p>これは、当社のお客様に増えてきている現象です。東証プライム上場企業も、営業担当者が訪問できない穴埋めに方針を変更されていますが、順調に成果を出されています。</p>
		<p>コロナの影響による在宅ワークの増加や直接訪問の機会減少で、接触頻度が減少しています。例えば、それが顕著に表れているのはルート営業などです。</p>
		<p>このように、接触頻度が減少した場合にも、ニュースレターが効果を上げてくれます。ニュースレターにもDMの内容をうまく織り交ぜて、営業色をどこまで出すかを考えて作成することが必要です。</p>

		<h3 id="m01-7" class="midashi03">自社商品が必要になったときの選択候補になる</h3>
		<p class="uk-text-center"><img src="/images/DM_matome/Newsletter_kouka_sub7.png" width="680" height="320" alt="選択肢の一つに挙がる" decoding="async" loading="lazy"></p>
		<p>これは、買い替えまでの時間が長い商品、日常的には購入がない商品・サービスの場合に考えられます。</p>
		<p>例えば、生命保険に新しく加入したいと思ったときには、インターネット検索で保険商品を調べるのが一般的です。その他、現在加入している保険会社に相談することもあります。</p>
		<p>その際に、情報提供としてニュースレターを年に数回送ってくれる保険会社があれば、選択肢の一つになるはずです。</p>
		<p>特に、高額で購入頻度の低い商品・サービスの場合には、ぜひニュースレターの活用を検討してください。</p>
	</section>


	<section id="m02">
		<h2 class="midashi02">ニュースレターは効果が出にくい？</h2>
		<p>ニュースレターを継続して発行すると、売上に良い影響があります。しかし、ニュースレターで得られる利益以上にコストがかかっていては、意味がありません。</p>
		<p>ニュースレターは、少なくとも1年間は発行を継続しないと効果がわかりにくいこと、一定の発行コストがかかることを理解したうえで、まずは自社に向いているかを判断してください。</p>
		<p>ここでは、ニュースレターが得意な分野・不得意な分野を紹介します。</p>

		<h3 id="m02-1" class="midashi03">ニュースレターが得意な分野</h3>
		<p>ニュースレターと相性の良い業種・業態や商品の例は、次のとおりです。</p>
		<div class="box box--yellow">
		<p class="midashi05-2">＜業種・業態＞</p>
		<ul class="list-circle">
			<li>顧客が限定されている</li>
			<li>顧客情報を分類できる</li>
			<li>売上金額が大きい</li>
			<li>競合がニュースレターを出していない</li>
			<li>フロントエンド商品とバックエンド商品がある</li>
			<li>複数業種・複数商品を扱っている</li>
		</ul>
		</div>
		<div class="box box--yellow">
		<p class="midashi05-2">＜商品＞</p>
		<ul class="list-circle">
			<li>単価が高い商品</li>
			<li>複数の候補を比較してから買う商品</li>
			<li>粗利が大きい商品</li>
			<li>付加価値がある商品</li>
			<li>値段や内容がわかりにくい商品</li>
			<li>リピート性がある商品</li>
		</ul>
		</div>
		<p>例えば、単価が高く、複数の候補を比較してから買う商品には、以下が挙げられます。</p>

		<div class="box box--yellow">
		<ul class="list-circle">
			<li>家</li>
			<li>保険</li>
			<li>車</li>
			<li>M&amp;A</li>
			<li>リゾート会員</li>
			<li>介護施設</li>
			<li>BtoB取引</li>
			<li>士業（弁護士・会計士・税理士など）</li>
			<li>健康関連</li>
		</ul>
		</div>
		<p>なお、ニュースレターと相性の良い商品でも、ニュースレターのおもな目的は売り込みではないことを忘れないようにしてください。</p>

		<h3 id="m02-2" class="midashi03">ニュースレターが不得意な分野</h3>
		<p>ニュースレターとあまり相性が良くない商品の例は、次のとおりです。</p>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>単価が低い商品</li>
			<li>他社と品質に差がなく価格で勝負する商品</li>
			<li>粗利が小さい商品</li>
		</ul>
		</div>
		<p>単価が低く、他社と品質に差がない商品の例として、消しゴムやクリップ、輪ゴム、ガソリンなどが挙げられます。</p>
		<p class="uk-text-center"><img src="/images/DM_matome/Newsletter_kouka_sub8.png" width="680" height="320" alt="ニュースレター 得意な分野 不得意な分野" decoding="async" loading="lazy"></p>
	</section>


	<section id="m03">
		<h2 class="midashi02">ニュースレターで効果を得るためにすべきこと</h2>
		<p>ニュースレターで効果を得るための2つのポイントを紹介します。</p>

		<h3 id="m03-1" class="midashi03">ニュースレターは「継続」が要</h3>
		<p>ニュースレターの良さを理解していても、実際に行動に移して発行するのは、10社に1社あるかないかの割合です。さらに、1年以上発行を続けられるのは、2社に1社しかありません。</p>
		<p>ニュースレターを発行し続けるには、内容を決めて作成するだけでなく、印刷・封入・発送にも手間がかかります。また、効果的なニュースレターにするには、できれば毎月、難しくても2ヵ月に1回は発行する必要があります。</p>
		<p>それらの点を踏まえると、日々の業務をこなしつつ、ニュースレターを継続するのは簡単ではないはずです。一方で、1年以上発行を続けられた会社の多くは、その後もニュースレターを継続し、大きな効果を得ています。</p>
		<p>したがって、ニュースレターを作成する際は、いかに継続可能な仕組みを整えられるかがポイントです。</p>
		<p>継続できている会社は、以下のような工夫を行っています。</p>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>3ヵ月以上書き溜めている（どうしても書けないときのためのストック）</li>
			<li>常にネタを探してメモしている</li>
			<li>ニュースレターひな型を利用して一部を自社の内容にしている</li>
		</ul>
		</div>
		<p>ニュースレターの継続的な作成は担当者の負担になりやすいため、ニュースレター作成代行会社へ依頼するのも一つの手です。ニュースレター作成代行会社への依頼を検討している方は、以下の記事も併せてご確認ください。</p>

