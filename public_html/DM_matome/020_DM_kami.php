	<section id="m03">
		<h2 class="midashi02">DMテストでDMの効果を上げよう</h2>
		<p><img src="/images/DM_matome/DM_kami_sub3.png" width="1500" height="695" alt="特定の要素のみを変更した、2種類のDMを用意" decoding="async" loading="lazy"></p>
		<p>選んだ紙が、DMの反応率にどのような影響を与えているのかを判別するには、DMテストが欠かせません。</p>
		<p>DMテストは2種類以上のDMを出すことで、DMのさまざまな要素の効果を調べる手法です。しかし、多くの企業ではDMテストを導入していないのが現状です。</p>
		<p>DMの効果を判定できなければ、行った施策が正しかったのか、間違っていたのかわからず、DMの反応率のデータも蓄積されません。DMをただ実施するのではなく、DMテストを行い、DMの効果アップに役立ててください。</p>
		<p>DMテストでは、ある特定の要素のみを変更した、2種類のDMを用意します。2種類のDMの反応率を比較することで、特定の要素が反応率に与えた影響を測定します。</p>
		<p>例えば、カラー印刷での紙質による反応率の違いを判定したい場合は、紙質のみを変え、紙質以外の要素である、文章や特典、封筒などは変えないことが重要です。一般的に、カラー印刷はコート紙を利用すると良いとされていますが、商品の種類によっては、上質紙のほうが反応率が高いという、意外な結果も得られています。</p>
		<p>感覚で判断するのではなく、DMテストで客観的なデータを取り、分析することが大切です。</p>
