	<section id="m02">
		<h2 class="midashi02">DM成功に導く！こだわるべき紙の5つの要素</h2>
		<p><img src="/images/DM_matome/DM_kami_sub1.png" width="1500" height="800" alt="紙の5つの要素" decoding="async" loading="lazy"></p>
		<p>DMの紙には、サイズ、色、質、厚さ、形の5つの要素があります。</p>

		<h3 id="m02-1" class="midashi03">紙のサイズ</h3>
		<p>DMでよく使われる紙のサイズは、B5サイズ（182mm×257mm）、A4サイズ（210mm×297mm）、A3サイズ（297mm×420mm）の3種類です。1つのDMに複数のサイズの紙を封入する場合もありますが、基本的にはA4用紙だけで作成します。</p>
		<p>ただし、申込用紙など目立たせたい重要な紙は、大きさを変えてほかの紙との違いを出すのがおすすめです。例えば、DMのメインとなる紙をA4用紙にする場合、申込用紙をB5用紙で作成してみてください。</p>
		<p>また、長形3号（120mm×235mm）の封筒に入れる際、紙を6つ折りにして存在感を出すなど、紙の折りかたを工夫して重要な用紙を目立たせる方法もあります。折る回数を増やすとコストがかかってしまいますが、目立たせたい用紙がある場合は試してみてください。</p>

		<h3 id="m02-2" class="midashi03">紙の色</h3>
		<p>DMの中に違った色の紙を入れることで、特定の用紙を目立たせる方法もあります。この方法は、モノクロ印刷のDMの場合に有効です。</p>
		<p>ただし、モノクロ印刷では文字色が黒になるため、紙の色を暗くしてしまうと、文字が読みづらくなってしまいます。暗い色を避けて、黄色やオレンジ色、クリーム色などの明るい色や淡い色を使うようにしてみてください。</p>

		<h3 id="m02-3" class="midashi03">紙の質</h3>
		<p>DMでよく使用される紙には、上質紙、コート紙、マットコート紙の3種類があります。</p>
		<p><img src="/images/DM_matome/DM_kami_sub2.png" width="1500" height="800" alt="上質紙、コート紙、マットコート紙" decoding="async" loading="lazy"></p>

		<table class="table01">
			<tr><th>上質紙</th><td>化学パルプを原料とする、最も一般的な紙。安価で手に入りやすく、市販の印刷用紙やノートなどで使用されています。</td></tr>
			<tr><th class="nowrap">コート紙</th><td>上質紙や中質紙の表面をコーティング加工した紙。表面に光沢とツヤがあり、インクのノリが良いため、カラーでの印刷に向いており、広告紙などに使用されています。</td></tr>
			<tr><th>マットコート紙</th><td>コート紙と同様、上質紙や中質紙の表面をコーティング加工した紙。コート紙よりも光沢が抑えられているため、光が反射しづらく、上品な印象を与えられます。おもな用途は、チラシやパンフレットなどです。</td></tr>
		</table>

		<p class="u-mt30">申込書など、顧客に書き込んでいただく紙には、上質紙やマットコート紙を使います。コート紙を使うと、紙の表面がつるつるとしているため、ペンが滑って文字を上手に書けません。</p>
		<p>DMの内容によって使う紙を分ける場合は、以下の表を参考にしてみてください。</p>

		<table class="table01">
			<tr><th>DMの内容</th><th>使用する紙質</th></tr>
			<tr><td class="uk-text-center">挨拶文</td><td class="uk-text-center">上質紙</td></tr>
