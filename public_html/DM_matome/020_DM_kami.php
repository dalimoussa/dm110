		<p class="u-mt30">また、カラー印刷で発色や色の再現性を重視したい場合は、コート紙やマットコート紙がおすすめです。落ち着いた色にしたい場合は、マットコート紙を使います。</p>

		<h3 id="m02-4" class="midashi03">紙の厚さ</h3>
		<p>紙の厚さは高級感や重みを与え、用紙を目立たせてくれます。</p>
		<p>例えば、複数の紙のなかに重さのある厚紙でひと廻り小さな紙を入れると、重さによってほかの紙からはみ出たり、抜け落ちたりするため目立ちやすくなります。また、封筒に入れる紙すべての厚みを増やすことで、高級感や重みを出すことも可能です。</p>
		<p>一般的に、紙の厚さは、連量（れんりょう）で表されます。<br>連量：原紙を1,000枚重ね合わせたときの重さ。単位はkg。</p>
		<p>例えば、「コート紙90kg」とは、原紙1,000枚を重ねたときに90kgの厚みをもった紙という意味になります。同じ材質の用紙でも、厚みの種類はいくつかあり、コート紙の場合は、コート紙73kgや、コート紙110kgなども選択できます。質感を変えずにコストを抑えたい場合は、材質を変えずに厚さを1ランク薄いものに変えるのも有効です。</p>
		<p>また、同じ連量でも、材質が違えば厚さが異なる点にも注意してください。例えば、コート紙135㎏とマットコート紙135kgでは、マットコート紙の方が実際の厚みは厚くなります。A4ハガキに使う紙の場合はマットコート紙の135㎏でも問題なく発送できます。</p>
		<p>また、DMで複数枚の紙をホッチキス止めする場合には、ホッチキスで止められるような厚さにするなどの工夫が必要です。通常のホッチキスで問題なく止められる厚さは上質紙5枚程度までと考え、それ以上の厚さにならないよう注意してください。なお、一回り大きなホッチキスなら、コピー用紙15枚程度を止めることもできます。</p>

		<h3 id="m02-5" class="midashi03">紙の形</h3>
		<p>紙を特定の形にすることを型抜きと呼び、用紙を目立たせる手法として用いられます。型抜きを利用する目的は、おもに以下の6つが挙げられます。</p>
		<div class="box box--yellow">
		<ul class="list-decimal">
			<li>商品の実物大に合わせて型抜きし、大きさを実感してもらう</li>
			<li>色や形、デザインを感じてもらう</li>
			<li>自社のブランドイメージを伝える</li>
			<li>ほかの用紙との違いを出して違和感を持たせ、反応率を上げる</li>
			<li>うちわ、ふせん、変形レターなどのプレゼントとして提供する</li>
			<li>割引券などの特典を目立たせる</li>
		</ul>
		</div>
		<p>子供向け通信教育のDMなど、DMらしさをあまり出したくない場合も、型抜きが使われます。パンダやゾウなど、動物の形に型抜きして、親しみを演出するのもおすすめです。凝ったものでは、飛び出す絵本のように仕掛けを施している場合もあります。</p>
		<p>型抜きは、コストと反応率のバランスを考えて実施することが大切です。凝れば凝るほど良い、というわけではないため、商品に合った最適な手法を取り入れます。</p>
