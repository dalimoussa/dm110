	<section id="m01">
		<h2 class="midashi02">DMの発送方法</h2>
		<p>DMを全国に発送する方法には、①ヤマト運輸のクロネコDM便（旧メール便）、②日本郵便のゆうメール、③佐川急便の飛脚ゆうメール便などがあります。</p>

		<h3 class="midashi05">① ヤマト運輸のクロネコDM便（旧メール便）</h3>
		<p>年間を通じて到着日数が早く、到着日も正確なのが特徴です。DM発送代行業者を経由して利用すると、業者によってはメール便の到着経路や到着状況を確認できます。</p>

		<h3 class="midashi05">② 日本郵便のゆうメール</h3>
		<p>郵便ポストや郵便局の窓口から発送することができます。DMの受取人が転居していても、受取人によって転居届が出されていれば1年間は新しい住所へ転送してもらえます。</p>

		<h3 class="midashi05">③ 佐川急便の飛脚ゆうメール便</h3>
		<p>顧客に代わって佐川急便が差出人となり、郵便局が配達を行います。配達状況の確認はできませんが、郵便局のシステムを経由するため、ゆうメールと同様に転居から1年間は新しい住所へ届けてもらえます。</p>

		<h3 class="midashi05">④ 日本郵便の郵便</h3>
		<p>信書などを送る場合はメール便が使えません。信書を送る場合は郵便局の郵便で送る必要があります。信書に関しては下記ページを参照ください。</p>
		<p><a href="https://www.dm110.jp/DM_matome/Shinsyotoha/"><img src="/images/DM_matome/btn_Shinsyotoha.png" width="760" height="126" alt="信書の詳細はこちら" decoding="async" loading="lazy"></a></p>
	</section>


	<section id="m02">
		<h2 class="midashi02">DMの発送でよく使われるメール便とは？</h2>
		<p><img src="/images/DM_matome/me-rubin_okurikata_sub2.jpg" width="1980" height="1320" alt="" decoding="async" loading="lazy"></p>
		<p>メール便とは、最大A4サイズ程度の軽くて薄い荷物を、配達員が郵便ポストや宅配ボックスに届けてくれるサービスです。</p>
		<p>配送業者によってサービス名が異なり、日本郵便ならゆうメールなど、ヤマト運輸ならクロネコDM便など、佐川急便なら飛脚ゆうメール便などと呼ばれています。配送料金や配送できるサイズ・重さ、送り方は業者によって異なります。それぞれのメール便に特徴があるため、使い分けることによりコストダウンができます。</p>
		<p>また、メール便では荷受人の希望をもとに出荷されるものや、信書に該当するDMの発送はできません。以降にて各社のサービスをそれぞれ紹介しますので、参考にしてください。</p>
	</section>


