		<h3 id="m03-1" class="midashi03">ヤマト運輸</h3>
		<p>ヤマト運輸のメール便「クロネコDM便」は契約した法人や個人が利用できる受領印不要の投函サービスです。</p>
		<p>書籍や雑誌、商品カタログ、CDやDVDなどを発送できます。ただし、信書や印刷していない手書きの紙などは発送できないため注意してください。</p>
		<p>料金は全国一律ですが、数量や出荷形態などによって顧客ごとに料金が異なります。ただし、1冊あたりの上限金額は167円（税込）となっているため、予算状況に応じて利用の可否を決定してください。</p>
		<p>クロネコDM便の対応サイズは、3辺の合計が60cm以内、最長辺34cm以内、厚さ2cm以内、重量1kg以下のものに限られます。発送できる最小サイズは長辺23cm、短辺11.5cmと設定されているので、注意してください。配達日は400km圏内であれば発送から翌々日、400km圏以上は4日目（発送日を含む）が目安です。</p>
		<p><img src="/images/DM_matome/me-rubin_okurikata_sub3.png" width="1500" height="1000" alt="クロネコDM便 3辺の合計が60cm以内、最長辺34cm以内、厚さ2cm以内、重さ1kg以下" decoding="async" loading="lazy"></p>
		<p>クロネコDM便の特徴は、到着経路や到着状態を把握できる「ひもつけ」にあります。DM発送代行業者を通じてクロネコDM便を利用すると、ひもつけの制度を利用できます。一部業者ではひもつけに対応していない場合もあるため、見積もり時に確認してください。</p>
		<p>また、DMに封入する内容物の印刷や封入・封緘などのオプションサービスも提供しています。</p>
		<p>弊社ではクロネコDM便とゆうメール便を比較した場合、返品率はゆうメール便の方が低く、成約率はクロネコDM便の方が高いというデータがでています（2019年6月現在）。このようなデータも参考にしながら、サービスを選択してください。</p>

