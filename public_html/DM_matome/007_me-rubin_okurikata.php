	<section id="m04">
		<h2 class="midashi02">【運送会社別】メール便の送り方</h2>
		<p><img src="/images/DM_matome/me-rubin_okurikata_sub6.jpg" width="1980" height="1320" alt="" decoding="async" loading="lazy"></p>
		<p>ここでは運送会社別にメール便の送り方をご紹介します。送り方によってはサービスを利用できない可能性もあるため、各社の内容を比較して利用サービスを検討してみてください。</p>

		<h3 id="m04-1" class="midashi03">ヤマト運輸（クロネコDM便）</h3>
		<p>クロネコDM便を送る際は、まず、送付する荷物を準備して専用の宛名ラベルを作成・発行します。宛名ラベルには様式に従い、届け先の郵便番号や住所、氏名を記載してください。</p>
		<p>ヤマト運輸のビジネスメンバー限定の送り状発行システムを使えば、クロネコDM便の宛名ラベルを簡単に発行できるので、適宜利用してみてください。</p>
		<p>作成した宛名ラベルを荷物に貼りつけ、営業所（全国約4,000ヵ所）への持ち込み、または集荷により発送できます。コンビニエンスストアなどの取扱店では発送できないので注意してください。</p>
		<p>送り状発行システムの利用またはＤＭ発送代行会社へ依頼した場合は、宛名とバーコードの両方が印刷されたラベル1枚で発送できます。</p>
		<p><img src="/images/DM_matome/me-rubin_okurikata_sub7.png" width="360" height="269" alt="クロネコDM便 宛名ラベル" decoding="async" loading="lazy"></p>
		<p>自社で宛名ラベルだけを作成して、DM発送代行会社に発送を依頼する場合は、宛名とバーコードの2つのラベルが必要です。クロネコDM便専用のバーコードのラベルはDM発送代行会社が用意します。</p>
		<p class="uk-flex uk-flex-middle"><img src="/images/DM_matome/me-rubin_okurikata_sub8.png" width="328" height="202" style="max-width:70%" alt="自社宛名ラベル" decoding="async" loading="lazy"> <img src="/images/DM_matome/me-rubin_okurikata_sub9.png" width="136" height="86" style="max-width:29%" alt="クロネコDM便専用のバーコードラベル" decoding="async" loading="lazy"></p>

		<h3 id="m04-2" class="midashi03">日本郵便（ゆうメール）</h3>
		<p>ゆうメールを送る際は、まず、送付する荷物を準備し、宛名を作成します。外装には「ゆうメール」や「冊子小包」などの文字を表示し、次のいずれかの方法により内容が確認できるようにしてください。</p>
		<p>① 封筒または袋の納入口の一部を開く<br>② 内容物の大部分を確認できるよう、包装の外部に無色透明の部分を設ける<br>③ 内容物の見本を郵便局で提示する</p>
		<p>以上をふまえたうえで、郵便ポストまたは郵便局の窓口から発送可能です。ただし、運賃を着払いとするものなどは、郵便ポストでの発送ができませんので注意してください。</p>
		<p>また、運送に航空機を使う遠方の地域へ発送する場合は、配達が遅れる場合があるため注意が必要です。</p>
		<p>料金後納の宛名ラベルを作成する際は、以下の例を参考にしてください。</p>
		<p><img src="/images/DM_matome/me-rubin_okurikata_sub10.png" width="1500" height="800" alt="ゆうメール 宛名ラベル" decoding="async" loading="lazy"></p>

		<h3 id="m04-3" class="midashi03">佐川急便（飛脚ゆうメール便）</h3>
		<p>飛脚ゆうメール便を送る際は、まず初期登録を行います。担当の営業所またはセールスドライバーに問い合わせてみてください。初期登録から利用開始までに1週間程度かかるため、発送前に余裕をもって登録しておくことが大切です。</p>
		<p>荷物に貼るラベルは、通常使っているラベルで問題ありません。郵便番号や住所などが書かれているか確認してから集荷を依頼してください。集荷の際は、飛脚ゆうメール便を利用する旨を担当のセールスドライバーへ伝える必要があります。</p>
		<p>なお、「料金後納」「ゆうメール」と記載するだけでなく、差出人や返還先が佐川急便であることを封筒等の表面に記載する必要があります。封筒に直接記載せず、宛名ラベルに印字しても問題ありません。以下の例を参考に作成してみてください。</p>
		<p><img src="/images/DM_matome/me-rubin_okurikata_sub11.png" width="1500" height="800" alt="飛脚ゆうメール便 宛名ラベル" decoding="async" loading="lazy"></p>
