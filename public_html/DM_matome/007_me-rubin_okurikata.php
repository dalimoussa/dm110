	<section id="m06">
		<h2 class="midashi02">DMをメール便で送るデメリット</h2>
		<p>メリットに続いて、DMをメール便で送るデメリットを、4項目に分けて解説します。</p>

		<h3 id="m06-1" class="midashi03">配達日を指定できない</h3>
		<p>メール便は基本的に配送日時を指定できません。配達したい日があれば、配送にかかる時間から逆算して、早めに発送作業にとりかかる必要があります。</p>
		<p>なお、一部オプションで配達日を指定できるサービスもありますが、追加料金が発生するため利用の際は注意が必要です。また、実際の配送状況を知るためには、追跡サービスがある企業を選択する必要があります。配達日や配達の成否にこだわりたい場合は、サービスを慎重に選んでください。</p>

		<h3 id="m06-2" class="midashi03">ポストに入らなければ持ち戻りになる</h3>
		<p>メール便はポスト投函や宅配ボックスへ配達されるため、規定サイズを満たしていても、相手のポストに入らなければ持ち戻りとなります。</p>
		<p>持ち戻られたメール便は、受け取り側から再配達の依頼をしてもらわなければ配達されないため、メール便の持ち戻りは受け取り側の負担になるといえます。規定のサイズぎりぎりの大きさや重さになる場合は、持ち戻りになってしまう可能性も考慮してください。</p>

		<h3 id="m06-3" class="midashi03">配送物の補償がない</h3>
		<p>メール便で配送した荷物に紛失・破損などのトラブルが発生した場合、運賃の返金はあっても、荷物自体の補償はされません。補償が必要な荷物を送る場合は、補償の付いた発送方法で送る必要があります。</p>

		<h3 id="m06-4" class="midashi03">到着の遅延が起こりやすい</h3>
		<p>中元や歳暮など配送物の量が増える時期は、特にメール便の配達に遅延が発生します。降雪などの天候によっても左右されるため、展示会など日程を記載しているDMを送る際は、余裕をもって送付する必要があります。</p>
	</section>


	<section id="m07">
		<h2 class="midashi02">メール便で起こりやすいトラブルと対応方法</h2>
		<p>メール便を利用する際に知っておきたいのが、起こりやすいトラブルと対応方法です。</p>
		<p>宅配便で送る場合、荷物を届けた際に受け取りの印鑑もしくはサインをいただきますが、メール便では受け取りの確認はありません。このようなメール便の特徴から、実際に以下のようなトラブルが発生しています。</p>
