	<section id="m01">
		<h2 class="midashi02">DMにおける挨拶文の役割</h2>
		<p>DMにおける「挨拶文」とは、顧客への簡単な挨拶として、DMの冒頭や送付状（挨拶状）に書く文章のことです。しかし、挨拶文の真の目的は、「顧客に挨拶すること」ではありません。</p>
		<p>挨拶文は、DMを受け取った顧客が最初に目にしやすい部分であり、DM全体の印象を左右する重要な要素です。そのため、挨拶文次第で顧客の反応が変わる場合があります。</p>
		<p>基本的な礼儀・マナーが守られていない挨拶文や、なんとなく作成した挨拶文では、DMを最後まで読み進めてもらえないかもしれません。挨拶文を社交辞令ととらえ、読み飛ばすお客様もいます。</p>
		<p>読み手を引き込むためには、ターゲットやシチュエーションに合わせた挨拶文を作成する必要があります。</p>

	</section>


	<section id="m02">
		<h2 class="midashi02">DMの挨拶文を作成する際のポイント5つ</h2>
		<p>DMの挨拶文を作成するうえで知っておきたいポイントを、5つ解説します。</p>
		<p class="u-mt0"><img src="/images/DM_matome/DM_aisatubun_sub1.png" width="1500" height="950" alt="DMの挨拶文を作成する際のポイント" decoding="async" loading="lazy"></p>

		<h3 id="m02-1" class="midashi03">顧客の属性によって表現を変える</h3>
		<p>顧客は、おもに「新規顧客」と「既存顧客」に分けられます。</p>
		<p>新規顧客の場合、まずは企業や商品・サービスについて知ってもらうことが大切です。そのため、基本的に挨拶文ではなくキャッチコピーで、企業や商品・サービスの特徴を端的に伝えます。まだ関係が構築されていない段階であり、ケースによっては挨拶文自体を盛り込みません。</p>
		<p>一方、既存顧客の場合は、関係性によって挨拶文の距離感を変えることがポイントです。関係性が深まるにつれ、一般的な挨拶文から的を絞った挨拶文へと変えていきます。的を絞った挨拶文のときには、付き合いのある担当者からの挨拶を入れることがおすすめです。</p>
		<p>また、最近の傾向として挨拶文は簡略化されています。特に個人宛ての場合は、お得な情報や問題解決ができることを挨拶文に含めて、相手に読み進めてもらうことを重要視しています。</p>
		<p>通常、挨拶文のなかに、赤文字や黄色のラインマーカーを入れることはありませんが、内容や目的によっては、これらを入れることで反応率を上げた例もあります。使用する場合は、1ヵ所、多くても2ヵ所までにしてください。強調部分が多くなると売込み色が強くなるためです。</p>

		<h3 id="m02-2" class="midashi03">売り込まない</h3>
		<p>例えば「◯◯（商品・サービス名）をご案内したく、ご連絡を差し上げました」のように、DMの冒頭から商品・サービスの売り込みが始まると、顧客の興味を削いでしまいます。</p>
		<p>DMを読み進めてもらうためには、ビジネスライクな定型文は避け、読み手に興味を持ってもらえるような・共感してもらえるような挨拶文にすることが重要です。商品・サービスの説明は、挨拶文以降の部分で行ってください。</p>
		<p>ただし、通販会社のように、値引き情報を前面に出して反応を上げたい場合は別です。その場合、お客様はDMの値引き情報を待ってから購入を考えるので、毎月のように値引き情報を前面に出したDMを送る必要があります。</p>

		<h3 id="m02-3" class="midashi03">礼儀正しさと親しみやすさを心がける</h3>
		<p>挨拶文から抱く印象は、企業や商品のイメージにも影響します。基本的な礼儀やマナーは守りつつ、業種や商品内容に応じて、親しみやすい表現を取り入れてください。</p>
		<p>文章の主語を読み手（＝あなた）にすると、私信風の挨拶文を書きやすくなります。私信風とは、不特定多数に向けて書かれた文章ではなく、「その人だけに向けて書かれた文章」のことです。</p>
		<p>挨拶文を私信風にすることで「自分に関係のあるDMだ」と認識してもらえ、DMの反応率が高まります。</p>

		<h3 id="m02-4" class="midashi03">メール便ならお客様を特定する言葉や表現を使わない</h3>
		<p>DMの発送をメール便で行う場合は、お客様を特定するような言葉や表現は信書にあたるため、使用することができません。DMに使用される頻度の高い「お客様各位」という表現は、商取引上の慣用語として使用されていることから、この文言のみで信書に該当することはありません。</p>
		<p>信書について、詳しくは以下の記事をご覧ください。</p>
		<p><a href="https://www.dm110.jp/DM_matome/Shinsyotoha/"><img src="/images/DM_matome/btn_Shinsyotoha.png" width="760" height="126" alt="信書の詳細はこちら" decoding="async" loading="lazy"></a></p>

		<h3 id="m02-5" class="midashi03">送付状・挨拶状を用意するなら用紙のサイズ・厚さにこだわる</h3>
		<p>1枚の用紙・ハガキにDMのすべての要素を盛り込むのではなく、挨拶文を「送付状」や「挨拶状」として個別に用意するなら、用紙のサイズや厚さを工夫してください。</p>
		<p>例えば、A4サイズの透明封筒でDMを送るケースでは、送付状・挨拶状もA4サイズで作成してしまいがちです。しかし、封筒と同じサイズの用紙を使うと、送付状・挨拶状を手前に入れたときに、後ろに入れた用紙がまったく見えません。</p>
		<p>そのため、上記のケースの場合は、A4サイズよりも小さいサイズ（A5サイズなど）で送付状・挨拶状を作成します。すると、後ろに入れた用紙も見えるようになり、キャッチコピーや本文で訴求しやすくなります。</p>
		<p>また、送付状・挨拶状には、無難な上質紙を選ぶのがおすすめです。DMによく使われる用紙の厚さは「四六判90～135kg」であり、送付状・挨拶状の場合は四六判90kgを選べば問題ありません。</p>
	</section>


	<section id="m03">
		<h2 class="midashi02">【季節別】挨拶文の例</h2>
		<p><img src="/images/DM_matome/DM_aisatubun_sub2.png" width="1980" height="1311" alt="季節の挨拶文イメージ" decoding="async" loading="lazy"></p>
		<p>ここから、挨拶文の例文を「季節別」「顧客別」「シチュエーション別」に紹介します。</p>
		<p>まずは、季節別の挨拶文の例です。その季節らしい言葉を入れた挨拶文は広く用いられています。新規顧客よりも、既存顧客に向けた挨拶文に用いると効果的です。</p>
	
		<h3 id="m03-1" class="midashi03">◇春の挨拶文</h3>
		<p class="box box--yellow">「まだ肌寒い日が続いておりますが、少しずつ春の気配が感じられるようになりました。◯◯様はいかがお過ごしでしょうか。」</p>
		<p class="box box--yellow">「春らしい陽気の日々が続き、花の便りが聞かれる頃となりました。新しい生活がスタートするこの時期は、◯◯でお困りの方もいるかもしれません。」</p>

		<h3 id="m03-2" class="midashi03">◇夏の挨拶文</h3>
		<p class="box box--yellow">「暑中お見舞い申し上げます。青空がまぶしく厳しい暑さが続く毎日ですが、お変わりなくお過ごしでしょうか。」</p>
		<p class="box box--yellow">「長かった梅雨もようやく終わり、いよいよ夏本番となりました。◯◯様におかれましては、お元気にご活躍のこととお慶び申し上げます。」</p>

		<h3 id="m03-3" class="midashi03">◇秋の挨拶文</h3>
		<p class="box box--yellow">「秋風が心地良く、過ごしやすい季節になりましたが、◯◯様はいかがお過ごしでしょうか。」</p>
		<p class="box box--yellow">「さわやかな秋晴れが続く行楽シーズンは、お出かけにぴったりです。今年のお出かけの予定はお決まりでしょうか？」</p>

		<h3 id="m03-4" class="midashi03">◇冬の挨拶文</h3>
		<p class="box box--yellow">「冬の到来を感じる季節となりましたが、貴社におかれましては、ますますご清栄のことと存じます。」</p>
		<p class="box box--yellow">「今年も残すところあとわずかとなり、ご多忙のことと存じますが、◯◯様にはいつもお世話になり厚く御礼申し上げます。」</p>
	</section>


	<section id="m04">
		<h2 class="midashi02">【顧客別】挨拶文の例</h2>
		<p>続いて、顧客別の挨拶文の例です。先述した「新規顧客」と「既存顧客」に加え、「休眠顧客」向けの挨拶文も紹介します。</p>

		<h3 id="m04-1" class="midashi03">新規顧客向けの挨拶文</h3>
		<p class="box box--yellow">「◯◯に興味のある社長様へ<br>突然ご連絡を差し上げますこと、誠に恐縮に存じます。弊社は、◯◯（商品・サービス名）を取り扱っている◯◯社と申します。◯◯で貴社のことを知り、〇〇に関する情報をお届けしたく、ご連絡を差し上げました。」</p>
		<p class="box box--yellow">「◯◯に不安を感じている方へ<br>突然のご連絡となり失礼いたします。私たちは、◯◯で◯◯をしております◯◯社です。近頃、◯◯（不安・悩み）とお考えではありませんか？」</p>

		<h3 id="m04-2" class="midashi03">既存顧客向けの挨拶文</h3>
		<p class="box box--yellow">「先日は新商品をご購入いただき、ありがとうございました。その後、商品に関するお困りごとなどはございませんでしょうか。些細なことでも構いませんので、何かありましたら◯◯（担当者名）までお気軽にご連絡ください。」</p>
		<p class="box box--yellow">「いつも◯◯をご利用いただき、誠にありがとうございます。今回は、日頃の感謝の気持ちを込めて、◯◯様のお役に立てるように特別なご案内を差し上げました。」</p>

		<h3 id="m04-3" class="midashi03">休眠顧客向けの挨拶文</h3>
		<p class="box box--yellow">「いつもお世話になっております。◯◯社の◯◯（担当者名）と申します。弊社の〇〇（商品・サービス名）をご購入いただいてから1年が経つ頃ですが、その後いかがでしょうか。この度は◯◯（商品・サービス名）をお使いいただいている方限定で、ささやかではございますが、割引クーポンを送付させていただきます。」</p>

		<p>特に、休眠期間が長い顧客の場合は、挨拶文の冒頭で差出人や商品・サービス内容を思い出してもらえるようにしてください。</p>
		<p>休眠理由が思い当たるケースでは、その理由によってアプローチを変えるのがポイントです。上記の例では、金銭面の理由で休眠した顧客を想定し、商品の割引案内をしています。</p>
		<p>休眠顧客のメリットとなる情報を提示しつつも、売り込みはしないほうが効果的です。</p>
	</section>


	<section id="m05">
		<h2 class="midashi02">【シチュエーション別】挨拶文の例</h2>
		<p>最後に、シチュエーション別の挨拶文の例を紹介します。</p>

		<h3 id="m05-1" class="midashi03">記念日の挨拶文</h3>
		<p class="box box--yellow">「◯◯様へ<br>お誕生日おめでとうございます。新たな一年をより快適にお過ごしいただけるよう、お祝いの気持ちを込めて、特別にプレゼントをご用意いたしました。」</p>
		<p class="box box--yellow">「いつも◯◯をご利用いただき、ありがとうございます。今月は、◯◯様が会員登録されてから3周年となります。あらためて感謝の気持ちをお伝えしたく、限定キャンペーンの情報をお届けいたしました。」</p>

		<h3 id="m05-2" class="midashi03">発送タイミング別の挨拶文</h3>
		<p>いわゆる「フォローDM」として、商品の購入・到着から一定期間ごとに複数回DMを発送する方法もあります。以下では、商品購入から1週間後・2週間後・1ヵ月後にフォローDMを送ると仮定し、挨拶文の例を紹介します。</p>
		<p>＜1週間後＞</p>
		<p class="box box--yellow">「先日は、◯◯（商品・サービス名）をご購入いただきありがとうございます。商品の到着から1週間が経つ頃ですが、お困りの点やご質問などはございませんでしょうか？」</p>
		<p>＜2週間後＞</p>
		<p class="box box--yellow">「度々のご連絡失礼いたします。今回は、◯◯（商品・サービス名）をご購入いただいた方に向けて、より効果的にお使いいただくための情報をお届けいたしました。」</p>
		<p>＜1ヵ月後＞</p>
		<p class="box box--yellow">「◯◯（商品・サービス名）をご購入いただき、もうすぐ1ヵ月です。以前ご説明させていただいた効果は実感いただけておりますでしょうか？今回は、お得な定期購入サービスのご案内をお届けいたします。ご不明点などございましたら、◯◯（担当者名）までお気軽にご連絡ください。」</p>
	</section>


	<section id="m06">
		<h2 class="midashi02">挨拶文を入れないケースもある</h2>
		<p><img src="/images/DM_matome/DM_aisatubun_sub3.png" width="1980" height="1320" alt="挨拶文を入れないケース" decoding="async" loading="lazy"></p>
		<p>ここまで、DMに挨拶文を入れる前提で例文を紹介しましたが、ケースによっては挨拶文を入れないこともあります。</p>
		<p>例えば、官製ハガキや、普通の官製ハガキをA4サイズにしたA4（ジャンボ）ハガキでは、挨拶文を入れません。文章を書くスペースが限られるハガキでは、挨拶文を入れない代わりに、商品やサービスの特徴をわかりやすく説明する必要があるためです。</p>
		<p>また、「DMの挨拶文を作成する際のポイント5つ」の章で紹介したとおり、新規顧客向けのDMでは、挨拶文を省く場合があります。挨拶文が嘘っぽく感じられたり、読んでも意味がないものに感じられたりと、DMに対して読もうと思う気持ちが薄れてしまうことがあるためです。</p>
		<p>特に新規顧客へのDMは、短時間で興味を引き、読み進めてもらえるかにかかっています。挨拶文だけで反応率を落とすことになりかねません。</p>
	</section>


	<section id="m07">
		<h2 class="midashi02">まとめ</h2>
		<p>DMの挨拶文は、以下の5つのポイントを意識することが大切です。</p>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>顧客の属性（新規顧客・既存顧客）によって表現を変える</li>
			<li>商品・サービスを売り込まない</li>
			<li>礼儀正しさと親しみやすさを心がける</li>
			<li>メール便ならお客様を特定する言葉や表現を使わない</li>
			<li>送付状・挨拶状を用意するなら用紙のサイズ・厚さにこだわる</li>
		</ul>
