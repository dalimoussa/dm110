	<section id="m01">
		<h2 class="midashi02">新規開拓にDMを用いるメリット</h2>
		<p>近年、DMの年間配送数は減少傾向にあります。これは、新規開拓などにDMを用いる会社が少なくなっている（＝ライバルが減っている）という意味です。</p>
		<p>また、消費者側の変化として、メルマガは開封されにくい一方で、DMのような作成・発送に時間やコストがかかるものは反応されやすくなっています。</p>
		<p>したがって、今こそDMを新規開拓に用いれば、他社と差をつけられます。</p>
		<p>加えて、絞り込んだターゲットに複数回DMを発送したり、インターネットとDMを連携したりすると、新規開拓効果を高められます。新規開拓DMで特に効果が出やすいのは、BtoBです。</p>
	</section>


	<section id="m02">
		<h2 class="midashi02">新規開拓にDMを用いるデメリット</h2>
		<p>新規開拓に効果的なDMですが、いくつかデメリットもあります。</p>
		<p>DMのなかで費用対効果が高いのは、既存顧客向けのものです。一方、DMの新規顧客獲得単価は、インターネットの新規顧客獲得単価と同じくらい上昇しています。</p>
		<p>コスト面だけでなく、DM作成そのものの負担もデメリットと感じるかもしれません。</p>
		<p>また、最近はインターネットで情報を得ようとする方が増えているため、先述のとおり、インターネットとDMをうまく連携してデメリットを回避する必要があります。</p>
	</section>


	<section id="m03">
		<h2 class="midashi02">新規開拓を成功させるDM活用5つのコツ</h2>
		<p>新規開拓にDMを用いるメリット・デメリットを踏まえ、新規開拓DMを成功させるコツを5つ紹介します。</p>
		<p><img src="/images/DM_matome/shinki_kaitaku_DM_sub1.png" width="1980" height="1170" alt="" decoding="async" loading="lazy"></p>

		<h3 id="m03-1" class="midashi03">ターゲット像を明確にする</h3>
		<p>最も重要なのが、DMの送り先（ターゲット）です。</p>
		<p>ターゲットを選定するために、名簿を購入するケースもあります。例えば、会社名簿に記載されているのは、次のような項目です。</p>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>会社名</li>
			<li>郵便番号・住所</li>
			<li>電話番号・FAX番号</li>
			<li>業種・業態</li>
			<li>従業員数</li>
			<li>売上</li>
			<li>資本金</li>
		</ul>
		</div>
		<p>BtoBの場合は、既存顧客の地域・業種・規模などの共通点をもとに、ターゲット像を明確にしたうえで名簿と照らし合わせてください。すると、売り込む商品・サービスに関心がありそうなターゲットを絞り込めるため、DM内容と送り先の齟齬が少なくなります。</p>
		<p>一方、BtoCの場合は、ターゲットを年齢や性別で分類しやすいものの、商品・サービスに関心を持ってもらえる確率は低くなります。したがって、BtoBと比べると開封率が落ちやすい点に注意が必要です。なお、BtoCの場合は名簿に関する個人情報保護法があるため、DM発送時は注意が必要です。</p>

		<h3 id="m03-2" class="midashi03">ターゲットを限定したDMを作成する</h3>
		<p>DMを「不特定多数に送られるもの」と認識している方は多いため、DMを送っても読んでもらえない可能性があります。</p>
		<p>DMを「自分に関係があるもの」と認識してもらうには、文章の冒頭に工夫が求められます。「お客様各位」や「中小企業の皆様へ」のような抽象的な表現ではなく、前項で絞り込んだターゲットを念頭に置き、具体性のある文言を考えてください。</p>
		<p>例えば、「人手不足にお悩みの製造業の社長様へ」「M＆A会社に不安を感じている社長様へ」などが挙げられます。</p>

		<h3 id="m03-3" class="midashi03">1つの商品・サービスに限定する</h3>
		<p>「DMを出すならできるだけ多くの商品・サービスを紹介しよう」と考えるかもしれません。</p>
		<p>しかし、新規開拓DMでは、原則として1つの商品・サービスに限定することがポイントです。メッセージが明確になるほか、ターゲットが複数の選択肢で迷うことがなくなるため、訴求力や反応率の向上につながります。</p>
		<p>また、売り込み色が強いと、ターゲットの興味は削がれてしまいます。売り込むというよりも、ターゲットの困りごとなどに寄り添う形で、商品・サービスのベネフィットを伝えてください。ベネフィットを伝える際は、商品・サービスについてまったく知らない方でも理解できる内容を心がけます。</p>

		<h3 id="m03-4" class="midashi03">ホームページに誘導する</h3>
		<p>DMに興味を持ってもらったらホームページへ誘導し、さらにメリットや必要性を感じてもらうことで、新規開拓の成功率が高まります。そのため、ホームページの体裁や内容も整えておかなければなりません。</p>
		<p>見やすい文章・画像は前提としたうえで、次のような基本情報が網羅されているか確認してください。</p>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>会社概要・沿革</li>
			<li>商品・サービスの一覧</li>
			<li>料金表</li>
			<li>取引実績</li>
			<li>お客様の声</li>
		</ul>
		</div>
		<p>上記に加えて、ホームページ（トップページ）のURLと、DMの内容と関連する個別ページのURLを記載します。</p>
		<p>また、DMがきっかけでホームページを見た方へ、特典を用意する方法もあります。</p>

		<h3 id="m03-5" class="midashi03">PDCAを回して内容を改善する</h3>
		<p>実際にターゲットへDMを送ったら、PDCAを回しながら内容を改善することが重要です。</p>
		<p>DMの反応率を確認しながら、文章・写真・売り込む商品・特典・送付タイミングなどの要素を変えてみて、より良い反応を得られるDMを探ってください。</p>
		<p>また、1回のDMで反応が得られなくても、ターゲットは「忙しく見る暇がなかった」「届いたのを忘れていた」だけかもしれません。そのため、DMは要素を変えながら複数回送り、ターゲットの目に留まる機会を増やす必要があります。</p>
	</section>


	<section id="m04">
		<h2 class="midashi02">新規開拓にDMを用いる際の注意点</h2>
		<p>新規開拓DMの反応率や開封率は、既存顧客向けのDMと比べると、どうしても低くなってしまいます。</p>
		<p>例えば、DMの反応率について、新規顧客と既存顧客では通常5倍ほどの差があるといわれています。実際には、新規顧客よりも既存顧客のほうが、反応率が10～20倍以上良いことも珍しくありません。</p>
		<p>したがって、ターゲットと一度接触してすぐに良い反応を得ることを目指すのではなく、定期的なフォローを続け、必要とされたときに対応できるようにすることが大切です。先述のとおり、PDCAを回しながらDM作成・発送を継続してください。</p>
