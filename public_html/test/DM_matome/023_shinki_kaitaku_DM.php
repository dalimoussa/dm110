	<section id="m06">
		<h2 class="midashi02">新規顧客へのDM挨拶文の例文</h2>
		<p><img src="/images/DM_matome/shinki_kaitaku_DM_sub3.png" width="1980" height="1166" alt="新規顧客へのDM挨拶文の例文" decoding="async" loading="lazy"></p>
		<p>最後に、新規顧客へ送るDMの挨拶文について、例文を2つ紹介します。</p>

		<p class="midashi05">【例1】</p>
		<div class="box box--blue">
		<p>「拝啓　時下ますますご健勝のこととお慶び申し上げます。<br>弊社は、◯◯を取り扱っている△△株式会社と申します。突然のご連絡で誠に恐縮ですが、●●にて貴社のことを知り、お手紙を送付させていただきました。」</p>
		</div>

		<p class="midashi05">【例2】</p>
		<div class="box box--blue">
		<p>「突然のご連絡失礼いたします。先日は、弊社のイベントに足をお運びくださり、誠にありがとうございます。◯◯にご興味をお持ちの方に、▲▲に関する情報をお届けしたいと思い、お手紙を差し上げました。」</p>
		</div>

		<p class="u-mt50">新規開拓DMでは、突然の連絡であることを詫びる文言を入れるのがおすすめです。</p>
		<p>挨拶文が丁寧すぎても途中で離脱される可能性があるため、適切な言葉選びで簡潔に記載してください。</p>
		<p>なお、A4ハガキの場合には挨拶文を入れない方法もあります。あくまでも内容に興味を持ってもらうキャッチコピーを優先させるためです。また、封筒に封入する場合も挨拶文は必要最小限に抑える方法が増えています。業種によっては新規顧客に送るDMに挨拶文を入れない場合もあります。</p>
