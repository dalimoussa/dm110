	<section id="m01">
		<h2 class="midashi02">DMを作成する方法は3通り</h2>
		<p><img src="/images/DM_matome/DM_sakusei_sub1.jpg" width="1980" height="1320" alt="" decoding="async" loading="lazy"></p>

		<p>DMを自社で作成する方法と、制作会社へ作成を依頼する方法、クラウドソーシングを利用する方法のメリット・デメリットをそれぞれ解説します。</p>

		<h3 id="m01-1" class="midashi03">1．自社で作成する</h3>
		<p>市販のソフトやアプリ、DMを作成できるサイトを使えば、専門のデザイナーが不在でも自社でDMは作成できます。無料で利用できるアプリやソフトもあるため、費用を抑えられ、デザインの追加や変更も簡単にできるのがメリットです。</p>
		<p>ただし、自社でDMを作成する場合、すべての作業を自力で行わなければなりません。</p>
		<p>文章やデザイン・写真・イラストなど、DMにはさまざまな要素があり、これらすべてをプロと同等に仕上げようとすると、時間や手間がかかります。また、作成中にプロからアドバイスをもらえないため、迷ったり悩んだりしても自社内で解決しなければなりません。</p>
		<p>自社でのDM作成は、作成時間や作成するスキル、人手などに余裕がある場合におすすめです。</p>

		<h3 id="m01-2" class="midashi03">2．DMの制作会社へ依頼する</h3>
		<p>よりDMのクオリティを高めたいなら、DMの制作会社へDM作成を依頼してみてください。</p>
		<p>費用はかかりますが、DM作成のすべてをプロに任せられるため、手間が省けるだけでなく、成果の出るDMを作成できます。</p>
		<p>ただし、業者選びを間違うと、費用がかさむ・思ったような成果が出ないなどの可能性もあるため注意が必要です。依頼する際は複数社に見積もりを提出してもらい、費用面だけでなく、実績があるか、対応は迅速かなど、サービス面も考慮して最適な業者を選択してください。</p>

		<h3 id="m01-3" class="midashi03">3．クラウドソーシングを利用する</h3>
		<p>コストを抑え、柔軟に対応できるようにする方法として、クラウドソーシングを利用してDM作成する会社が増えています。</p>
		<p>以前は自社作成かDMの制作会社に依頼する方法が主流でした。しかし、今では優秀な人材が低コストで利用できる環境が整ってきました。</p>
		<p>具体的には以下のようなサイトがあります。</p>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>ランサーズ</li>
			<li>クラウドワークス</li>
			<li>ジョブハブ</li>
		</ul>
		</div>
		<p class="u-mt20">デザインや校正、文書作成など細かく分けて依頼することで、コストを下げより安く、良いものを作成できる可能性が高くなります。</p>

		<h3 id="m01-4" class="midashi03">実際にDM作成で効果を上げている会社の特徴</h3>
		<p>実際に当社のお客様でDM・ニュースレターで効果を上げ続けている会社様は、以下内容のいくつかを行っています。</p>
		<div class="box box--yellow">
		<ul class="list-decimal">
			<li>DMテストを続けている</li>
			<li>社長がDM作成に関わっている（大企業を除く）</li>
			<li>DM制作会社は最初だけで2回目以降は自社内で作成している</li>
			<li>発送回数が増えるにつれ自社作成部分が増えている</li>
			<li>ひな型などを利用しつつ自社独自の内容を増やしている</li>
			<li>自社で足りない部分だけクラウドソーシングしている</li>
		</ul>
		</div>
	</section>


	<section id="m02">
		<h2 class="midashi02">効果的なDMを作成する8つのコツ</h2>
		<p><img src="/images/DM_matome/DM_sakusei_sub2.png" width="1500" height="900" alt="" decoding="async" loading="lazy"></p>
		<p>効果的なDMを作成するためには、どのような点に注意すれば良いのか、知っておきたい8つのポイントを解説します。</p>

		<h3 id="m02-1" class="midashi03">DMテストを行う前提で作成する</h3>
		<p>DMを作成するときの一番大切なポイントは、DMテストを行う前提で、内容の異なる2種類のDMを用意することです。2種類のキャッチコピーを用意して、DMを作成してみてください。</p>
		<p>通常、広告代理店やDM制作会社にDM作成を依頼すると、1種類のDMしか作成してもらえません。しかし、DMを作成するプロは、効果を正確に計るテストのためにDMを複数作成します。</p>
		<p>DMテストを行わなければ、DMが成功しているのか失敗しているのかわかりません。効果がわからないDMは、単なる「バクチDM」で終わってしまう可能性もあります。</p>
		<p>DMテストは、DM作成で押さえるべき大事な要素です。2回目、3回目のDM発送ができるよう予算を組んでおき、どのようなテストをすべきか検討します。</p>
		<p>DMテストの詳しい内容は下記リンク先で解説しているので、併せてご確認ください。<br><a href="https://test.dm110.jp/message.html">90%以上の人が知らずに損をしているDMの真実 →</a><br><a href="https://test.dm110.jp/DM_test_point.html">DMテストのポイント →</a></p>

		<h3 id="m02-2" class="midashi03">ターゲットを明確にする</h3>
		<p>DM作成前に、どのような顧客にDMを送るのかを明らかにしておくことも重要です。一般顧客向けのDMであれば年齢・性別・年収など、企業向けのDMであれば業界・企業規模・企業の抱える課題などを設定し、具体的にターゲットを決めておきます。</p>
		<p>設定したターゲットのニーズに合わせて文章やデザインを決定すれば、DMの方向性がぶれないうえ、ターゲットに適さないDMを作成してしまうリスクを避けられます。</p>
		<p>しかし、ターゲットを絞らず不特定多数に向けて作成したDMは、訴求内容が曖昧になり、DMの効果が薄くなってしまいかねません。</p>
		<p>ターゲットを明確にしたうえで、ターゲットに合わせたDMを作成してみてください。</p>

		<h3 id="m02-3" class="midashi03">キャッチコピーを大きく表示する</h3>
		<p>どんなに良いDMを作っても、興味を持ってもらわなければDMは読まれません。</p>
		<p>DMのなかでも顧客の目に真っ先に入る情報であるキャッチコピーは、DMを読んでもらうための重要な要素です。</p>
		<p>設定したターゲットが関心を持ちそうなキャッチコピーを考え、目立つ場所に大きく配置することで、顧客の心をつかみやすくなります。</p>
		<p>キャッチコピーは2種類作成し、毎回DMテストを繰り返すことをおすすめします。</p>

		<h3 id="m02-4" class="midashi03">顧客のメリットを丁寧に伝える</h3>
		<p>DMを読むことでどのようなメリットがあるのかを、顧客がイメージしやすいようにわかりやすく書くことも大事です。</p>
		<p>メリットを提示する際は、DM内容にマッチした具体的な数字を入れることをおすすめします。数字を入れづらい商品・サービスの場合でも、アンケートをとるなどの工夫で数値を出し、反応率を上げた事例もあります。</p>
		<p>また、顧客を主語にしてメリットを解説するのも効果的です。「○○で困っていませんか？」「○○になれます」など、顧客を主語にすると、よりDMの内容を身近に感じてもらえます。</p>

		<h3 id="m02-5" class="midashi03">わかりやすさを重視する</h3>
		<p>人はわからない言葉が3回続くと、読むのを止めてしまうといわれています。そのため、DMの内容を簡単に理解してもらうための工夫も必要です。</p>
		<p>例えば、専門用語はわかりやすい言葉に置き換えてください。どうしても専門用語を使わなければならない場合は、必ずその前後で解説を加え、顧客の理解を助けることが大切です。ただし、DM内容に合致する専門家へ送る場合には、専門用語を適宜使用しても問題ありません。</p>
		<p>また、「とても」「ものすごく」「たくさん」「みんなが」といった抽象的な言葉の使用も避けてください。抽象的な言葉は受け取り方によって内容が変わるため、多用すると商品やサービスのイメージが適切に伝わりません。</p>
		<p>抽象的な言葉は絶対に使用禁止、というわけではありませんが、少なくともDMのメインであるキャッチコピーに使うのは避けるべきです。</p>
		<p>また、一文を短くする・語句の繰り返しを避ける・文字を詰め込みすぎない・ターゲットに合ったフォントを使用するといった工夫も、わかりやすさにつながります。</p>

		<h3 id="m02-6" class="midashi03">レイアウトはZ型またはN型に配置する</h3>
		<p>空白は、読み手に読みやすい印象を与えます。情報を詰め込みすぎず、空白を適切に配置すれば、DMの反応率も上がります。絵や写真のない文字だけのDMであったとしても、空白を使って読みやすさを演出してみてください。</p>
		<p>また、顧客の視線を意識して、要素をZ型またはN型で配置すると、顧客がより内容を理解しやすくなります。横文字のDMはZ型、縦書きのDMはN型のレイアウトを使用し、読みやすくなるような工夫が大切です。</p>
		<p><img src="/images/DM_matome/DM_sakusei_sub3.png" width="1500" height="800" alt="" decoding="async" loading="lazy"></p>

		<h3 id="m02-7" class="midashi03">写真や表・グラフを効果的に使う</h3>
		<p>文章で表現するよりも、視覚的に理解できる写真や表・グラフで表現するほうが情報を伝えやすい場合もあります。わかりにくいと感じた場合は、表やグラフにできないか、一度考えることが大事です。</p>
		<p>視覚的な情報のなかでも写真は特に目を引きます。DMの内容や季節にあったものを選択することで、顧客にDMのイメージを伝えられます。</p>

		<h3 id="m02-8" class="midashi03">問い合わせや購入への誘導は最後に行う</h3>
		<p>冒頭でいきなり商品を売り込むと、顧客が離れてしまいかねません。DMの最終目的は商品やサービスを購入してもらうことにありますが、焦らずに商品やサービスの内容を説明したうえで、最後に購入へ誘導してください。</p>
	</section>


	<section id="m03">
		<h2 class="midashi02">DMを無料でプロに見てもらう</h2>
		<p>DMが作成できたとしても「このDMで大丈夫なのだろうか……」と悩みや疑問は生じるものです。こういった悩みや疑問を、自社内で解決するのは困難です。</p>
		<p>悩みや疑問を簡単に解決したいなら、DM作成のプロにDMを見てもらうのがおすすめです。プロに依頼すれば、蓄積されたデータや経験をもとに、DMの改善方法や、開封率・反応率を上げる方法をアドバイスしてもらえます。</p>
		<p>プロに相談すると費用がかかるのでは、と思われるかもしれませんが、DM制作会社やDM発送代行会社のなかには、DMについて無料で相談を受け付けている会社もあります。</p>
		<p>DM発送代行センターでは無料でDMのアドバイスを行っています。DMの効果を高めるためにも、サービス利用を検討してみてください。</p>
	</section>


