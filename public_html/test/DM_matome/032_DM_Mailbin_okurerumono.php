	<section id="m07">
		<h2 class="midashi02">DM発送は「宅配便」と「メール便」の使い分けも大切！</h2>
		<p>雑誌や商品カタログなどを送る際、宅配便を利用するケースも多いかもしれません。メール便は、宅配便に比べて発送費用を抑えられるため、状況によって使い分けることが大切です。</p>
		<p>例えば、ヤマト運輸のサービスを使って、とある顧客に一冊500gの商品カタログを3冊送る必要があるとします。</p>
		<p>クロネコDM便は1kg以下の荷物しか送れないため、重量オーバーになります。こうなると、通常なら宅配便を利用しようと考えます。しかし、3冊の商品カタログを2冊と1冊に分ければ、クロネコDM便で発送可能です。</p>
		<p>あえてメール便を利用することで発送回数が増えても、発送費用の合計金額は宅配便よりも安くなることがあります。ただし、封入点数や一ヵ所への配達通数、封筒の選び方など複雑な作業が必要になります。送りたいものと各種メール便サービスの条件を照らし合わせて、発送費用の削減を目指してください。</p>
		<p class="u-mt30">カタログを安く発送する方法や実例は以下の記事で詳しく紹介しています。ぜひ参考にしてください。</p>
		<p><a href="https://test.dm110.jp/catalogs.html"><img src="/images/DM_matome/btn_catalogs.png" width="760" height="126" alt="カタログを安く発送する方法はこちら" decoding="async" loading="lazy"></a></p>
	</section>
	

