	<section id="m01">
		<h2 class="midashi02">DMとは？</h2>
		<p>DMとは、自社の商品・サービスを個人または法人へ売り込むための、販促媒体の一つです。宣伝のために送る新商品の案内や割引のお知らせ、パンフレット、カタログなどはすべてDMに該当します。</p>
		<p>なお、DMと相性の良い媒体には以下のとおりです。これらの媒体はDMと連動することで、効果が上がりやすくなります。</p>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>インターネット</li>
			<li>電話</li>
			<li>FAX</li>
		</ul>
		</div>
	</section>


	<section id="m02">
		<h2 class="midashi02">DMの目的はさまざま</h2>
		<p>DMを出す目的は、ケースによってさまざまです。</p>
		<p>例えば、新規顧客の獲得が目的の場合もあれば、既存顧客へのフォローや、休眠顧客の引き戻しなどが目的の場合もあります。</p>
		<p>また、新商品の案内やイベントのお知らせなどのように、特別な情報を届けるためにDMが用いられます。一方で、特別な内容ではないものの、顧客との接触頻度を増やし、関係性を築くためにDMを出すケースも考えられます。</p>
	</section>


	<section id="m03">
		<h2 class="midashi02">DMの5つのメリット</h2>
		<p>DMのおもなメリットを解説します。</p>
		<p><img src="/images/DM_matome/DM_merit_sub1.png" width="1500" height="900" alt="DMのメリット" decoding="async" loading="lazy"></p>

		<h3 id="m03-1" class="midashi03">真似されにくい</h3>
		<p>最も重要なのが、DMの送り先（ターゲット）です。</p>
		<p>効果的なDMを企画するのは、決して簡単ではありません。どのようなDMにするか決めてからも、実際に作成・発送するのにコストや時間がかかります。</p>
		<p>また、DMは誰もが閲覧できるものではなく、受け取った本人・会社だけが内容を把握できるものです。</p>
		<p>これらの点から、DMは他社に真似されにくいメリットがあります。</p>
		<p>DMに対し、作成に比較的時間がかからず、宛先を限定できないインターネット（ホームページなど）で販促しようとすると、他社に真似されやすくなります。</p>
		<p>他社に真似されにくい方法を取ることで成功を続けている会社の実践例を紹介します。</p>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>ライバルの主戦場に入らないように、東京を除く全国へ発送する</li>
			<li>日本海側だけの特別な内容のDMを発送する</li>
			<li>新潟県内は地域により購買特性が違うので、DM内容により発送しない地域を作る</li>
		</ul>
		</div>
		<p>このように地域を分析して内容の違うDMを複数出したり、発送しない地域を作ったりすることで、よりライバルに把握されにくくなります。</p>

		<h3 id="m03-2" class="midashi03">効果が長続きする</h3>
		<p>インターネットと異なり、DMは効果が長く持続します。</p>
		<p>その理由として、紙媒体は手元に残るため、自分から情報を探しにいかなくても、何度でも確認できることが挙げられます。また、デジタル媒体よりも紙媒体のほうが、記憶に残りやすいのも特徴です。</p>
		<p>効果が長続きすれば、DMを受け取った直後は行動を起こさなくても、後日の問い合わせや購入につながる可能性が高くなります。</p>
		<p>さらに、手元に残ることでDMを受け取った本人だけでなく、個人宛なら顧客の家族、法人宛なら他部署の人などにも間接的に情報が届きやすい点もメリットです。DMを保存してもらうことを目的に作成する方法もあります。</p>

		<h3 id="m03-3" class="midashi03">ターゲットを限定できる</h3>
		<p>DMなら、顧客のなかから特定のターゲットを選び、最適な情報を届けられます。</p>
		<p>特に、DMのみに反応する顧客が一定数存在するため、その顧客に向けて自社の商品・サービスを効果的に訴求可能です。</p>
		<p>また、すべてインターネットで完結しようとすると、普段インターネットを利用しない顧客はターゲットから漏れてしまいます。手元に届くDMなら、誰にでも簡単に情報を届けられるため、Webリテラシーなどに左右される心配はありません。</p>
		<p>顧客への認知を深めるために、DMとメールを組み合わせて使うことで効果を上げている会社もあります。</p>

		<h3 id="m03-4" class="midashi03">既存顧客に効果が高い</h3>
		<p>DMのなかで特に費用対効果が高いのは、既存顧客の離脱防止と追加商品購入のために送るDMです。</p>
		<p>離脱防止と利益率の関係は、「5対25の法則」として知られています。具体的には、顧客の離脱を5％改善できれば、利益率が25％アップするという法則です。</p>
		<p>当社（株式会社メディアボックス）や、当社と関わりのある企業様のテスト結果では、顧客の離脱を5％改善できれば、実質30％以上の粗利が増えています。</p>

		<h3 id="m03-5" class="midashi03">サンプル品・プレゼントを入れられる</h3>
		<p>DM反応率を上げるためにサンプル品やプレゼントを入れることはとても重要です。</p>
		<p>クロネコDM便でDMを送る場合は、以下のサイズ制限に注意してサンプル品やプレゼントを入れてください。</p>
		<p class="midashi05">上限のサイズ</p>
		<ul class="list-circle u-ml30">
			<li>3辺計60cm以内（最長辺34cm以内）</li>
			<li>厚さ2cm以内</li>
			<li>重さ1kg以内</li>
		</ul>
		<p class="midashi05">下限のサイズ</p>
		<ul class="list-circle u-ml30">
			<li>長辺23cm×短辺11.5cm以上</li>
		</ul>
