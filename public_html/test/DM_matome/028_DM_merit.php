	<section id="m04">
		<h2 class="midashi02">DMの3つのデメリット</h2>
		<p>DMのおもなデメリットを解説します。</p>
		<p><img src="/images/DM_matome/DM_merit_sub2.png" width="1500" height="650" alt="DMのデメリット" decoding="async" loading="lazy"></p>

		<h3 id="m04-1" class="midashi03">コストと時間がかかる</h3>
		<p>先述のとおり、DMの作成・発送にはコストと時間がかかります。</p>
		<p>ただし、コストを抑えてDMを出すことも可能です。具体的には、次のいずれかの方法でDMを送ります。</p>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>納品書や請求書に同梱する</li>
			<li>商品に同梱する</li>
			<li>顧客を訪問する際に持参する</li>
		</ul>
		</div>
		<p>これらの方法なら、印刷コストはかかるものの、発送コストはかかりません。DMを出す場合は、なるべくコストをかけない方法から始めるのがおすすめです。</p>

		<h3 id="m04-2" class="midashi03">個人の新規顧客へ送るDMは費用対効果が低い</h3>
		<p>個人の新規顧客へDMを発送する場合、個人情報保護法により、誰にでも好きに発送できないのが現状です。</p>
		<p>具体的には「DMを送っていいですよ」と承諾を得ていないところに送ると、違法になります。そのため、新規DM発送リストの獲得にコストがかかります。</p>

		<h3 id="m04-3" class="midashi03">送り先の住所の調査と管理に手間がかかる</h3>
		<p>DMを取り扱ううえでは、個人情報を守るための対策が必須です。また、DMに記載した送り先の住所などの情報が誤っていると、相手に届かない可能性があります。</p>
		<p>法人名簿の場合は、少なくとも年1回は内容を精査し、データを入れ替えるのが一般的です。しかし、なかにはインターネットから情報を集めただけ、または他の業者から得た名簿を使い回しているだけで、実態調査をせずに名簿を販売している業者もいるようです。</p>
		<p>自社の顧客データではなく、外部の業者から入手したデータをもとにDMを送る際には、事前に複数業者から該当地域の名簿を購入・比較し、精度をチェックする必要があります。</p>
		<p>発送ミスを防ぐため、送り先の情報の調査・管理を継続して行う手間がかかる点は、DMのデメリットです。</p>
	</section>


	<section id="m05">
		<h2 class="midashi02">DMのメリットを最大限活かすための3つの方法</h2>
		<p>最後に、DMのメリットを最大限活かすためのポイントを3点解説します。</p>

		<h3 id="m05-1" class="midashi03">Webなどの他の媒体と組み合わせる</h3>
		<p>DMを活用する際は、ホームページ・メールマガジン・ブログ・電話・FAXなど、さまざまな販促媒体と組み合わせることが大切です。「DMのみに反応する顧客が一定数いる」とお伝えしたように、それぞれの媒体で反応する顧客が異なるからです。</p>
		<p>特に最近では、DMを見て商品・サービスに興味を持った顧客は、会社のホームページを見にいくケースが増えています。ホームページでさらに情報を得て、納得してから問い合わせや購入といった行動を起こしています。</p>
		<p>したがって、販促媒体のなかでもインターネットとの融合を重視し、力を入れるべきです。</p>

		<h3 id="m05-2" class="midashi03">既存顧客を中心に送付先を絞り込む</h3>
		<p>DMは新規顧客よりも既存顧客への費用対効果が高いため、ターゲットを既存顧客中心にするのがおすすめです。既存顧客は、次の例のように分類できます。</p>
		<div class="box box--yellow">（例）
		<ul class="list-circle">
			<li>初回購入したばかりの顧客</li>
			<li>取引回数は少ないが一回の購入金額が多い顧客</li>
			<li>一回の購入金額は少ないが長く取引が続いている顧客</li>
			<li>他の顧客から紹介してもらった顧客</li>
			<li>離脱防止のために接触したい顧客</li>
			<li>最近離脱してしまった顧客</li>
			<li>特定の情報を必要としている顧客</li>
			<li>類似商品を他社とも取引している顧客</li>
		</ul>
		</div>
		<p>顧客を分類すると、どのような目的で・どのような情報を届ければ良いかわかりやすくなります。</p>
		<p>なお、新規顧客については、インターネットを中心に集客し、必要に応じてDMを組み合わせる方法を基本としてください。</p>

		<h3 id="m05-3" class="midashi03">同梱物を最大限に使う</h3>
		<p>実際に触れてもらえることもDMの最大のメリットです。そのため、サンプル品やプレゼントなどの現物をDMに同梱することで、開封率や成約率をよりアップさせることができます。</p>
