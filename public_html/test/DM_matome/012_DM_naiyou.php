	<section id="m02">
		<h2 class="midashi02">DMに封入する内容物はどの工程で考えるべき？</h2>
		<p>DMに同封する内容物は、いつ、どのように決定すれば良いのでしょうか。</p>
		<p>通常、DMは以下の手順で作成・発送されます。</p>
		<p>①コンセプト・ターゲットを決める<br>②DMに入れる要素を決める<br>③文章・デザインを決める<br>④最終確認<br>⑤印刷<br>⑥封入<br>⑦発送</p>
		<p>DMに同封する内容物は、コンセプト・ターゲットが決まったあと、「②DMに入れる要素を決める」の段階で検討してください。</p>
		<p><img src="/images/DM_matome/DM_naiyou_sub1.png" width="1500" height="900" alt="DM作成・発送の手順" decoding="async" loading="lazy"></p>
		<p>DMのコンセプト・ターゲットを決めずに内容物を決定してしまうと、内容物が顧客と合わず、商品やサービスのメリットが伝わりません。ターゲットとなる顧客が求めるものは何かを考えて、最適な内容物を選択することが大切です。</p>
	</section>


	<section id="m03">
		<h2 class="midashi02">DMで好まれる内容物とは</h2>
		<p>DMの内容物はどのようなものが好まれるのでしょうか。統計データをもとに内容物を選ぶポイントを2つ解説します。</p>

		<h3 id="m03-1" class="midashi03">顧客がメリットを感じられるもの</h3>
		<p>日本ダイレクトメール協会が2021年に行った「DMメディア実態調査」によると、顧客がDMに求めている内容は、以下のグラフのようになっています。</p>
		<p><img src="/images/DM_matome/DM_naiyou_sub2.png" width="1000" height="800" alt="顧客が希望するDMの内容" decoding="async" loading="lazy"></p>
		<p>データによると、「クーポンの案内・プレゼント」や「特売・セール・キャンペーンの案内」「試供品の案内・プレゼント」など、実際に顧客がメリットを感じられる内容が好まれていることがわかります。</p>
		<p>訴求したい商品やサービスに関連した、顧客にとってメリットとなるものを内容物に選択してください。</p>

		<h3 id="m03-2" class="midashi03">パーソナライズされたもの</h3>
		<p>パーソナライズとは「一人ひとりに合わせてサービスを提供すること」をいい、パーソナライズされた内容物は顧客に受け入れられやすくなります。</p>
		<p>先ほども紹介した「DMメディア実態調査」では、パーソナライズされたDMを開封したいかどうか、その意向を調査しています。パーソナライズされたDMを開封したいと回答したのは全体の約55％であり、開封したくないと回答した12％と比べて高いことがわかります。</p>
		<p><img src="/images/DM_matome/DM_naiyou_sub3.png" width="1500" height="1000" alt="パーソナライズされたDMの開封意向" decoding="async" loading="lazy"></p>
		<p>したがって、内容物を検討する際は、DMのターゲット層に合うものを選択し、パーソナライズされたDMであることを提示するのがおすすめです。</p>
		<p>また、パーソナライズにもパターンがあります。訴求したい商品やサービスを以下のような項目でパーソナライズできないか、検討してください。</p>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>顧客によって価格を変える</li>
			<li>顧客によって商品内容・サービス内容を変える</li>
			<li>顧客によってあいさつ文を変える</li>
			<li>封入順序を変える</li>
			<li>購入履歴によって封入物を変える</li>
			<li>1回目購入者と2回目以降購入者を分ける</li>
			<li>VIP客と一般客を分ける</li>
			<li>離脱客と一般客を分ける</li>
			<li>購入期間によって顧客を分ける</li>
			<li>商品内容によって顧客を分ける</li>
			<li>地域により顧客を分ける</li>
		</ul>
		</div>
	</section>


	<section id="m04">
		<h2 class="midashi02">内容物にこだわって成功したDM事例</h2>
		<p>ここまで、DMの内容物の種類や選び方を解説しましたが、実際にはどのような内容物が商品購入やサービス利用につながっているのでしょうか。ここでは内容物を工夫して成功したDM事例をいくつか紹介します。自社に取り入れられるポイントがないか、参考にしてください。</p>

		<h3 id="m04-1" class="midashi03">デザインを工夫した事例</h3>
		<p>株式会社水星（旧社名：株式会社L&amp;Gグローバルビジネス）は、見込み顧客に対するDMにおいて、デザインを重視した内容物を作成し、顧客満足度を高めました。招待状を模したデザインと世界観に没入できるストーリー設計で、参加型のエンタメ体験を演出し、DMを起点としてイベント前後の体験を深めたことで、高評価を得られたのです。<br>
		出典：<a href="https://www.dm-award.jp/winner/36th/silver/silver-02.html" target="_blank" rel="noopener noreferrer"><cite>日本郵便株式会社　第36回 全日本DM大賞『泊まれる演劇 「MOTEL ANEMONE」招待状』</cite></a></p>

		<p class="u-mt30">また、ピツニーボウズジャパン株式会社は、既存顧客に対する販促DMにおいて、鮮明な原寸大の製品画像を掲載することで、昨年比2.5倍の販売増を記録しました。コロナ禍で実際に商品を手に取って確認する機会が減っていますが、商品のサイズ感やメリットをわかりやすくデザインに落とし込むことで、顧客に商品の魅力をより明確に伝えられたのです。わかりやすいデザインは商談プロセスの効率化にもつながっています。<br>
		出典：<a href="https://www.dm-award.jp/winner/36th/special/special-01.html" target="_blank" rel="noopener noreferrer"><cite>日本郵便株式会社　第36回 全日本DM大賞『コロナ禍で効果を発揮！製品原寸大DMで商談獲得』</cite></a></p>

		<h3 id="m04-2" class="midashi03">オファーを工夫した事例</h3>
		<p>株式会社イムラ封筒は、既存顧客に対するDMでカフェの外観をモチーフにし、特製のドリップコーヒーとコースターを同封しました。気軽に無料で相談できる雰囲気をDM全体で表現することで、新規サービス利用者を増やす効果が得られており、「第36回 全日本DM大賞」で金賞 グランプリにも選ばれています。<br>
		出典：<a href="https://www.dm-award.jp/winner/36th/gold_gp.html" target="_blank" rel="noopener noreferrer"><cite>日本郵便株式会社　第36回 全日本DM大賞『封筒専門会社というイメージ脱却 新規サービスの認知拡大』</cite></a></p>

		<p class="u-mt30">また、花王株式会社は、新規顧客に対するDMでブランド最高峰製品のサンプルを送付し、購入率のアップやワンランク上の商品へのアップセルに成功しています。このDMのポイントは、購入商品とは別のタイミングでサンプルを送付したこと。顧客の予期せぬタイミングでサンプルを送付して、商品の印象がより鮮明に残るよう工夫されています。<br>
		出典：<a href="https://www.dm-award.jp/winner/36th/silver/silver-03.html" target="_blank" rel="noopener noreferrer"><cite>日本郵便株式会社　第36回 全日本DM大賞『「心に残る体験」DMでロイヤリティ、 F2購入率UP』</cite></a></p>
	</section>


