	<section id="m01">
		<h2 class="midashi02">DMに封入するおもな内容物</h2>
		<p>DMには具体的にどのようなものが封入されるのでしょうか。DMのおもな内容物を5種類紹介します。</p>

		<h3 id="m01-1" class="midashi03">あいさつ状</h3>
		<p>顧客に対して安心感や親近感を持ってもらうために、商品やサービスを紹介する文書とは別に同封するのがあいさつ状です。顧客に対して丁寧にあいさつすることで、DMに同封したパンフレットなどを読んでもらえるよう誘導できます。</p>
		<p>あいさつ状で、DMを送付した理由やDMを読むことで顧客が得られるメリットなどを提示できれば、顧客の関心を誘えます。新規顧客、既存顧客、休眠顧客など、顧客の属性に合わせてあいさつの内容を変えるのがポイントです。記念日を迎える顧客に向けて特別なあいさつ状を作成するなど、工夫次第で顧客の関心をより高めることもできます。</p>

		<h3 id="m01-2" class="midashi03">申込用紙</h3>
		<p>申込用紙は、顧客が商品購入やサービス利用を始める際に必要な用紙です。顧客の消費行動と直接関係がないと思われがちな申込用紙ですが、実は申込用紙でDMの反応率は大きく変わります。</p>
		<p>申込用紙の内容がわかりにくい、紙質が悪いため書きづらいなど、些細なことで顧客の購買意欲は減退し、DMの反応率は下がってしまうのです。申込用紙の内容や材質にもこだわり、DM反応率アップにつなげてください。</p>
		<p>また、申込用紙を通してではなく、直接電話で商品購入やサービス利用を始めたい顧客もいます。電話で申し込みを希望する顧客のために、申込用紙には必ず下記項目を記載してください。</p>

		<div class="box box--yellow">
		<p class="midashi05-2">【申込用紙に記載すべき事項】</p>
		<ul class="list-circle">
			<li>電話番号（BtoCの場合はフリーダイヤル必須）</li>
			<li>休日、営業時間</li>
			<li>担当者名（商品やサービスごとに決めておく）</li>
			<li>他の部署に電話がつながったときの対応（顧客をたらいまわしにしないため）</li>
			<li>FAX番号（BtoBの業種によりFAXが有効なため）</li>
			<li>QRコード（スマートフォンから申し込みたい人用）</li>
			<li>検索キーワード（PCから申し込みたい人用に自社ホームページが検索1位に来る語句）</li>
		</ul>
		</div>
		<p>昨今はDMを見てインターネットで商品名やサービス名、会社名などを検索し、ホームページから商品購入やサービス利用を申し込む方も増えています。パソコンとスマートフォンの両方でスムーズに表示できるホームページを用意しておき、顧客の申込機会を増やすのがおすすめです。</p>

		<h3 id="m01-3" class="midashi03">返信用封筒</h3>
		<p>返信用封筒は申込用紙やアンケートなどを返信してもらうための封筒です。封筒を用意することで顧客の返送の手間を減らせるほか、誤送の防止にもなります。</p>
		<p>封筒のサイズは、返送する書類のサイズに合わせて選んでください。A4用紙を三つ折りにして封入できる「長形3号」を使用する場合が多いですが、書類を折らずに返送してもらう場合は、より大きいサイズの封筒を用意するのがおすすめです。</p>
		<p>また、返信用封筒を用意せず、申込用紙と返信用封筒を兼ねたハガキをDMに封入する場合もあります。</p>

		<h3 id="m01-4" class="midashi03">パンフレット・カタログ・冊子など</h3>
		<p>パンフレット・カタログ・冊子は、商品やサービスの特徴をダイレクトに伝える重要な内容物です。これらの発送には宅急便を利用することが多いですが、発送条件を満たせばメール便での発送も可能で、発送費用を大幅に削減できる場合があります。</p>
		<p>パンフレット・カタログ・冊子を同封する場合は、文章やカラー、写真、イラスト、サイズなどにこだわり、顧客の購買意欲を高められるよう工夫してください。</p>
		<p>なお、パンフレット・カタログ・冊子以外にも、DMには以下のようなものが同封される場合があります。どのようなものを同封すべきか、ぜひ参考にしてください。</p>

		<div class="box box--yellow">
		<p class="midashi05-2">【DMに同封されるもの】</p>
		<ul class="list-circle">
			<li>CD</li>
			<li>DVD</li>
			<li>小冊子</li>
			<li>マニュアル</li>
			<li>案内状</li>
			<li>会員誌</li>
			<li>会報</li>
			<li>学会誌</li>
			<li>学校案内</li>
			<li>刊行誌（月刊誌・季刊誌など）</li>
			<li>取扱説明書</li>
			<li>就職案内</li>
			<li>ガイドブック</li>
			<li>イベント案内（セミナーなど）</li>
			<li>名刺</li>
		</ul>
		</div>

		<h3 id="m01-5" class="midashi03">オファー（特典・プレゼント）</h3>
		<p>オファーは特典やプレゼントとも呼ばれており、DMの開封率アップに寄与する要素の一つです。</p>
		<p>例えば、オファーとしてボールペンをつけた場合、ボールペンという異物で注意を引くことで開封したくなるよう誘導したり、ボールペンがもったいないから開封しようという心理を働かせたりする効果も期待できます。</p>
		<p>ボールペン以外にもオファーにはさまざまな種類があります。物理的なオファーと心理的なオファーを以下にまとめていますので、自社の商品やサービスに合ったオファーを選択してください。</p>

		<div class="box box--yellow">
		<p class="midashi05-2">【物理的なオファー】</p>
		<ul class="list-circle">
			<li>押し花</li>
			<li>花の種</li>
			<li>携帯電話のストラップ</li>
			<li>お守り</li>
			<li>カレンダー</li>
			<li>小冊子</li>
			<li>金券</li>
			<li>小銭入れ</li>
			<li>鈴</li>
			<li>石鹸</li>
			<li>箸　など</li>
		</ul>
		</div>

		<div class="box box--yellow">
		<p class="midashi05-2">【心理的なオファー】</p>
		<ul class="list-circle">
			<li>割引</li>
			<li>キャッシュバック</li>
			<li>保証</li>
			<li>多様な支払い方法　など</li>
		</ul>
