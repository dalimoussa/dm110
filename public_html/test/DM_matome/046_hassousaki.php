	<section id="m01">
		<h2 class="midashi02">DMで成果を上げるには「発送先」が重要</h2>
		<p>「成果を上げるためのDM」と聞くと、魅力的な特典・プレゼントを付けたDMや、質の高い内容のDMなどをイメージするかもしれません。</p>
		<p>たしかに、特典・オファーや内容の良し悪しは、DMの成果に影響します。しかし、それよりも重要視すべきなのが、DMの「発送先」です。</p>
		<p>重要度の比重について、当社（メディアボックス）では、発送先が50％、特典・オファーが30％、内容が20％という結果が出ています。</p>
		<p>特典・オファーが付いていないなど、内容が多少荒削りなDMでも、適切なターゲットに届けられればDMの反応率は上がります。したがって、DMの作成・発送を考える際は、まずは「誰に送るのか」を明確にすることがポイントです。</p>
	</section>


	<section id="m02">
		<h2 class="midashi02">DMが効果を発揮しやすい発送先は？</h2>
		<p>ここでは、DMで成果を上げやすい発送先について、さまざまな視点から解説します。</p>

		<h3 id="m02-1" class="midashi03">既存と新規では「既存顧客」</h3>
		<p>顧客のうち、既存顧客と新規顧客に注目すると、DMの効果を発揮しやすいのは既存顧客です。既存顧客向けDMの反応率は、新規顧客向けDMの反応率よりも1桁多くなることも珍しくありません。</p>
		<p>新規顧客向けDMに力を入れている企業は多いものの、新規顧客を獲得するには、大幅な値引きや過剰なサービスの提供を行うと相応のコストがかかります。効率的に成果を上げるには、既存顧客の離脱防止やリピートの促進にDMを活用すべきです。</p>
		<p>当社（株式会社メディアボックス）のデータでは、DMで既存顧客との接触頻度を高め、離脱率を5％も防げれば、30％程度の粗利増加が目指せます。</p>

		<h3 id="m02-2" class="midashi03">BtoCとBtoBなら「BtoB」が有利</h3>
		<p>対個人のビジネスモデルである「BtoC」と、対企業のビジネスモデルである「BtoB」なら、DMの成果の上げやすさはBtoBが勝ります。</p>
		<p>やり方次第では、BtoCでもきちんと効果は出ます。ただし、対個人の場合は、個人情報を取り扱う関係上、アプローチしたいターゲットにDMを発送できるとは限りません。</p>
		<p>一方、対企業の場合は、上記のような心配がないのに加え、一回の取引金額も高額になるため有利です。</p>

		<h3 id="m02-3" class="midashi03">DMと相性の良い業界・業種</h3>
		<p>DMの効果を発揮しやすい業界・業種は、次のとおりです。</p>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>高単価商品を扱う業界・業種</li>
			<li>高粗利商品を扱う業界・業種</li>
			<li>競争が激しい業界・業種</li>
			<li>顧客との関係性が重要な業界・業種</li>
			<li>他社と差別化しにくい業界・業種</li>
			<li>あまり認知されていないニッチな業界</li>
		</ul>
		</div>
		<p>例えば、不動産業界や自動車業界など、高単価・高粗利商品を扱う業界・業種の場合は、一回の取引金額が大きいため、DMの作成・発送コストを上回りやすいと考えられます。</p>
		<p>また、コンサルタント業界や美容系サービス業界など、顧客との関係性が重要な業種・業界もDMとの相性は良好です。DMを定期的に送付することで顧客との接触回数が増え、良好な関係を築きやすくなります。</p>
