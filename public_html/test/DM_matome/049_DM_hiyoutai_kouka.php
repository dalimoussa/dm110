		<h3 id="m05-2" class="midashi03">DM効果が低い業界</h3>
		<p>DMの効果を発揮しにくい業界は、低単価商品・低粗利商品を扱う業界です。また、スーパーで売っている商品のように、誰もが知っていてどこでも手に入る商品を扱う業界も、DMの効果は高くありません。</p>
		<p>ただし、低単価商品・低粗利商品を扱う業界などでも、既存顧客のつなぎとめや離脱顧客の呼び戻し、既存顧客からの新たな顧客の紹介などにうまくDMを活用しています。効果的なDMを継続して出せば、費用対効果は高められます。</p>
