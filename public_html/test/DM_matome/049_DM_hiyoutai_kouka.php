	<section id="m01">
		<h2 class="midashi02">DMにおける費用対効果の考え方</h2>
		<p>反応率が0.01％で「大成功」といえるDMもあれば、反応率が30％で「失敗」と判断されるDMもあります。DMの効果は反応率だけではなく、「粗利が出ているか」「コストがLTV（ライフタイムバリュー）を下回っているか」を考えることが大切です。</p>
	</section>


	<section id="m02">
		<h2 class="midashi02">DM成功を見極める3つの指標</h2>
		<p><img src="/images/DM_matome/DM_hiyoutai_kouka_sub1.png" width="1500" height="580" alt="反応率・粗利・LTV" decoding="async" loading="lazy"></p>
		<p>ここでは、DM成功を見極めるための3つの指標について、概要やポイントなどを解説します。</p>

		<h3 id="m02-1" class="midashi03">反応率</h3>
		<p>DMの反応率とは、DMを送付した顧客のうち、次のような行動（レスポンス）を起こした顧客の割合のことです。</p>

		<div class="box box--yellow">
		<ul class="list-circle">
			<li>インターネットで商品について検索した</li>
			<li>家族や友人などとの会話で商品の話題を取り上げた</li>
			<li>商品の資料を請求した</li>
			<li>商品を購入・利用した　など</li>
		</ul>
		</div>

		<p class="u-mt30">DMの反応率は、次の計算式で求められます。</p>
		<p class="box box--blue">DMの反応率（％）＝ レスポンスの数 ÷ DMの送付数 × 100</p>

		<p>これまでに多くの企業がDMを活用してきたことで、世の中にDMが浸透した現在では、以前と比べてDMの反応率は悪くなっています。実際に、不特定多数を対象としたDMの場合、反応率は0.5～1.0％程度、FAXによるDMだと0.1％程度が目安です。一方で、既存顧客を対象としたDMなら、5.0～15.0％程度の反応率が期待できます。</p>

		<h3 id="m02-2" class="midashi03">粗利</h3>
		<p>粗利は、売上高から原価を差し引いた総利益のことです。いくら売上が良くても、粗利が出なければ事業は継続できません。</p>
		<p>粗利を上げるには、「商品の原価を下げる」「商品の価格を上げる」「一度にたくさん売る」「一人当たりの購入回数を増やす」などの方法が考えられます。</p>
		<p>ただし、リピートのない商品の場合は、同じ顧客に何度も買ってもらうことは期待できないため、1回のDMの粗利で採算が取れるか判断してください。また、粗利から損益分岐点（BEP）を求めれば、どれくらいのコストをかけられるかがわかります。</p>

		<h3 id="m02-3" class="midashi03">LTV</h3>
		<p>リピートがある商品を扱っている場合は、LTV（ライフタイムバリュー）を考えます。LTVは、顧客が自社と取引を始めてから終えるまでの期間にもたらす粗利の合計です。粗利ではなく売上で計算するケースや、期間を1年間や半年に設定するケースもあります。</p>
		<p>通常、新規顧客を獲得するためのコストは、既存顧客を維持するためのコストの5倍といわれています。よって、既存顧客の維持や顧客満足度の判断基準となるLTVは、重要な指標です。</p>
		<p>DMの成否を判断するには、反応率だけを見るのではなく、「DMを発送して反応があった顧客の人数 × LTV」を算出します。その数値がDMの発送にかかったコストを上回れば、そのDMは成功です。逆に赤字となりそうなら、DMの発送は中止してください。</p>
	</section>


	<section id="m03">
		<h2 class="midashi02">DMには見えない費用対効果も</h2>
		<p>DMには、数値化しにくい効果もあります。具体的には、認知度や信頼度の向上です。</p>
		<p>そもそも、ターゲットが自社商品の存在を知っていなければ、商品購入にはつながりません。DMは高い開封率が期待できるため、商品の認知度を高める手段として有効です。</p>
		<p>商品に興味を持ってもらえた場合は、DMを保存してくれる可能性があります。DMを見てすぐに商品購入に至らなくても、あとからDMを思い出す・見返すことで、商品を比較検討する際の選択肢になります。</p>
		<p>また、DMを定期的に送付すると既存顧客との接触頻度が上がるため、信頼関係の構築が可能です。結果として、既存顧客をつなぎとめやすくなります。</p>
	</section>


	<section id="m04">
		<h2 class="midashi02">DMとインターネットの費用対効果の比較</h2>
		<p>ここでは、DMとインターネットの特徴をそれぞれ解説します。</p>

		<h3 id="m04-1" class="midashi03">DMは既存顧客の維持に優れる</h3>
		<p>DMは、特定のターゲットに直接情報を届けられます。効率的なアプローチにより、即効性に優れるのが特徴です。</p>
		<p>なかでも、すでに商品の購入経験がある既存顧客へのDMは、非常に効果的です。DMの一部を手書きにするなど、時間やコストをかけると、良い反応が得られやすくなります。</p>
		<p>また、近年では、販売側の集客意識がインターネットにシフトしている背景などもあり、DM発送数は減少傾向です。ライバルが減っているため、より成功しやすい環境といえます。</p>

		<h3 id="m04-2" class="midashi03">インターネットは新規顧客獲得に優れる</h3>
		<p>一方で、日々多くの方が利用しているインターネットは、DMが苦手とする新規顧客の獲得に優れるのが特徴です。</p>
		<p>インターネットなら、特定のターゲットに直接アプローチする「プッシュ型」でも、不特定多数にアプローチして顧客からの接触を待つ「プル型」でも活用できます。</p>
		<p>ただし、インターネットで効果を上げるためには、大変な労力やコストがかかり、費用対効果が悪いケースも増えています。また、メールマガジンやブログなどでのアプローチは気付かれないことも多く、ターゲットとの関係構築は容易ではありません。</p>
	</section>


