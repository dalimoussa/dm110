	<section id="m06">
		<h2 class="midashi02">DMの費用対効果を高める方法</h2>
		<p><img src="/images/DM_matome/DM_hiyoutai_kouka_sub3.jpg" width="1920" height="1320" alt="DMの費用対効果" decoding="async" loading="lazy"></p>
		<p>最後に、DMの費用対効果を高める方法を解説します。</p>

		<h3 id="m06-1" class="midashi03">インターネットと連携する</h3>
		<p>先述のとおり、DMとインターネットには異なる強みがあります。インターネットが欠かせなくなった今では、DMを見て興味を持ったターゲットは、まず会社のホームページを見に行きます。ホームページからより多くの情報を得たうえで、問い合わせなどの行動をとるか、商品を購入するかなどを判断しているのです。</p>
		<p>そのため、DMを見てホームページを訪れたターゲット用に、ホームページ内に新たなページを追加するなど、確実に成約につなげる導線を作ることをおすすめします。</p>
		<p>また、ホームページ上で問い合わせを行ったが、購入までは至らなかったターゲットに対しては、DMでフォローし続け、自社の商品への興味を継続してもらうことが大切です。</p>
		<p>どの媒体で購入に至るかは顧客によって異なるため、DMとインターネットを連携させれば、顧客の取りこぼしを減らすことができ、費用対効果を高めることにつながります。</p>

		<h3 id="m06-2" class="midashi03">反応率を高める</h3>
		<p>DMの反応率に影響するおもな要素は、次の4つです。</p>

		<div class="box box--yellow">
		<ul class="list-decimal">
			<li>発送先</li>
			<li>オファー（特典・プレゼント）</li>
			<li>内容・デザイン</li>
			<li>発送数</li>
		</ul>
		</div>

		<p>このなかで最も重要なのが、発送先です。先述のとおり、既存顧客向けDMのほうが費用対効果が高いため、まずは既存顧客のなかからターゲットを絞ってください。</p>
		<p>また、顧客にとってメリットとなる特典・プレゼントなどのオファーをつける場合は、商品が無料になる特典を避けることや、商品と関連の深いプレゼントを選ぶことが重要です。</p>
		<p>加えて、DMの内容・デザインは、次のようなポイントを意識する必要があります。</p>

		<div class="box box--yellow">
		<ul class="list-circle">
			<li>抽象的な言葉や専門用語を入れない</li>
			<li>具体的な数字を入れる</li>
			<li>見やすい・読みやすいデザインにする</li>
			<li>訴求する商品を1つに絞る</li>
			<li>表やグラフを活用する</li>
			<li>空白はあえて残す</li>
		</ul>
		</div>

		<p>さらに、DMの反応率は発送数とも関係します。例えば、反応率が0.1％あれば採算が取れる商品なら、1,000件に1件の受注があれば良いため、発送数は1,000件以上となります。このように、目指すべき反応率から発送数を逆算してください。</p>
		<p>なお、ここで紹介した内容も含め、DMの反応率を高めるポイントについては以下の記事で詳しく解説しています。併せて参考にしてください。</p>
		<p><a href="https://test.dm110.jp/DM_matome/Hannouritu/"><img src="/images/DM_matome/btn_Hannouritu.png" width="760" height="126" alt="DM反応率の詳細はこちら" decoding="async" loading="lazy"></a></p>
	</section>


	<section id="m07">
		<h2 class="midashi02">費用0円でDMを出す方法</h2>
		<p>DMは、発送コストをかけずに出すこともできます。具体的な方法は、次のとおりです。</p>

		<div class="box box--yellow">
		<ul class="list-circle">
			<li>納品書や請求書に同封する</li>
			<li>商品に同梱する</li>
			<li>顧客を訪問する際に持参する</li>
		</ul>
		</div>

		<p>例えば、当社から顧客に向けてある商品を送る際は、コストゼロのDMを同梱しており、その場合の成約率は12％です。100件にコストゼロのDMを出したとすると、12件の成約となります。</p>
		<p>さらに、当社のリピート率は67％ですので、コストゼロのDMを入れることにより31件のリピート受注が発生します。当然コストゼロのDMを入れなければ受注はゼロですので、この差がのちに大きな差になるのです。</p>
		<p>実際に、プリンターでモノクロの両面印刷をしたDMを同封しただけで、成約率を10％以上高めた事例もあります。このように、DMにコストをかけなくても費用対効果を高めることは可能です。</p>
	</section>


