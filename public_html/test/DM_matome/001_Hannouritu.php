	<section id="m01">
		<h2 class="midashi02">DMの反応率とは？</h2>
		<p><img src="/images/DM_matome/Hannouritu_sub1.jpg" width="1980" height="1305" alt="" decoding="async" loading="lazy"></p>
		<p>DMの反応率とは、DMを送付した顧客のうち「インターネットで検索した」「商品を購入・利用した」など、期待される行動を起こした顧客の割合のことです。</p>
		<p>DMの反応率は、以下の計算式で求められます。</p>
		<p class="box box--blue">DMの反応率（％）＝ レスポンスの数 ÷ DMの送付数 × 100</p>
		<p>ただし、DMを送付する目的は「最終的に自社の利益を増やすこと」です。そのため、上記の数式に基づくDMの反応率だけで成果を判断するのではなく、以下の点も加味する必要があります。</p>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>最終的な成約数、あるいは粗利額を基準にする</li>
			<li>どのDMが成約のきっかけとなったかを確認できるようにする</li>
			<li>DMによる継続率や離脱率を見極める</li>
		</ul>
		</div>

		<h3 id="m01-1" class="midashi03">DMによる反応の種類</h3>
		<p>顧客がDMを受け取ったあと、実際に起こす行動、すなわち反応の種類は以下のとおりです。</p>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>インターネットで検索する</li>
			<li>家族や友人との話題にする</li>
			<li>実店舗に足を運ぶ</li>
			<li>商品を購入・利用する</li>
			<li>資料請求をする</li>
			<li>問い合わせる</li>
			<li>会員登録をする</li>
			<li>DMを保存する</li>
			<li>SNSに投稿する　　　　　など</li>
		</ul>
		</div>
	</section>


