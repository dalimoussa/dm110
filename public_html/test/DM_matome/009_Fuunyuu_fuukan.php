		<h2 class="midashi02">封入・封緘とは</h2>
		<p>封入は、封筒のなかに同封物（印刷済のDMやチラシ、挨拶状など）を入れる作業を指し、封入後の封筒をのり付けなどで閉じる作業を封緘（ふうかん）と呼びます。封入・封緘まで作業が終わると、あとは封筒に宛名を貼って発送するだけで作業は完了です。</p>
		<p>DM発送においてなくてはならない封入と封緘ですが、一つひとつの作業は単純でも、発送量が多くなると大きな負担になりかねません。</p>
		<p>封入と封緘はセットで行われることが多く、同封物が多くなればなるほど封入には時間がかかります。発送量が多い場合や同封物の種類が多い場合は、どのように封入・封緘するかによって、かかる時間とコストが大きく変わると考えることが大切です。</p>
	</section>


