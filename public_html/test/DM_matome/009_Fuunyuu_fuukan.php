		<h3 id="m02-2" class="midashi03">自社で封入・封緘作業を行うデメリット</h3>
		<p>封入・封緘作業には時間と手間がかかるため、どうしても人件費が必要です。特に送付する書類や部数が数百・数千以上になる場合、作業量は膨大になり、作業スペースも必要になります。</p>
