	<section id="m01">
		<h2 class="midashi02">DMにおけるキャッチコピーの重要性</h2>
		<p>DMには「発送先の選別」「特典」「DMの内容」という重要な3つの要素があります。メディアボックスでは、これら3つの要素の比重を「発送先の選別50％、特典30％、DMの内容20％」だと考えています。</p>
		<p>これら3つの要素のかけ算で、DMの効果は決まります。3つのうちどれか一つでも欠けていると、DMの効果はなくなってしまうので注意が必要です。</p>
		<p>キャッチコピーは、「DMの内容」の一番大切なポイントです。キャッチコピーは顧客が最初に目にする部分なので、キャッチコピーが顧客に合っていないと、最悪の場合DMをまったく読んでもらえない可能性もあります。</p>
		<p><img src="/images/DM_matome/catch_copy_sub1.png" width="1500" height="1000" alt="" decoding="async" loading="lazy"></p>
		<p>DMの効果を上げるためにも、キャッチコピーの重要性を理解し、キャッチコピー作成に注力してみてください。</p>
	</section>


	<section id="m02">
		<h2 class="midashi02">DMのキャッチコピーを作成する前にすべきこと</h2>
		<p><img src="/images/DM_matome/catch_copy_sub2.jpg" width="1980" height="970" alt="" decoding="async" loading="lazy"></p>
		<p>DMの作成は下準備が7割、といわれるほど、下準備は重要です。キャッチコピーも下準備を丁寧に行って、効果アップにつなげます。</p>
		<p>準備では、まず、DMの「顧客」「直接競合」「間接競合」「自社の強み」などに関するブレインストーミングを行います。ブレインストーミングは、複数人でアイデアを自由に出し合う手法です。</p>
		<p>ブレインストーミングで出されたアイデアはすべて書き出し、アイデアをキーワードごとにまとめて、関連性を図示したマインドマップを作成します。ブレインストーミングによって得られたアイデアやキーワードをもとに、DMのキャッチコピーを作成してください。</p>
		<p>また、ブレインストーミングで出された疑問や問題点は、顧客にアンケートをとったり、市場調査を行ったりして解決しておくことも大切です。</p>
		<p>以上の下準備をしっかりと行ったうえで、キャッチコピーを作成し、その効果を計ってください。</p>
	</section>


	<section id="m03">
		<h2 class="midashi02">効果的なキャッチコピーの作り方！ 6つのコツ</h2>
		<p><img src="/images/DM_matome/catch_copy_sub3.png" width="1500" height="1000" alt="" decoding="async" loading="lazy"></p>
		<p>ここでは、キャッチコピーを作る際のコツを6つ解説します。ポイントを一つひとつ押さえて、効果的なDMになるよう工夫してみてください。</p>

		<h3 id="m03-1" class="midashi03">メリットを伝える</h3>
		<p>キャッチコピーでは、顧客がDMを読むメリットをアピールします。顧客がメリットを感じないDMは読んでもらえません。</p>
		<div class="box box--yellow">
		<p class="midashi05-2">◇キャッチコピーの例</p>
		<ul class="list-circle">
			<li>たった○日で○○できる</li>
			<li>あっというまに</li>
			<li>すぐに</li>
			<li>これだけで○○できる○○の法則</li>
		</ul>
		</div>

		<p>以上のような言葉を使いながら、DMのメリットをわかりやすく簡潔に顧客に伝えます。DMにサンプル品や試供品などのプレゼントをつける場合は、プレゼントの内容をキャッチコピーに入れるのもおすすめです。</p>

		<h3 id="m03-2" class="midashi03">自分のことだと思わせる</h3>
		<p>顧客は目にした情報が自分に関係があるかどうかを判断し、その文章を読み進めるかどうかを決めています。</p>
		<p>すべての人を対象とした文章は、誰にも関心を持ってもらえません。ターゲットとなる顧客が自分のことだと思えるよう、ターゲットを絞ったキャッチコピーを作成してください。</p>
		<div class="box box--yellow">
		<p class="midashi05-2">◇キャッチコピーの例</p>
		<ul class="list-circle">
			<li>○○でお困りのあなたへ</li>
			<li>○○代におすすめの○○</li>
			<li>○○の経験はありませんか？</li>
			<li>○○をご愛用の方へ</li>
		</ul>
		</div>

		<p>以上の言葉を参考に具体性を持たせると、DMに興味を持ってもらいやすくなります。</p>

		<h3 id="m03-3" class="midashi03">特別感を出す</h3>
		<p>特定の人に向けたDMであることを強調して特別感を出し、DMの効果を上げる方法もあります。特別感は希少性や限定性、最新性から生まれるため、これらを強調できる表現を使用してみてください。</p>
		<div class="box box--yellow">
		<p class="midashi05-2">◇キャッチコピーの例</p>
		<ul class="list-circle">
			<li>お得意様限定</li>
			<li>○○店限定</li>
			<li>限定○○個</li>
			<li>新発売</li>
		</ul>
		</div>

		<h3 id="m03-4" class="midashi03">読まないと損だと思わせる</h3>
		<p>DMを読まないことで発生するデメリットを強調し、読んでみようと思ってもらうのもおすすめです。</p>
		<div class="box box--yellow">
		<p class="midashi05-2">◇キャッチコピーの例</p>
		<ul class="list-circle">
			<li>今○○しなければ○○</li>
			<li>まだ○○し続けますか？</li>
			<li>○割の人が気付いていない○○</li>
		</ul>
		</div>

		<p>ただし、あまり読まないと損であることを強調し続けると、顧客から悪いイメージを持たれる可能性があります。使用頻度は抑え、効果的なタイミングでのみ使用することをおすすめします。</p>

		<h3 id="m03-5" class="midashi03">意外性のある言葉を使う</h3>
		<p>常識とは異なる表現で興味を引き、その理由を知りたいと思わせる言葉を使ってみてください。顧客の持つ悩みと、悩みへの一般的な対処法以外を提示することで、DMの意外性を強調できます。</p>
		<div class="box box--yellow">
		<p class="midashi05-2">◇キャッチコピーの例</p>
		<ul class="list-circle">
			<li>実は○○</li>
			<li>○○しなくてOK</li>
			<li>○○するだけで○○できる</li>
		</ul>
		</div>

		<h3 id="m03-6" class="midashi03">お客様の声や話題性を活用する</h3>
		<p>第三者からの評価は顧客からの信頼性も高いため、お客様の声を紹介することで安心感を与えることが可能です。</p>
		<p>また、テレビや新聞、ラジオ、SNSなどで有名になった話題は、DMを宣伝するうえでも役に立ちます。話題性をDMの効果アップにつなげてみてください。</p>
		<div class="box box--yellow">
		<p class="midashi05-2">◇キャッチコピーの例</p>
		<ul class="list-circle">
			<li>○○で大人気の</li>
			<li>テレビや雑誌で話題の</li>
			<li>○○な声多数！</li>
			<li>顧客満足度○○％</li>
		</ul>
		</div>
	</section>


