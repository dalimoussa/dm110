	<section id="m05">
		<h2 class="midashi02">キャッチコピーを実際に書く際の注意点</h2>
		<p><img src="/images/DM_matome/catch_copy_sub4.png" width="1500" height="1000" alt="" decoding="async" loading="lazy"></p>
		<p>キャッチコピーを作成する際は、以下の5つの点に注意してみてください。</p>

		<h3 id="m05-1" class="midashi03">① 具体的な数字を入れる</h3>
		<p>数字は顧客の目を引くため、DMの内容を印象づけるのに役立ちます。DMで紹介する商品やサービスのなかで、数字に落とし込めるものがないか探してみてください。</p>

		<h3 id="m05-2" class="midashi03">②「最高」・「たくさん」・「ものすごく」などのあいまいな言葉を使用しない</h3>
		<p>人によって受け取り方が変わる、あいまいな表現の使用は避けます。「とても」「ものすごく」「たくさん」「みんなが」などもあいまいな表現にあたります。ただし「格安」「激安」は例外的に使用可能なので、適宜取り入れてみてください。</p>

		<h3 id="m05-3" class="midashi03">③ お客様にもわかる言葉を使う</h3>
		<p>自分たちが普段使っている専門用語が入っていないかチェックしてください。専門用語は反応率が落ちる原因にもなります。ただし、専門用語がわかるお客様に送るDMの場合は除きます。またお客様が個人の場合、その商品を使う客層や年齢層・性別などを考慮して、言葉を選んでください。</p>

		<h3 id="m05-4" class="midashi03">④ 難しい漢字を入れない</h3>
		<p>DM全体にも言えることですが、難しい漢字を入れないことは重要です。</p>
		<p>読めない漢字があると途中で読むのをやめてしまいます。また、わからないところが3回続く場合も読むのをやめるとも言われています。そのため、スムーズに読めるような配慮が大切です。</p>

		<h3 id="m05-5" class="midashi03">⑤ 言いたいことは1つに絞る</h3>
		<p>知ってほしいことがたくさんあったとしても、伝えることは1つに絞ります。</p>
		<p>複数のことを言ってしまうと、本当に伝えたいことがぼやけてしまいます。一番言いたいことが2つあるいは3つある場合は、キャッチコピーのテストをしてみてください。</p>
	</section>


	<section id="m06">
		<h2 class="midashi02">テストDMでキャッチコピーの効果を計ろう</h2>
		<p>キャッチコピーは初回で成功することは滅多にありません。キャッチコピーだけを変えた2種類のDMを作成してDMテストを行い、キャッチコピーの効果を計るようにしてください。</p>
		<p>1種類のDMから効果を計ろうとすると、得られた結果がキャッチコピーによるものなのか、その他の要素によるものなのかを判別できません。必ず2種類のDMを用意して、DMテストに臨みます。</p>
		<p>DMテストでは、2種類のDMのどこを変えるかが重要です。変更する場所は必ず1ヵ所のみにし、それ以外の部分は変更しないようにしてください。キャッチコピーの効果を計りたい場合は、キャッチコピーのみを変更します。</p>
		<p>DMテストを行った結果、反応率がゼロの場合は重要なデータが取れたと思ってください。なぜなら、そのキャッチコピーの方向性は反応率が悪いということがわかるためです。</p>
		<p>この結果を踏まえ、反応率の悪い部分を削除して良い部分のさらに細分化したものを作り続けることがキャッチコピーで反応率を上げる秘訣です。</p>
		<p>テストDMの手法は、キャッチコピー以外の効果を判定するのにも有用です。以下の項目のうち、効果を計りたい項目に焦点をあててDMを作成してみてください。</p>

		<div class="box box--yellow">
		<ul class="list-circle">
			<li>内容</li>
			<li>事例</li>
			<li>特典</li>
			<li>お客様の声</li>
			<li>フォント大きさ、字間・行間</li>
			<li>紙の大きさ・色・厚さ</li>
			<li>封筒のキャッチ</li>
			<li>写真・イラスト（子供・犬・猫、大きさ、差別化）</li>
			<li>キャプション（写真の下の文章）</li>
			<li>配置</li>
			<li>枠線・下線・付箋</li>
			<li>手書き</li>
			<li>地図の大きさ・内容</li>
			<li>発送の曜日、月末月初月中、曜日などの時期</li>
		</ul>
		</div>
	</section>


