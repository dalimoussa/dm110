	<section id="m01">
		<h2 class="midashi02">DM発送で「クロネコDM便」を利用する際の宛名面のルール</h2>
		<p>「クロネコDM便」は、ヤマト運輸が提供するメール便サービスです。クロネコDM便でDMを発送する場合は、住所や法人名などが記載された専用の宛名ラベルが必要です。</p>
		<p>宛名ラベルは、「ヤマトビジネスメンバーズ」限定の送り状発行システムから、簡単かつ無料で作成できます。</p>
		<p>送り状発行システムを利用する場合、またはDM発送代行会社へ宛名ラベルの作成を依頼する場合は、宛名とバーコードの両方が印刷されたラベル1枚だけで発送可能です。</p>
		<p><img src="/images/DM_matome/DM_atenamen_sub1.png" width="460" height="320" alt="宛名とバーコードの両方が印刷されたラベル" decoding="async" loading="lazy"></p>
		<p>一方、自社で宛名ラベルを作成して、DM発送代行会社に発送を依頼する場合は、宛名とバーコードがそれぞれ印刷された、合計2枚のラベルが必要です。バーコード付きのラベルは、DM発送代行会社が作成します。</p>
		<p><img src="/images/DM_matome/DM_atenamen_sub2.png" width="780" height="350" alt="宛名ラベルとバーコードラベル" decoding="async" loading="lazy"></p>
