	<section id="m02">
		<h2 class="midashi02">DMの宛名面への対応や費用を効率化する方法</h2>
		<p>先述のとおり、クロネコDM便を利用すれば、専用の宛名ラベルを貼るだけでDMを発送可能です。</p>
		<p>特に、A4サイズのハガキDMの場合は、発送部数が3万件以下なら、郵送よりもクロネコDM便のほうが安く発送できます。郵送よりも安価、かつ宛名面を書く手間もかからないため、クロネコDM便の活用がおすすめです。</p>
		<p>また、宛名ラベルの作成に際しては、自社で作成するよりも、DM発送代行会社へ依頼したほうが安くなるケースもあります。自社で作成する場合は、宛名とバーコードの2枚のラベルが必要なため、その分の作業負担が増えることも考慮しなければなりません。</p>
		<p>自社の人件費・作業スペース・リソースなどの観点から、自社で対応するのか、DM発送代行会社に依頼するのかを検討してください。</p>
