	<section id="m03">
		<h2 class="midashi02">DMの効果を高める宛名面の書き方・作り方・貼り方</h2>
		<p class="u-mt0 u-mb0"><img src="/images/DM_matome/DM_atenamen_sub3.png" width="1500" height="1120" alt="DMの効果を高める宛名面の書き方・作り方・貼り方" decoding="async" loading="lazy"></p>
		<p class="u-mt0">ここでは、DMの効果を高めるために、宛名面でできる工夫を紹介します。</p>

		<h3 id="m03-1" class="midashi03">好印象を与えるのは手書き</h3>
		<p>DMの宛名面の書き方で特に効果的なのが、手書きです。</p>
		<p>手書きで書くと「自分のためにひと手間かけてくれた」と感じてもらえるため、印象の良いDMになります。また、画一的なフォントで印刷されたものよりも目立つことから、DMを開封してもらえる確率が高くなります。</p>
		<p>ただし、発送部数が多い場合は手間や時間がかかり、一日に作成できる量が限られてしまいます。他の業務を抱えながら、すべてのDMに手書きで宛名を書くことは現実的ではないため、発送部数に応じて手書き風フォントを活用するのがおすすめです。</p>
		<p><a href="https://test.dm110.jp/DM_matome/tegaki_font/"><img src="/images/DM_matome/btn_tegaki_font.png" width="760" height="126" alt="手書き風フォントの詳細はこちら" decoding="async" loading="lazy"></a></p>

		<h3 id="m03-2" class="midashi03">宛名の住所や法人名は省略しない</h3>
		<p>特にBtoBのDMの場合は、以下のNG例のように、宛名の住所や法人名などを省略しないよう注意が必要です。</p>

		<div class="box box--yellow">
		<p>（NG例）</p>
		<ul class="list-circle">
			<li>都道府県名を省略する</li>
			<li>ビル名や階数を省略する</li>
			<li>部署名を明記しない</li>
			<li>株式会社や有限会社を「（株）」「（有）」と略字で表す</li>
		</ul>
		</div>
		<p>宛名の一部を省略すると、手抜きしている印象を与え、相手に失礼となります。また、例えばビル名や部署名などを省略すると、DMが届かないリスクも高まります。</p>
		<p>これらの理由から、DMの宛名は省略せずに記載し、間違いがないか十分な確認のうえ発送してください。</p>

		<h3 id="m03-3" class="midashi03">商品やターゲットに合うフォントを使う</h3>
		<p>手書きまたは手書き風フォントを使用しない場合は、商品やターゲットの特徴に応じて、適切なフォントを使い分けることが大切です。</p>
		<p>よく使用されるフォントとして、視認性を重視するなら「ゴシック体」、高級感を出すなら「明朝体」などが挙げられます。また、それぞれのフォントを細字にするのか太字にするのかによっても、与える印象が変わります。</p>

		<h3 id="m03-4" class="midashi03">A4ハガキDMは宛名ラベルを貼る位置に注意する</h3>
		<p>クロネコDM便でA4ハガキDMを送る場合、宛名ラベルを貼る位置によって、反応率が大きく変わります。宛名ラベルを貼るのに最もおすすめの位置は「右下」です。</p>
		<p>人の目線の動きには、左から右へ・上から下へ移動する性質があり、A4用紙・横書きの文章を読む際は、まず左上に目線が行くと考えられます。したがって、DMで最も重要なキャッチコピーを左上に置き、優先的に見てもらう必要のない宛名ラベルは、目線が最後に到達する右下に貼ります。</p>
		<p>また、人は違和感を覚えると、その原因を知ろうとする傾向があります。右下に宛名ラベルを貼るケースは少ないため、DMを受け取ったターゲットは違和感を覚え、内容を確認しようとする確率が上がります。この点も、宛名ラベルを右下に貼る効果の一つです。</p>
		<p>詳しくは以下の記事をご覧ください。</p>
		<p><a href="https://test.dm110.jp/DM_atena_label_ichi_best3.html"><img src="/images/DM_matome/btn_DM_atena_label_ichi.png" width="760" height="126" alt="宛名ラベルの貼る位置はこちら" decoding="async" loading="lazy"></a></p>

		<h3 id="m03-5" class="midashi03">透明封筒なら宛名ラベルの位置を工夫する</h3>
		<p>透明封筒を使う場合、中の封入物が見えるため、宛名ラベルの貼り位置を工夫する必要があります。</p>
		<p>以下の注意点やポイントを確認して、貼る位置を決めてください。</p>

		<div class="box box--yellow">
		<ul class="list-circle">
			<li>キャッチコピーが隠れないように宛名ラベルを貼る</li>
			<li>DMを受け取った人は、何が書いてあるのかを最初に知ろうとするため、ターゲットが知りたい情報を隠す位置に宛名ラベルを貼らない。具体的には左上に宛名ラベルを貼るのは控える</li>
			<li>表面を全部見せたいとき、宛名ラベルは裏面に貼る</li>
			<li>透明封筒の宛名ラベルは、通常左上か中央よりやや上あたりの位置に貼ることが多いが、裏面左下に貼るとDMを受け取ったターゲットが違和感を覚え、反応率が上がる場合がある</li>
		</ul>
		</div>

		<h3 id="m03-6" class="midashi03">ターゲットの興味を引くキャッチコピーを工夫する</h3>
		<p>先述のとおり、DMの導入部分となるキャッチコピーは重要です。キャッチコピーでうまく興味を引けないと、その先は読み進めてもらえません。</p>
		<p>効果的なキャッチコピーを書くためのおもなポイントは、次のとおりです。</p>

		<div class="box box--yellow">
		<ul class="list-circle">
			<li>DMの本文からキーワードをピックアップする</li>
			<li>数字を盛り込む</li>
			<li>たくさん・ものすごくなどの曖昧な言葉を使わない</li>
			<li>考えなくても意味がわかる文章にする</li>
			<li>DMを読めばメリットがある・読まないと損だと感じさせる</li>
			<li>ターゲットに向けた特別感のある表現にする</li>
		</ul>
		</div>
		<p>これらの点を意識してキャッチコピーを作成すれば、失敗を避けられます。</p>
