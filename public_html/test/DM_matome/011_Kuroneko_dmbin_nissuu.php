		<h2 class="midashi02">クロネコDM便とは</h2>
		<p>ヤマト運輸のクロネコDM便は、カタログ・パンフレットといった販促物などを全国へ発送できるサービスです。ポストへ投函するため、受領印をいただく必要がありません。また、ヤマト運輸が指定する専用の資材はなく、サイズなどの規定を満たしていれば、梱包材を自由に選択できます。</p>

		<p class="u-mb0">【クロネコDM便の概要】</p>
		<table class="table01">
			<tr><th class="nowrap">利用できる人</th><td>ヤマト運輸と契約した法人や各種団体、個人事業主</td></tr>
			<tr><th>送れるもの</th><td>カタログ、パンフレット、チラシ</td></tr>
			<tr><th>送れないもの</th><td>信書（請求書、手紙など）<br>オークションの落札品、通販での販売品など売買に関わる商品<br>荷受人の希望により出荷されるもの（サンプル品など）</td></tr>
		</table>
		<p>参照：<a href="https://business.kuronekoyamato.co.jp/service/lineup/dmbin/index.html"target="_blank" rel="noopener noreferrer"><cite>ヤマト運輸　クロネコDM便</cite></a></p>

		<p>DM発送代行業者を通じてクロネコDM便を利用すると、クロネコDM便の到着経路と到着状況を確認できるようになります。こちらは、クロネコDM便でのみ利用できる「ひもつけ」という仕組みです。</p>
		<p>ひもつけできるかどうかは代行業者によって異なるため、代行業者を利用する際は事前に確認してください。</p>

