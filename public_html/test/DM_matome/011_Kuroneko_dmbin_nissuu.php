		<h3 id="m01-2" class="midashi03">クロネコDM便の運賃・料金</h3>
		<p>クロネコDM便の発送料金は全国一律で、1通167円が上限となっています。出荷の形態や数量などの条件によって価格は変わるため、発送前に確認が必要です。</p>
		<p>DMなどの発送を宅急便からクロネコDM便に切り替えると、発送費の削減につながる可能性があります。サイズや発送できるものの種類などを確認し、クロネコDM便の利用を検討してください。</p>
