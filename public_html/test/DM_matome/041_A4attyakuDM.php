		<p>梅雨の時期以外の場合は、イベントや顧客の誕生日、セール開始などの2週間前頃に、ターゲットの手元に届くようにするのがおすすめです。夏季休暇や年末年始といった長期休暇は反応率が低下しやすいことから、発送タイミングに注意してください。</p>

		<h3 id="m06-4" class="midashi03">発送費用は複数社に見積もりを取って比較する</h3>
