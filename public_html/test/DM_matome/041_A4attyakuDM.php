		<h3 id="m04-1" class="midashi03">二つ折りのV型圧着</h3>
		<p>圧着DMのなかでもシンプルかつ定番といえるのが、ベースとなる用紙を二つ折りして接着する「V型圧着」タイプです。V型圧着の場合は、開封箇所は1ヵ所です。</p>
		<p>封筒代や封入作業料などのコストを抑えつつ、一通に複数の情報を載せたいときに、V型圧着を活用すると便利です。</p>

		<h3 id="m04-2" class="midashi03">三つ折りのZ型圧着</h3>
		<p>ベースとなる用紙を三つ折りし、中央部分の表と裏の両側を接着する「Z型圧着」タイプもあります。開封箇所は2ヵ所あり、V型圧着よりもたくさんの情報を掲載可能です。</p>
		<p>単に掲載できる情報量が増えるだけでなく、次のようなより高度な用途にも対応できます。</p>
		<div class="box box--yellow">
		<ul class="list-circle">
			<li>宛名面裏・中面・外面などとスペースごとにテイストを分けて、硬い情報と楽しい情報を切り替えて伝える</li>
			<li>広いスペースを活かし、複雑な情報を図解でわかりやすく説明する</li>
		</ul>
		</div>

		<h3 id="m04-3" class="midashi03">往復型</h3>
		<p>往復型は、返信用はがきの付いた圧着DMです。例えば、V型圧着に返信用はがきを付した「往復L型圧着」タイプなどがあります。</p>
		<p>資料請求やアンケート、商品注文のように、ターゲットからの返信が欲しい場合に活用可能です。</p>
	</section>


