		<h2 class="midashi02">DM成功に導く！ABテストの4つのポイント</h2>
		<p>ABテストを実施する際のポイントを、4つ解説します。</p>
		<p><img src="/images/DM_matome/DM_Abtest_sub6.png" width="1500" height="800" alt="ABテストの4つのポイント" decoding="async" loading="lazy"></p>

		<h3 id="m05-1" class="midashi03">小さいテストを何度も繰り返す</h3>
		<p>ABテストをすると、必然的に「良い反応のDM」と「悪い反応のDM」が生まれます。例えば、AパターンとBパターンのDMを50％ずつの割合で発送した場合、極端にいうと半分は「失敗」に終わります。</p>
		<p>上記の理由から、毎回全顧客を対象とするのはコスト的に非効率なため、ABテスト一回当たりの規模を小さくすることが大切です。小規模でのABテストを繰り返すことは、コスト面だけでなく、短期間でより多くのデータを集めるうえでもメリットが大きいといえます。</p>
		<p>具体的に何通のDMを発送すれば良いか判断するために、当社がABテストを実施する際に用いている計算式について、簡略化して紹介します。</p>
		<p>初めてABテストをする場合、DMの最低発送数の基準となるのが、「2.8÷想定反応率」です。想定反応率とは、発送するDMが得られるであろう反応率のことです。</p>
