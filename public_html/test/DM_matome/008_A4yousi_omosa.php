	<section id="m03">
		<h2 class="midashi02">DMで使用する用紙の選び方</h2>
		<p><img src="/images/DM_matome/A4yousi_omosa_sub2.png" width="1500" height="800" alt="上質紙・コート紙・マットコート紙" decoding="async" loading="lazy"></p>
		<p>おもな紙質として、上質紙・コート紙・マットコート紙を紹介しましたが、どの紙質や厚さの用紙をDMで使用するか、迷う場面も多いのではないでしょうか。</p>
		<p>ここでは、DMで使用する用紙の選び方を、3つのポイントに分けて紹介します。</p>

		<h3 id="m03-1" class="midashi03">DMの内容に合わせる</h3>
		<p>DMの内容によって、適した用紙は異なります。<br>以下は、よくあるDMの内容と、それぞれに適した紙質・厚さの一覧です。</p>

		<h4 class="midashi05">一般的なDM</h4>
		<p>原則として上質紙を選びます。厚さは73kgが目安です。</p>

		<h4 class="midashi05">挨拶状</h4>
		<p>なじみのある上質紙を選びます。厚さは90kgが目安です。</p>

		<h4 class="midashi05">ニュースレター</h4>
		<p>写真やイラストなどでの訴求効果を見込んでいない場合は、上質紙を選びます。厚さは73kgが目安です。</p>

		<h4 class="midashi05">プレゼントカタログ</h4>
		<p>写真を用いるケースが多いため、コート紙が適しています。厚さは90kgが目安です。</p>

		<h4 class="midashi05">申込用紙</h4>
		<p>文字を書き込みやすい上質紙を選びます。少し厚めにすると反応率の向上が期待できるため、厚さは110kgが目安です。</p>

		<h3 id="m03-2" class="midashi03">印刷する内容や商品の特徴で決める</h3>
		<p>商品の写真・イラストを美しく見せることで売上アップを期待できるケースでは、仕上がりがきれいなコート紙を選びます。例えば、飲食物や洋服などの写真・イラストを鮮やかに表現できれば、顧客は商品を購入したい気持ちが高まりやすくなります。さらに高級感を出したい場合は、厚めのコート紙を選んでみてください。</p>
		<p>ただし、新聞に折り込むスーパーのチラシのような用途の場合は、薄めのコート紙が適しています。また、文字量の多いDMは、反射の少ないマットコート紙を選ぶと読みやすくなるのでおすすめです。</p>

		<h3 id="m03-3" class="midashi03">カラー印刷で迷う場合はテストして比較する</h3>
		<p>DMをカラー印刷する場合は、上質紙とコート紙に実際にテスト印刷をし、比較してみてください。一般的に、カラー印刷ではコート紙が使われますが、テストしてみると上質紙のほうがしっくりくることがあります。これは、コート紙の発色が良いために、「売り込み感」を強めてしまうからです。</p>
		<p>上質紙でカラー印刷すると、仕上がりの美しさは落ちますが、なじみがあるため安心感を与えます。その際の用紙の厚さは、通常のコピー用紙よりも厚みがあるものがおすすめです。</p>
		<p>なお、上質紙にカラー印刷する際は、以下のポイントに注意してください。この方法をとって反応率を上げているDMに寄付金を募る会社もあります。参考にしてみてください。</p>

		<div class="box box--yellow">
		<ul class="list-circle">
			<li>色数は2種類だけにする（2色印刷）</li>
			<li>色文字は3ヵ所までにする</li>
			<li>下線・斜め文字・マーカー線は使用しない</li>
		</ul>
