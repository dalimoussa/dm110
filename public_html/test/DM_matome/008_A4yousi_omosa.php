		<p>用紙の厚さは、数値が小さいほど薄く大きいほど厚くなるため、先ほどの例を用いると「コート紙90kg」よりも「コート紙135kg」のほうが厚いことになります。DMでは、特に四六判90～135kgの厚さの用紙が多く使われます。</p>
