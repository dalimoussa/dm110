		<h2 class="midashi02">DMでよく使われるA4用紙の基礎知識</h2>
		<p><img src="/images/DM_matome/A4yousi_omosa_sub1.jpg" width="1980" height="1320" alt="" decoding="async" loading="lazy"></p>
		<p>A4用紙の重さは、紙質によって異なります。例えば、A4サイズのコピー用紙の場合は、1枚当たり4～5gです。</p>
		<p>また、紙には水分を含む性質があるため、梅雨の季節など湿度が高い気候では、用紙の水分量が増えて重くなります。</p>
		<p>以下では、用紙のおもな紙質と、用紙の重さと厚さの関係性を詳しく解説します。</p>

		<h3 id="m01-1" class="midashi03">用紙の紙質はおもに3種類</h3>
		<p>用紙のおもな紙質には、上質紙・コート紙・マットコート紙の3種類があります。</p>

		<h4 class="midashi05">上質紙</h4>
		<p>いわゆるコピー用紙のことで、ボールペンなどで文字を書き込みやすい紙質です。A4用紙1枚当たりの重さは、前述のとおり4～5gです。</p>

		<h4 class="midashi05">コート紙</h4>
		<p>上質紙の表面をコーティングしたもので、ツルツルとした光沢感のある紙質です。上質紙に比べて文字を書き込みにくくなりますが、印刷時の仕上がりや発色の美しさは、上質紙よりも優れています。A4用紙1枚当たりの重さは、6～7gです。</p>

		<h4 class="midashi05">マットコート紙</h4>
		<p>コート紙と同様に、上質紙の表面をコーティングしたものですが、弱めの圧力でコーティングされ、光沢が控えめな紙質です。印刷時の鮮やかさはコート紙に劣るものの、落ち着いた印象に仕上がるメリットがあります。A4用紙1枚当たりの重さは、6～7gです。またマットコート紙はボールペンで文字を問題なく書くことができます。</p>

