		<h3 id="m03-4" class="midashi03">＋α：発送数や発送タイミング</h3>
		<p>DMの反応率は、発送数や発送タイミングにも関係します。</p>
		<p>例えば、反応率が0.2％あれば採算が合う商品の場合は、少なくとも2,000件に1件の受注が必要です。そのため、DMは2,000件以上を発送しなければなりません。</p>
		<p>また、ターゲットが「自社商品・サービスを欲しい」と思うタイミングで、DMを届けられることが理想です。</p>
		<p>繰り返しDMを発送する場合は、月に1回から2ヵ月に1回程度のペースが一般的です。顧客から忘れられないようにするためには、最低でも4半期に1回は発送してください。ただし、発送頻度はDMの目的や内容によっても異なり、なかには毎週DMを発送して成果を上げているケースもあります。</p>
		<p>DMの発送頻度や発送タイミングについて、さらに詳しくは以下の記事をご覧ください。</p>
