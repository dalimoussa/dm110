	<section id="m03">
		<h2 class="midashi02">DM（ダイレクトメール）の3つの基本とプラスで知っておいてほしい要素</h2>
		<p>DMには「ターゲット」「特典（オファー）」「クリエイティブ」という重要な3つの要素があります。</p>
		<p><img src="/images/DM_matome/DM_toha_sub2.png" width="1500" height="940" alt="DMの3つの重要な要素" decoding="async" loading="lazy"></p>

		<p>DM発送代行会社としてDM発送に携わってきた経験上、メディアボックスでは、これら3つの重要度の比重を「ターゲット」が全体の50％、「特典（オファー）」が30％、「クリエイティブ」が20％だと考えています。とはいえ、どれか1つでも欠けてしまうと期待する成果は得られないため、各要素のポイントは押さえておく必要があります。</p>
		<p>ここでは、3つの要素をそれぞれ詳しく見ていくとともに、プラスで押さえておくべき「発送数・発送タイミング」についても解説します。</p>

		<h3 id="m03-1" class="midashi03">要素1：ターゲット</h3>
		<p>前述のとおり、3つの要素のうち最も重要になるのが「ターゲット」です。</p>
		<p>一般的に、新規顧客よりも既存顧客のほうが、DMの反応率は高い傾向にあります。実際に既存顧客の反応率が、新規顧客の10～20倍以上となることは少なくありません。</p>
		<p>また、反応率を高めるには、宣伝する商品とターゲットがどれだけマッチしているかも重要です。単に「新規顧客」「既存顧客」と分類するだけでなく、ケースごとにターゲットを絞り込む必要があります。</p>
		<p>DMのターゲットの選定について、さらに詳しくは以下の各記事をご覧ください。</p>
		<p><a href="https://test.dm110.jp/DM_matome/DM_List/"><img src="/images/DM_matome/btn_DM_List.png" width="760" height="126" alt="顧客リストの作成・分析はこちら" decoding="async" loading="lazy"></a></p>
		<p><a href="https://test.dm110.jp/DM_matome/hassousaki/"><img src="/images/DM_matome/btn_hassousaki.png" width="760" height="126" alt="効果的なDMの発送先はこちら" decoding="async" loading="lazy"></a></p>

		<h3 id="m03-2" class="midashi03">要素2：特典（オファー）</h3>
		<p>DMを成功させるためには、魅力的な特典（オファー）もポイントとなります。特典（オファー）には、サンプルのほか、割引券や抽選券など、顧客に喜ばれるものが該当します。</p>
		<p>「このDMを受け取ったあなただけが得られる特典です」といった訴求ができれば、顧客の行動につながりやすくなります。また、厚みのある封入物を入れることで、開封率は上がります。何が入っているのか確認しないまま捨てることは、心理的にハードルが上がるためです。この手段がもたらす効果は、昔も今も変わりません。</p>
		<p>なお、特典（オファー）を付けても反応率が良くないときは、特典（オファー）の価値を3～5倍にしてみてください。例えば、100円分の割引券を入れていたなら、300～500円分の割引券にするといった方法です。</p>
		<p>DMの特典（オファー）について、さらに詳しくは以下の各記事をご覧ください。</p>
		<p><a href="https://test.dm110.jp/DM_matome/DM_offer/"><img src="/images/DM_matome/btn_DM_offer.png" width="760" height="126" alt="DMオファー（特典）の詳細はこちら" decoding="async" loading="lazy"></a></p>
