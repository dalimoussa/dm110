	<section id="m04">
		<h2 class="midashi02">DM（ダイレクトメール）成功へ！ 企画からテストまでを一連で考えよう</h2>
		<p>DMを作成・発送する目的は、「売上をアップさせること」「粗利を上げること」です。「DMを作ること・送ること」が目的にならないよう、企画・作成・発送・テスト（効果測定）を一連で考える必要があります。</p>
		<p><img src="/images/DM_matome/DM_toha_sub3.png" width="1500" height="290" alt="企画・作成・発送・効果測定（テスト）" decoding="async" loading="lazy"></p>

		<h3 id="m04-1" class="midashi03 u-mt0">DM作成は“企画”が7割</h3>
		<p>企画段階で下準備をどれだけできるかによって、DMの反応率や行動喚起率は変動します。DMの企画段階に、DMの一連の流れにかかる時間の半分以上、ときには70％以上を充てることもあります。</p>
		<p>具体的には、商品・サービスの販売担当者を集めて、DM作成に関するアイデアを出し合います。</p>

		<h3 id="m04-2" class="midashi03">効果的なDM作成のヒントは“6W1H”</h3>
		<p>効果的なDMを作ろうと思っても、自分一人や自社内だけで考えていては、なかなか良いアイデアは出てきません。そこで、次のやり方をおすすめします。</p>

		<div class="box box--yellow">
		<ul class="list-decimal">
			<li>DMを作成する</li>
			<li>大きな紙を用意し、DMに関する“6W1H”を書き出す<br>
				※6W1H：Who、What、When、Where、Which、Why、How</li>
			<li>書き出した内容を踏まえ、顧客に質問したいことをまとめる</li>
			<li>DMを持って直接顧客を訪ね、まとめた項目について質問する</li>
			<li>顧客の回答を踏まえ、DMの内容を改善する</li>
		</ul>
		</div>

		<p>このやり方においては、とにかくわかりやすい内容のDMを作ることが大切です。</p>
		<p>効果的なDMの作成方法などについて、さらに詳しくは以下の記事をご覧ください。</p>
		<p><a href="https://test.dm110.jp/DM_matome/DM_kouka/"><img src="/images/DM_matome/btn_DM_kouka.png" width="760" height="126" alt="DMの効果の詳細はこちら" decoding="async" loading="lazy"></a></p>

		<h3 id="m04-3" class="midashi03">DM成功は“テスト”がカギを握る</h3>
		<p>DMにおいて、「これをやれば100％反応率が上がる」といえるものはありません。そのため、DMの反応率を高めるにはテストが不可欠です。</p>
		<p>DMを1種類しか出さないと、そのDMが良いのか悪いのかがわからないため、少なくとも2種類のDMを出して、比較テストをする必要があります。「2種類のDMのうち反応の良かったほうをベースにして、また2種類出す」といったように、テストを繰り返すことでDMの精度が上がり、戦略を立てやすくなります。</p>
		<p>DMのテストの具体的なやり方やポイントについて、詳しくは以下の記事で解説していますので、併せて参考にしてください。</p>
		<p><a href="https://test.dm110.jp/DM_matome/DM_Abtest/"><img src="/images/DM_matome/btn_DM_Abtest.png" width="760" height="126" alt="DMテスト（ABテスト）のコツはこちら" decoding="async" loading="lazy"></a></p>
