		<h3 id="m03-3" class="midashi03">要素3：クリエイティブ</h3>
		<p>DMには、訴求する商品・サービスやターゲットに合った、キャッチコピーとデザインが必要です。</p>
		<p>キャッチコピーは、DMを読み進めてもらえるかどうかのカギとなる部分です。また、DM全体の印象を左右するデザインも、開封率や反応率に大きく影響します。</p>
		<p>どれほど洗練されたクリエイティブでも、ターゲットが反応しなくては意味がありません。「良いクリエイティブ」というのは、売上につながるキャッチコピー・デザインを指します。</p>
		<p>デザインに関しては、一度良いものを作成できれば、それをベースとして長く活用できます。以下の各記事を参考に、DMのキャッチコピーやデザインなどを検討してみてください。</p>
		<p><a href="https://test.dm110.jp/DM_matome/DM_design/"><img src="/images/DM_matome/btn_DM_design.png" width="760" height="126" alt="DMのデザイン・レイアウトのコツはこちら" decoding="async" loading="lazy"></a></p>
